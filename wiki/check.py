#!/usr/bin/env python3
"""Does the wiki still describe the repository it sits in.

A map nobody checks is a map that lies within a month — `CLAUDE.md` had lost
sixteen tests and four directories before this wiki existed, and no reader
could tell, because prose that names a file reads the same whether the file is
there or not. This script turns the wiki's claims into checks:

  map         every path named in MAP.md exists; every `pseudex/` module has an
              entry whose `Uses` / `Used by` / `API` lines EQUAL the real import
              graph and the real top-level names; every test script the map
              names as a direct test really imports the module; every module,
              test and bench script in the tree is on the map.
  claude      the copy of MAP.md embedded in CLAUDE.md between the markers is
              byte-equal to MAP.md (`--sync` rewrites it).
  index       every file in docs/ and research/ has a row in INDEX.md, and every
              row names a file that exists.
  invariants  every rule in INVARIANTS.md names at least one test that exists.
  flows       every `module.function` and `Class.method` named in FLOWS.md is a
              real definition in pseudex/ or licensing/.

`--selftest` runs the classifier over deliberately broken copies of the wiki
and REFUSES to report on the real one unless every break was caught — an
instrument that cannot fail is not an instrument (`e2e/audit_gates.py` learned
that the hard way).

Run from anywhere:  python3 wiki/check.py [--only map,claude] [--sync] [--selftest]
"""
from __future__ import annotations

import argparse
import ast
import re
import sys
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
WIKI = ROOT / "wiki"
PROTO = ROOT / "prototype"
PKG = PROTO / "pseudex"

MAP_BEGIN = "<!-- wiki:MAP:begin -->"
MAP_END = "<!-- wiki:MAP:end -->"

# Paths the map names ON PURPOSE although they are absent from a checkout:
# generated at build, gitignored, or cited as missing. Each entry carries the
# reason so that a future reader can retire it rather than extend it blindly.
KNOWN_ABSENT: dict[str, str] = {
    "pseudex/_release.py": "generated by both Dockerfiles from PSEUDEX_LICENSE_PUBKEY",
    "prototype/pseudex/_release.py": "generated by both Dockerfiles",
    "prototype/*.json": "datasets from make_*.py, gitignored",
    "prototype/*.db*": "SQLite stores, gitignored",
    "prototype/pseudex-vault.key": "generated beside the data, gitignored",
    "prototype/.env.local": "the OpenRouter key, gitignored",
    "deploy/secrets/": "gitignored",
    "storefront/.venv": "gitignored",
    "storefront/storefront.sqlite3": "gitignored",
    "dirty.json": "make_dirty.py output",
    "dataset.json": "make_dataset.py output",
    "~/.cache/pseudex-bench/": "external corpora, outside the repository",
    ".claude/worktrees/": "gitignored — Claude Code agent worktrees, local only",
    ".claude/settings.local.json": "gitignored — per-machine Claude Code settings",
}

PATH_EXTENSIONS = (".py", ".md", ".sh", ".yml", ".yaml", ".json", ".txt", ".tsv", ".html", ".js", ".key")
NON_PATH_TOKENS = {"/mask", "/unmask", "/unmask_chunk", "/unmask_arguments", "/spans", "/health",
                   "/reveal", "/usage", "/status", "/events", "/stats", "/stats.csv", "/reveals",
                   "/subscription", "/diagnostics", "/selfcheck", "/metrics", "/profile",
                   "/v1/lease", "/v1/release", "/v1/tripwire", "/v1/meter", "/v1/usage",
                   "/v1/chat/completions", "/admin/fleet", "/app/ui", "/app/pseudex", "/data",
                   "/v1/attest", "+7", "/healthz"}


@dataclass(frozen=True)
class Finding:
    file: str
    line: int
    message: str

    def render(self) -> str:
        return f"{self.file}:{self.line}: {self.message}"


# ---------------------------------------------------------------- helpers

def read_lines(path: Path) -> list[str]:
    return path.read_text(encoding="utf-8").splitlines()


def is_known_absent(rel: str) -> bool:
    for pattern in KNOWN_ABSENT:
        if pattern.endswith("/") and rel.startswith(pattern):
            return True
        if "*" in pattern:
            regex = "^" + re.escape(pattern).replace(r"\*", ".*") + "$"
            if re.match(regex, rel):
                return True
        if rel == pattern or rel.endswith("/" + pattern):
            return True
    return False


def looks_like_path(token: str) -> bool:
    if token in NON_PATH_TOKENS or token.startswith("http") or " " in token:
        return False
    if token.startswith("~/"):
        return False  # a real reference OUTSIDE the repo (~/.cache, ~/Backups) — not ours to check
    if any(ord(ch) > 0x400 for ch in token):
        return False  # a Cyrillic token (`.ru/.рф/.su`, `-я/-ова`) — never a repo path
    if "@" in token or "…" in token or ":" in token.split("/")[-1] and token.rsplit(":", 1)[-1].isdigit():
        # `@refs/tags/v…` is a git ref; `docs/idea.md:69` is a line reference — strip the :NN and re-test
        token = token.rsplit(":", 1)[0] if (":" in token and token.rsplit(":", 1)[-1].isdigit()) else token
        if "@" in token or "…" in token:
            return False
    if token.startswith(".") and "/" not in token:
        return False  # `.py`, `.dc.html`, `.timer` — an extension named in prose
    if "/" in token and not token.startswith("/"):
        return True
    return token.endswith(PATH_EXTENSIONS) and not token.startswith("--")


def resolve(token: str) -> Path | None:
    """A wiki path is relative to the root, or to prototype/ when a section
    says so; trying both is simpler than tracking the section and cannot
    produce a false red (a false green needs the same name in both places).
    A glob (`make_*.py`, `bench/agentpii{2,3,4}`) resolves when it matches at
    least one file under either base."""
    if "{" in token:
        token = token[: token.index("{")].rstrip("/")
    if "<" in token:
        token = token[: token.index("<")].rstrip("/")
    if ":" in token and token.rsplit(":", 1)[-1].isdigit():
        token = token.rsplit(":", 1)[0]  # `docs/idea.md:69` → `docs/idea.md`
    for base in (ROOT, PROTO):
        if "*" in token:
            if any(base.glob(token)):
                return base
        elif (base / token).exists():
            return base / token
    return None


def strip_glob(token: str) -> str:
    return token


# ---------------------------------------------------------------- real graph

@dataclass(frozen=True)
class ModuleFacts:
    name: str
    uses: frozenset[str]
    public: frozenset[str]


def module_name(path: Path) -> str:
    return "localui" if path.parent.name == "localui" else path.stem


def package_modules() -> list[Path]:
    return [p for p in sorted(PKG.rglob("*.py")) if "__pycache__" not in p.parts and p.stem != "__init__"]


def imports_of(tree: ast.AST, own: str, names: set[str]) -> frozenset[str]:
    used: set[str] = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.ImportFrom) and node.module:
            if node.module.startswith("pseudex."):
                used.add(node.module.split(".")[1])
            elif node.module == "pseudex":
                used.update(alias.name for alias in node.names if alias.name in names)
            elif node.level > 0:
                used.add(node.module.split(".")[0])
        if isinstance(node, ast.Import):
            for alias in node.names:
                if alias.name.startswith("pseudex."):
                    used.add(alias.name.split(".")[1])
    used.discard(own)
    return frozenset(used)


def real_graph() -> dict[str, ModuleFacts]:
    paths = package_modules()
    names = {module_name(p) for p in paths} | {"_release"}
    facts: dict[str, ModuleFacts] = {}
    for p in paths:
        tree = ast.parse(p.read_text(encoding="utf-8"))
        public = frozenset(
            n.name for n in tree.body
            if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)) and not n.name.startswith("_")
        )
        facts[module_name(p)] = ModuleFacts(module_name(p), imports_of(tree, module_name(p), names), public)
    return facts


def reverse_graph(facts: dict[str, ModuleFacts]) -> dict[str, frozenset[str]]:
    rev: dict[str, set[str]] = {m: set() for m in facts}
    for m, f in facts.items():
        for u in f.uses:
            rev.setdefault(u, set()).add(m)
    return {m: frozenset(v) for m, v in rev.items()}


def script_imports_module(script: Path, module: str) -> bool:
    tree = ast.parse(script.read_text(encoding="utf-8"))
    for node in ast.walk(tree):
        if isinstance(node, ast.ImportFrom) and node.module:
            if node.module == f"pseudex.{module}" or node.module.startswith(f"pseudex.{module}."):
                return True
            if node.module == "pseudex" and any(a.name == module for a in node.names):
                return True
        if isinstance(node, ast.Import) and any(a.name == f"pseudex.{module}" for a in node.names):
            return True
    return False


# ---------------------------------------------------------------- MAP parsing

ENTRY_RE = re.compile(r"^#### `pseudex/([\w/]+)\.py`")
FIELD_RE = re.compile(r"^- \*\*(API|Uses|Used by|Tests|Docs):\*\* (.*)$")


@dataclass(frozen=True)
class MapEntry:
    module: str
    line: int
    api: tuple[str, ...]
    uses: frozenset[str]
    used_by: frozenset[str]
    direct_tests: tuple[str, ...]
    via_tests: tuple[str, ...]


def split_names(text: str) -> list[str]:
    text = re.sub(r"\([^)]*\)", "", text)  # drop "(lazy)", "(generated)" notes
    out: list[str] = []
    for chunk in re.split(r"[,;]", text):
        token = chunk.strip().strip("`").strip()
        if token and token != "—":
            out.append(token)
    return out


def parse_map_entries(lines: list[str]) -> list[MapEntry]:
    entries: list[MapEntry] = []
    i = 0
    while i < len(lines):
        m = ENTRY_RE.match(lines[i])
        if not m:
            i += 1
            continue
        module = m.group(1).replace("localui/server", "localui")
        start = i
        fields: dict[str, str] = {}
        i += 1
        while i < len(lines) and not lines[i].startswith("#### ") and not lines[i].startswith("### ") and not lines[i].startswith("---"):
            f = FIELD_RE.match(lines[i])
            if f:
                fields[f.group(1)] = f.group(2)
            i += 1
        api = tuple(n for n in split_names(fields.get("API", "")) if re.fullmatch(r"\w+", n))
        uses_text = fields.get("Uses", "—")
        used_by_text = ""
        if " · **Used by:** " in uses_text:
            uses_text, used_by_text = uses_text.split(" · **Used by:** ", 1)
        uses = frozenset(n for n in split_names(uses_text) if re.fullmatch(r"\w+", n))
        used_by_internal = used_by_text.split(";")[0]
        used_by = frozenset(n for n in split_names(used_by_internal) if re.fullmatch(r"\w+", n) and n != "serve_main")
        tests_text = fields.get("Tests", "")
        if tests_text.startswith("via ") or tests_text.startswith("none direct"):
            direct_text, via_text = "", tests_text
        else:
            direct_text, _, via_text = tests_text.partition(" via ")
        direct_text = direct_text.split(";")[0]
        direct = tuple(n for n in split_names(direct_text) if re.fullmatch(r"[\w./]+", n) and not n.startswith("none"))
        via = tuple(n for n in re.findall(r"(test_\w+|vault_test|bench_masking|profile_\w+|make_\w+|eval_\w+)", via_text))
        entries.append(MapEntry(module, start + 1, api, uses, used_by, direct, via))
    return entries


def locate_script(name: str) -> Path | None:
    name = name.strip("`")
    bare = name[:-3] if name.endswith(".py") else name
    for cand in (PROTO / f"{bare}.py", PROTO / "licensing" / f"{bare}.py", PROTO / "bench" / f"{bare}.py",
                 PROTO / bare, ROOT / bare):
        if cand.exists():
            return cand
    return None


# ---------------------------------------------------------------- checks

def check_paths(name: str, lines: list[str]) -> list[Finding]:
    findings: list[Finding] = []
    for idx, line in enumerate(lines, 1):
        for token in re.findall(r"`([^`]+)`", line):
            token = token.strip()
            if not looks_like_path(token):
                continue
            target = strip_glob(token)
            if not target or is_known_absent(target) or is_known_absent(token):
                continue
            if resolve(target) is None:
                findings.append(Finding(name, idx, f"path does not exist: `{token}`"))
    return findings


def check_map(lines: list[str]) -> list[Finding]:
    findings = check_paths("wiki/MAP.md", lines)
    facts = real_graph()
    rev = reverse_graph(facts)
    entries = parse_map_entries(lines)
    seen = {e.module for e in entries}

    # every module on the map, every map entry a module
    for m in sorted(facts):
        if m not in seen and m not in ("_release",):
            findings.append(Finding("wiki/MAP.md", 1, f"module `pseudex/{m}.py` has no entry in §1"))
    for e in entries:
        if e.module not in facts and e.module != "_release":
            findings.append(Finding("wiki/MAP.md", e.line, f"entry names a module that does not exist: {e.module}"))

    for e in entries:
        if e.module not in facts:
            continue
        f = facts[e.module]
        # public API
        for a in e.api:
            if a not in f.public and a != "main":
                findings.append(Finding("wiki/MAP.md", e.line, f"{e.module}: API names `{a}` which is not a public top-level def"))
        missing_api = sorted(f.public - set(e.api))
        if missing_api and e.api:
            findings.append(Finding("wiki/MAP.md", e.line, f"{e.module}: public names missing from API line: {', '.join(missing_api)}"))
        # uses
        real_uses = set(f.uses)
        if e.uses != real_uses:
            extra = sorted(e.uses - real_uses)
            lacking = sorted(real_uses - e.uses)
            findings.append(Finding("wiki/MAP.md", e.line, f"{e.module}: Uses differs — map has extra {extra or '-'}, lacks {lacking or '-'}"))
        # used by (internal part only)
        real_rev = set(rev.get(e.module, frozenset()))
        # entries written as "every recognizer, …" are prose; only compare when the map lists names
        if e.used_by and e.used_by != real_rev and not any(" " in n for n in e.used_by):
            extra = sorted(e.used_by - real_rev)
            lacking = sorted(real_rev - e.used_by)
            if extra or lacking:
                findings.append(Finding("wiki/MAP.md", e.line, f"{e.module}: Used by differs — map has extra {extra or '-'}, lacks {lacking or '-'}"))
        # direct tests really import the module
        for t in e.direct_tests:
            script = locate_script(t)
            if script is None:
                findings.append(Finding("wiki/MAP.md", e.line, f"{e.module}: test `{t}` not found"))
            elif script.suffix == ".py" and not script_imports_module(script, e.module):
                findings.append(Finding("wiki/MAP.md", e.line, f"{e.module}: `{t}` is listed as a direct test but does not import pseudex.{e.module}"))
        for t in e.via_tests:
            if locate_script(t) is None:
                findings.append(Finding("wiki/MAP.md", e.line, f"{e.module}: via-test `{t}` not found"))

    # every test script in the tree is on the map (§3.3 or §2)
    text = "\n".join(lines)
    for script in sorted(PROTO.glob("test_*.py")) + [PROTO / "vault_test.py"] + sorted((PROTO / "licensing").glob("test_*.py")):
        if f"`{script.name}`" not in text and f"`licensing/{script.name}`" not in text:
            findings.append(Finding("wiki/MAP.md", 1, f"test script not on the map: {script.relative_to(ROOT)}"))
    for script in sorted((PROTO / "bench").glob("*.py")):
        if script.stem in ("__init__",):
            continue
        if f"bench/{script.name}" not in text:
            findings.append(Finding("wiki/MAP.md", 1, f"bench script not on the map: {script.relative_to(ROOT)}"))
    for sub in sorted((PROTO / "bench").iterdir()):
        if sub.is_dir() and sub.name not in ("__pycache__",) and f"`bench/{sub.name}/`" not in text:
            findings.append(Finding("wiki/MAP.md", 1, f"bench package not on the map: {sub.relative_to(ROOT)}/"))
    for script in sorted((PROTO / "e2e").glob("*.py")):
        if script.stem != "__init__" and f"`e2e/{script.name}`" not in text:
            findings.append(Finding("wiki/MAP.md", 1, f"e2e script not on the map: {script.relative_to(ROOT)}"))
    for script in sorted((ROOT / "storefront").glob("test_*.py")):
        if script.stem not in text:
            findings.append(Finding("wiki/MAP.md", 1, f"storefront test not on the map: {script.relative_to(ROOT)}"))
    for entry in sorted((ROOT / "deploy").iterdir()):
        if entry.name.startswith(".") or entry.name in ("certs",):
            continue
        if f"deploy/{entry.name}" not in text:
            findings.append(Finding("wiki/MAP.md", 1, f"deploy entry not on the map: deploy/{entry.name}"))
    for wf in sorted((ROOT / ".github" / "workflows").glob("*.yml")):
        if f"`.github/workflows/{wf.name}`" not in text:
            findings.append(Finding("wiki/MAP.md", 1, f"workflow not on the map: {wf.relative_to(ROOT)}"))
    return findings


def claude_block(claude_lines: list[str]) -> tuple[int, int] | None:
    try:
        b = claude_lines.index(MAP_BEGIN)
        e = claude_lines.index(MAP_END)
    except ValueError:
        return None
    return (b, e) if b < e else None


def check_claude(map_lines: list[str], claude_lines: list[str]) -> list[Finding]:
    block = claude_block(claude_lines)
    if block is None:
        return [Finding("CLAUDE.md", 1, f"markers {MAP_BEGIN} … {MAP_END} not found; the MAP copy is required")]
    b, e = block
    embedded = claude_lines[b + 1:e]
    if embedded != map_lines:
        first = next((i for i, (x, y) in enumerate(zip(embedded, map_lines)) if x != y), min(len(embedded), len(map_lines)))
        return [Finding("CLAUDE.md", b + 2 + first, f"embedded MAP differs from wiki/MAP.md (first difference at MAP.md:{first + 1}); run wiki/check.py --sync")]
    return []


def sync_claude(map_lines: list[str], claude_path: Path) -> None:
    lines = read_lines(claude_path)
    block = claude_block(lines)
    if block is None:
        raise SystemExit(f"{claude_path}: markers not found; add {MAP_BEGIN} and {MAP_END} where the map belongs")
    b, e = block
    new = lines[:b + 1] + map_lines + lines[e:]
    claude_path.write_text("\n".join(new) + "\n", encoding="utf-8")


def check_index(lines: list[str]) -> list[Finding]:
    findings = check_paths("wiki/INDEX.md", lines)
    text = "\n".join(lines)
    for folder in ("docs", "research"):
        for f in sorted((ROOT / folder).glob("*.md")):
            if f"`{folder}/{f.name}`" not in text:
                findings.append(Finding("wiki/INDEX.md", 1, f"no row for {folder}/{f.name}"))
    return findings


PIN_RE = re.compile(r"`((?:licensing/|storefront/|e2e/|wiki/|deploy/|bench/(?:\w+/)*)?(?:test_\w+|vault_test|bench_masking|gates|pack_gates|audit_gates|lint_tests|parity|check)(?:\.py|\.sh)?)")


FN_PIN_RE = re.compile(r"`([\w/]+)` \(((?:`\w+`(?:, )?)+)\)")


def script_defines(script: Path, name: str) -> bool:
    tree = ast.parse(script.read_text(encoding="utf-8"))
    return any(isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef)) and n.name == name for n in ast.walk(tree))


def heading_slugs(lines: list[str]) -> set[str]:
    """GitHub-style anchors of `## ` headings: lower-case, spaces → hyphens."""
    slugs: set[str] = set()
    for line in lines:
        if line.startswith("## "):
            title = line[3:].strip()
            slugs.add(re.sub(r"[^\w\- ]", "", title).lower().replace(" ", "-"))
    return slugs


def locate_pin(pin: str) -> Path | None:
    # A shell test lives where it is named (deploy/test_agent.sh); it has no
    # `.py` twin to search for.
    if pin.endswith(".sh"):
        return (ROOT / pin) if (ROOT / pin).exists() else None
    bare = pin[:-3] if pin.endswith(".py") else pin
    for cand in (PROTO / f"{bare}.py", PROTO / "e2e" / f"{bare}.py", ROOT / f"{bare}.py",
                 PROTO / "licensing" / f"{bare.split('/')[-1]}.py", ROOT / "storefront" / f"{bare.split('/')[-1]}.py",
                 WIKI / f"{bare.split('/')[-1]}.py"):
        if cand.exists():
            return cand
    return None


def check_invariants(lines: list[str], map_lines: list[str]) -> list[Finding]:
    findings = check_paths("wiki/INVARIANTS.md", lines)
    in_backlog = False
    idx = 0
    while idx < len(lines):
        line = lines[idx]
        if line.startswith("## Unpinned"):
            in_backlog = True
        if not in_backlog and line.startswith("- **"):
            start = idx + 1
            block = line
            idx += 1
            while idx < len(lines) and lines[idx].startswith("  "):
                block += " " + lines[idx].strip()
                idx += 1
            # `test_file` (`test_fn`, `test_fn2`) — the functions are checked INSIDE the file,
            # and removed from the block so they are not mistaken for files.
            for file_pin, fns in FN_PIN_RE.findall(block):
                script = locate_pin(file_pin)
                for fn in re.findall(r"`(\w+)`", fns):
                    if script is None or not script_defines(script, fn):
                        findings.append(Finding("wiki/INVARIANTS.md", start, f"`{file_pin}` defines no `{fn}`"))
            block = FN_PIN_RE.sub(lambda m: f"`{m.group(1)}`", block)
            pins = PIN_RE.findall(block)
            if not pins and "UNPINNED" not in block:
                findings.append(Finding("wiki/INVARIANTS.md", start, "rule names no test and is not marked UNPINNED"))
            for pin in pins:
                if locate_pin(pin) is None:
                    findings.append(Finding("wiki/INVARIANTS.md", start, f"pin `{pin}` is not a file in the tree"))
            continue
        idx += 1
    slugs = heading_slugs(lines)
    for n, line in enumerate(map_lines, 1):
        for slug in re.findall(r"INVARIANTS\.md#([\w-]+)", line):
            if slug not in slugs:
                findings.append(Finding("wiki/MAP.md", n, f"anchor INVARIANTS.md#{slug} has no `## ` heading in INVARIANTS.md"))
    return findings


SYMBOL_RE = re.compile(r"\b([A-Za-z_]\w*)\.([a-z_]\w*)\b")
NOT_SYMBOLS = {"e2e", "docs", "bench", "deploy", "storefront", "wiki", "research", "licensing", "prototype",
               "self", "time", "json", "message", "delta", "tool_calls", "response", "anyio", "cache", "context",
               "pseudex", "github", "ru", "ФЗ", "i", "e", "g", "st", "п", "ст"}


def definitions() -> tuple[dict[str, set[str]], dict[str, set[str]]]:
    """module → every def/class name in it (methods included); class → its methods."""
    by_module: dict[str, set[str]] = {}
    by_class: dict[str, set[str]] = {}
    for base, prefix in ((PKG, ""), (PROTO / "licensing", "licensing.")):
        for path in base.rglob("*.py"):
            if "__pycache__" in path.parts:
                continue
            tree = ast.parse(path.read_text(encoding="utf-8"))
            mod = module_name(path) if base == PKG else path.stem
            names = by_module.setdefault(mod, set())
            for node in ast.walk(tree):
                if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                    names.add(node.name)
                if isinstance(node, ast.ClassDef):
                    names.add(node.name)
                    by_class.setdefault(node.name, set()).update(
                        n.name for n in node.body if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef)))
    for path in (PROTO / "serve_main.py", PROTO / "entrypoint.sh"):
        by_module.setdefault(path.stem, set())
    return by_module, by_class


def check_flows(lines: list[str]) -> list[Finding]:
    findings = check_paths("wiki/FLOWS.md", lines)
    by_module, by_class = definitions()
    module_files = {m: True for m in by_module}
    for idx, line in enumerate(lines, 1):
        for owner, member in SYMBOL_RE.findall(line):
            if owner in NOT_SYMBOLS or owner.lower() != owner and owner not in by_class:
                continue
            if owner in by_class:
                if member not in by_class[owner] and member not in by_module.get(owner.lower(), set()):
                    findings.append(Finding("wiki/FLOWS.md", idx, f"`{owner}.{member}` — class {owner} has no such method"))
                continue
            if owner in module_files:
                if member.endswith(("py", "sh", "yml", "md", "json")):
                    continue  # a file name like compose.local.yml, not a symbol
                if member not in by_module[owner] and not member.isupper():
                    findings.append(Finding("wiki/FLOWS.md", idx, f"`{owner}.{member}` — module {owner} defines no `{member}`"))
    return findings


def check_state(lines: list[str]) -> list[Finding]:
    findings = check_paths("wiki/STATE.md", lines)
    ids: dict[str, int] = {}
    for idx, line in enumerate(lines, 1):
        m = re.match(r"### (D-\d{3}) ", line)
        if m:
            if m.group(1) in ids:
                findings.append(Finding("wiki/STATE.md", idx, f"duplicate decision id {m.group(1)} (first at line {ids[m.group(1)]})"))
            ids[m.group(1)] = idx
    # every INVARIANTS.md#anchor referenced from STATE must resolve
    inv = WIKI / "INVARIANTS.md"
    slugs = heading_slugs(read_lines(inv)) if inv.exists() else set()
    for idx, line in enumerate(lines, 1):
        for slug in re.findall(r"INVARIANTS\.md#([\w-]+)", line):
            if slug not in slugs:
                findings.append(Finding("wiki/STATE.md", idx, f"anchor INVARIANTS.md#{slug} has no heading"))
    return findings


# ---------------------------------------------------------------- selftest

def selftest() -> None:
    """Break a copy of the wiki in known ways and demand a red for each."""
    map_lines = read_lines(WIKI / "MAP.md")
    base = check_map(map_lines)
    assert not base, "selftest needs a green MAP.md first:\n" + "\n".join(f.render() for f in base)

    def expect(mutated: list[str], needle: str, label: str) -> None:
        found = [f for f in check_map(mutated) if needle in f.message]
        assert found, f"selftest: {label} was NOT caught"

    # 1. a path that does not exist
    m = [l.replace("`pseudex/normalize.py`", "`pseudex/normalise.py`", 1) for l in map_lines]
    expect(m, "does not exist", "renamed module path")
    # 2. a Uses edge removed. ADDRESSED BY THE ENTRY, NOT BY THE WHOLE LINE: the
    # mutation used to quote `normalize`'s Used-by list verbatim, so the day a new
    # importer appeared (redact) the replacement matched nothing, the copy was not
    # broken at all, and the selftest failed with «was NOT caught» — a red that
    # says the CHECKER is broken while the checker was fine.
    m = list(map_lines)
    for i, line in enumerate(m):
        if line.startswith("- **Uses:**") and "`pseudex/normalize.py`" in "".join(m[max(0, i - 6):i]):
            m[i] = re.sub(r"\*\*Uses:\*\* [^·]+", "**Uses:** — ", line, count=1)
            break
    else:
        raise AssertionError("selftest: no Uses line under pseudex/normalize.py")
    expect(m, "Uses differs", "dropped Uses edge")
    # 3. a fake API name
    m = [l.replace("- **API:** `normalize`", "- **API:** `normalize`, `denormalize`", 1) for l in map_lines]
    expect(m, "not a public top-level def", "fake API name")
    # 4. a direct test that does not import the module
    m = [l.replace("- **Tests:** test_persona_defects, test_product · via detect_all", "- **Tests:** test_tripwire, test_product · via detect_all", 1) for l in map_lines]
    expect(m, "does not import pseudex.normalize", "false direct-test claim")
    # 5. a module entry deleted
    m = [l for l in map_lines if "`pseudex/metering.py`" not in l]
    expect(m, "has no entry", "deleted module entry")
    # 6. a test script dropped from §3.3
    m = [l for l in map_lines if "`test_tripwire.py`" not in l]
    m = [l.replace("test_tripwire", "test_tripwyre") for l in m]
    expect(m, "not on the map", "test script dropped from the table")
    # 7. CLAUDE.md copy drift
    drift = check_claude(map_lines, ["x", MAP_BEGIN, "stale", MAP_END])
    assert drift and "differs" in drift[0].message, "selftest: CLAUDE.md drift was NOT caught"
    assert check_claude(map_lines, ["x"]), "selftest: missing CLAUDE.md markers were NOT caught"
    flows = read_lines(WIKI / "FLOWS.md")
    assert not check_flows(flows), "selftest needs a green FLOWS.md first:\n" + "\n".join(f.render() for f in check_flows(flows))
    broken = [l.replace("normalize.normalize(text)", "normalize.normalise(text)", 1) for l in flows]
    assert any("defines no" in f.message for f in check_flows(broken)), "selftest: fake symbol in FLOWS was NOT caught"
    inv = read_lines(WIKI / "INVARIANTS.md")
    assert not check_invariants(inv, map_lines), "selftest needs a green INVARIANTS.md first"
    broken = [l.replace("Pins: `test_credentials`.", "Pins: `test_credentialz`.", 1) for l in inv]
    assert any("not a file" in f.message for f in check_invariants(broken, map_lines)), "selftest: fake pin was NOT caught"
    broken = [l.replace("Pins: `test_credentials`.", "", 1) for l in inv]
    assert any("names no test" in f.message for f in check_invariants(broken, map_lines)), "selftest: pinless rule was NOT caught"
    broken_map = [l.replace("INVARIANTS.md#address", "INVARIANTS.md#adress", 1) for l in map_lines]
    assert any("has no" in f.message for f in check_invariants(inv, broken_map)), "selftest: dead anchor was NOT caught"
    broken = [l.replace("(`test_addresses`)", "(`test_adresses`)", 1) for l in inv]
    assert any("defines no" in f.message for f in check_invariants(broken, map_lines)), "selftest: fake pin function was NOT caught"
    st = read_lines(WIKI / "STATE.md")
    assert not check_state(st), "selftest needs a green STATE.md first"
    dup = st + ["### D-001 · dup · x"]
    assert any("duplicate" in f.message for f in check_state(dup)), "selftest: duplicate id was NOT caught"
    print("selftest: 14 known breaks, 14 caught")


# ---------------------------------------------------------------- main

def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--only", default="map,flows,state,claude,index,invariants", help="comma-separated subset of checks")
    parser.add_argument("--sync", action="store_true", help="rewrite the MAP block inside CLAUDE.md from wiki/MAP.md")
    parser.add_argument("--selftest", action="store_true", help="prove the checker catches known breaks, then run")
    args = parser.parse_args(argv)

    if args.selftest:
        selftest()

    map_lines = read_lines(WIKI / "MAP.md")
    if args.sync:
        sync_claude(map_lines, ROOT / "CLAUDE.md")
        print("CLAUDE.md: MAP block rewritten from wiki/MAP.md")

    wanted = {s.strip() for s in args.only.split(",")}
    findings: list[Finding] = []
    ran: list[str] = []
    if "map" in wanted:
        findings += check_map(map_lines); ran.append("map")
    if "flows" in wanted:
        p = WIKI / "FLOWS.md"
        findings += check_flows(read_lines(p)) if p.exists() else [Finding("wiki/FLOWS.md", 1, "file missing")]; ran.append("flows")
    if "claude" in wanted:
        findings += check_claude(map_lines, read_lines(ROOT / "CLAUDE.md")); ran.append("claude")
    if "index" in wanted:
        p = WIKI / "INDEX.md"
        findings += check_index(read_lines(p)) if p.exists() else [Finding("wiki/INDEX.md", 1, "file missing")]; ran.append("index")
    if "state" in wanted:
        p = WIKI / "STATE.md"
        findings += check_state(read_lines(p)) if p.exists() else [Finding("wiki/STATE.md", 1, "file missing")]; ran.append("state")
    if "invariants" in wanted:
        p = WIKI / "INVARIANTS.md"
        findings += check_invariants(read_lines(p), map_lines) if p.exists() else [Finding("wiki/INVARIANTS.md", 1, "file missing")]; ran.append("invariants")

    for f in findings:
        print(f.render())
    print(f"wiki/check.py: {', '.join(ran)} — {len(findings)} finding(s)")
    return 1 if findings else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
