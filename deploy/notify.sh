#!/bin/sh
# Один канал тревоги на всё: выкатку, сторожа и бэкап.
#
# ПОЧЕМУ ОТДЕЛЬНЫЙ ФАЙЛ, А НЕ ТРИ CURL'А. Отправка — единственное место, где
# ошибка молчалива по своей природе: если она сломается, всё остальное
# продолжит работать и никто об этом не узнает. Поэтому она одна, и её отказ
# печатается в лог контейнера, где его увидит `docker logs`.
#
# ТЕЛЕГРАМ, А НЕ ПОЧТА, — по решению от 20.08.2026 (docs/decisions.md):
# письмо о падении в три ночи читается утром, сообщение в канал — сразу.
#
# usage:  notify.sh LEVEL "заголовок" "тело"
#         LEVEL = info | warn | crit
set -eu

LEVEL="${1:-info}"
TITLE="${2:-}"
BODY="${3:-}"

if [ -z "${PSEUDEX_TG_TOKEN:-}" ] || [ -z "${PSEUDEX_TG_CHAT:-}" ]; then
    # НЕ молча. Ненастроенная тревога — это отсутствующая тревога, и узнать об
    # этом надо в тот момент, когда она впервые понадобилась, а не после.
    echo "notify: PSEUDEX_TG_TOKEN/PSEUDEX_TG_CHAT не заданы — [$LEVEL] $TITLE: $BODY" >&2
    exit 0
fi

case "$LEVEL" in
    crit) MARK="🔴" ;;
    warn) MARK="🟡" ;;
    *)    MARK="⚪️" ;;
esac

HOST="${PSEUDEX_ENV_NAME:-$(hostname)}"

# HTML, а не Markdown: тело почти всегда содержит вывод команды со скобками,
# подчёркиваниями и звёздочками, и Markdown на нём разваливается — сообщение
# либо не отправляется, либо приходит покорёженным ровно в тот момент, когда
# его читают внимательнее всего.
escape() { printf '%s' "$1" | sed -e 's/&/\&amp;/g' -e 's/</\&lt;/g' -e 's/>/\&gt;/g'; }

# Telegram отвергает текст длиннее 4096 символов, а тело тревоги — это почти
# всегда вывод команды, который свою длину не выбирает. Обрезаем ЗДЕСЬ, потому
# что альтернатива — 400 и потерянная тревога: усечённая крит-тревога доходит,
# полная не доходит вовсе. Проверено вживую 29.08.2026: 5000 символов ->
# {"error_code":400,"description":"message is too long"}.
#
# Режем ПО ЦЕЛЫМ СТРОКАМ, а не по байтам: `head -c` разрубает многобайтовый
# символ, и битый UTF-8 — это снова отказ. По строкам граница всегда законная.
# Бюджет 2600 безопасен при любом прочтении `length` (байты или символы) — в
# обоих случаях с запасом под лимит, и остаток покрывает заголовок и хост.
trim() {
    printf '%s\n' "$1" | awk '
        { n += length($0) + 1
          if (n > 2600) { print "…"; print "обрезано, целиком — в логе контейнера"; exit }
          print }'
}


TEXT="$MARK <b>$(escape "$TITLE")</b>
<i>$(escape "$HOST")</i>

<pre>$(escape "$(trim "$BODY")")</pre>"

# Тревога не должна валить того, кто её послал: сторож обязан продолжить обход,
# даже если Телеграм недоступен. Отказ печатается и проглатывается.
#
# ПРОВЕРЯЕТСЯ КОД ОТВЕТА, А НЕ КОД ВОЗВРАТА curl. Здесь стояло `if ! curl`, и оно
# не срабатывало НИКОГДА: без `--fail` curl считает HTTP 400 успешной передачей и
# возвращает 0. Telegram отвечает 400 на любую сломанную разметку, а тело тревоги
# почти всегда содержит вывод команды — то есть сообщение терялось молча ровно в
# том случае, ради которого отправка вынесена в отдельный файл. Проверено вживую
# 29.08.2026: {"ok":false,"error_code":400,"description":"can\'t parse entities…"}
# при коде возврата curl = 0.
#
# Описание печатается целиком: «Unclosed start tag at byte offset 42» — это то, с
# чем человек может что-то сделать, в отличие от «не удалось отправить».
RESP="$(curl -sS --max-time 15 -w '\n%{http_code}' \
        "https://api.telegram.org/bot${PSEUDEX_TG_TOKEN}/sendMessage" \
        -d "chat_id=${PSEUDEX_TG_CHAT}" \
        -d "parse_mode=HTML" \
        --data-urlencode "text=${TEXT}")" || RESP='сеть недоступна
000'

# Последняя строка — код, всё выше — тело. Токен сюда не попадает: свои ошибки
# curl пишет в stderr, и мы их не переизлучаем, а Telegram URL в ответе не несёт.
if [ "$(printf '%s' "$RESP" | tail -n 1)" != "200" ]; then
    echo "notify: НЕ ДОСТАВЛЕНО [$LEVEL] $TITLE — $(printf '%s' "$RESP" | tr '\n' ' ' | head -c 400)" >&2
fi
