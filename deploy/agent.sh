#!/bin/sh
# Выкатка, которую хост делает САМ.
#
# ПОЧЕМУ ХОСТ ЗАБИРАЕТ, А НЕ CI ПРИХОДИТ. Вариант «GitHub Actions заходит по
# SSH» привычнее и виден в логах Actions — и требует двух вещей, которые для
# продукта про приватность плохой размен: долгоживущего ключа в GitHub, дающего
# root на боевой машине, и открытого наружу входящего SSH. Здесь наружу не
# открыто ничего: машина сама раз в минуту смотрит в git и в реестр.
#
# ЧТО ДЕЛАЕТ ЭТОТ ФАЙЛ, ЧЕГО НЕ ДЕЛАЕТ `docker compose pull`:
#
#   1. ПРОВЕРЯЕТ ПОДПИСЬ до того, как что-либо остановит. Реестр — не
#      доверенная сторона; подпись существует ровно затем, чтобы его не
#      приходилось считать таковой, и проверка тут единственное место, где это
#      имеет силу. Не сошлась — не выкатываем и кричим.
#   2. ЖДЁТ ЗДОРОВЬЯ и ОТКАТЫВАЕТСЯ САМ. Обновление, после которого сервис не
#      поднялся, чинится за 40 секунд без человека. Это и есть разница между
#      «автономно» и «автоматически»: автоматическое умеет только ломать
#      быстрее.
#   3. Держит замок. Таймер раз в минуту и выкатка длиной в три — это два
#      одновременных `compose up`, если не мешать.
#
# Источник правды — ТЕГ В GIT. Из него же берётся compose-файл, поэтому
# описание стенда и версии образов не могут разъехаться: они переезжают одним
# движением. Откат — `git tag -f` на прежний коммит или PSEUDEX_PIN.
set -eu

HERE="$(cd "$(dirname "$0")" && pwd)"
REPO="$(cd "$HERE/.." && pwd)"
STATE="${PSEUDEX_AGENT_STATE:-$HERE/.deployed}"
LOCK="${PSEUDEX_AGENT_LOCK:-$HERE/.agent.lock}"
REGISTRY="${REGISTRY:-cr.yandex/pseudex}"
notify() { "$HERE/notify.sh" "$@" || true; }

# Одновременных выкаток не бывает. `flock` без ожидания: если предыдущая ещё
# идёт, эта просто уходит — через минуту таймер придёт снова.
exec 9>"$LOCK"
flock -n 9 || { echo "agent: предыдущая выкатка ещё идёт"; exit 0; }

cd "$REPO"
git fetch --tags --quiet --force

# PSEUDEX_PIN закрепляет версию и выключает автовыкатку. Нужен ровно в тот
# момент, когда что-то пошло не так и нужно время подумать, не воюя с агентом,
# который упорно возвращает «правильную» версию.
# `v[0-9]*`, НЕ `v*`: старый тег `veilgate-final` начинается с v и сортировался
# выше любой версии — агент выкатил бы его первым же обходом.
WANT="${PSEUDEX_PIN:-$(git tag -l 'v[0-9]*' --sort=-v:refname | head -1)}"
[ -n "$WANT" ] || { echo "agent: тегов вида v* нет"; exit 0; }

HAVE="$(cat "$STATE" 2>/dev/null || echo "")"
[ "$WANT" = "$HAVE" ] && exit 0

VERSION="${WANT#v}"
echo "agent: $HAVE -> $WANT"

# ── подпись, ДО остановки чего бы то ни было ────────────────────────────────
# Проверяется каждый образ, включая клиентский: он не крутится у нас, но его
# дайджест — то, что мы показываем клиенту в инструкции, и расхождение здесь
# означает, что мы собираемся раздать неподтверждённые байты.
# ЛИЧНОСТЬ ПОДПИСАНТА ОБЯЗАТЕЛЬНА, И БЕЗ НЕЁ АГЕНТ НЕ РАБОТАЕТ. Здесь стояло
# `${COSIGN_IDENTITY_REGEXP:-.*}` — и по коду cosign (`pkg/cosign/verify.go`,
# CheckCertificatePolicy) регексп `.*` делает проверку личности тавтологией:
# остаются цепочка до Fulcio, SCT и Rekor, но публичный Fulcio выдаёт
# сертификат ЛЮБОМУ workflow ЛЮБОГО репозитория GitHub, и любая такая подпись
# проходила. То есть агент доверял реестру ровно так, как заявлял, что не
# доверяет, — единственной границей была учётка реестра. Это Watchtower с
# лишним шагом.
#
# ТЕГ В IDENTITY — НЕ ПЕДАНТИЗМ. `publish` запускается и вручную:
# `gh workflow run release.yml --ref main -f publish=true` любым write-аккаунтом
# подпишет образ личностью `…/release.yml@refs/heads/main`. Только якорь
# `@refs/tags/v<число>.<число>.<число>$` отсекает это на хосте.
#
# ПУСТАЯ ПЕРЕМЕННАЯ — ОТКАЗ, А НЕ УМОЛЧАНИЕ. Умолчание здесь может быть только
# слабее заданного, а слабее «любой» не бывает.
IDENTITY="${COSIGN_IDENTITY_REGEXP:-}"
ISSUER="${COSIGN_ISSUER_REGEXP:-}"
if [ -z "$IDENTITY" ] || [ -z "$ISSUER" ]; then
    notify crit "Выкатка ОТМЕНЕНА: не задано, кому верить" \
        "В deploy/.env нет COSIGN_IDENTITY_REGEXP или COSIGN_ISSUER_REGEXP.
Без них проверка подписи пропускает ЛЮБУЮ keyless-подпись — чужой аккаунт
GitHub подписал бы образ, и агент его выкатил бы. Ничего не остановлено,
работает $HAVE. Образец значений — в deploy/.env.example."
    exit 1
fi
case "$IDENTITY" in
    *'@refs/tags/'*) : ;;
    *)
        notify crit "Выкатка ОТМЕНЕНА: identity не привязана к тегу" \
            "COSIGN_IDENTITY_REGEXP=$IDENTITY
Без '@refs/tags/' в якоре подпись из ветки main через ручной dispatch
прошла бы как релизная. Ничего не остановлено, работает $HAVE."
        exit 1 ;;
esac

for name in pseudex pseudex-licensing pseudex-storefront pseudex-backup pseudex-supportbot; do
    REF="${REGISTRY}/${name}:${VERSION}"
    # ОБРАЗА ЕЩЁ НЕТ — ЭТО НЕ «ПОДПИСЬ НЕ СОШЛАСЬ». Тег появляется сразу, образы
    # — через ~50 минут сборки, и всё это время агент раз в минуту приходил
    # сюда и слал crit-тревогу «подпись не сошлась». Час ложных тревог на
    # каждый релиз, и настоящая среди них потерялась бы. Отсутствие манифеста
    # — тихий выход: следующий обход через минуту.
    if ! docker manifest inspect "$REF" >/dev/null 2>&1; then
        echo "agent: $REF ещё не опубликован — жду"
        exit 0
    fi
    if ! cosign verify "$REF" \
            --certificate-identity-regexp "$IDENTITY" \
            --certificate-oidc-issuer-regexp "$ISSUER" >/dev/null 2>&1; then
        notify crit "Выкатка ОТМЕНЕНА: подпись не сошлась" \
            "$REF
Ничего не остановлено, работает $HAVE.
Реестру мы не доверяем — подпись для того и нужна. Разберитесь, откуда взялся
этот образ, прежде чем снимать проверку."
        exit 1
    fi
done

notify info "Выкатка $HAVE → $WANT" "Подписи проверены, поднимаю."

# ── выкатка ────────────────────────────────────────────────────────────────
# Прежний тег запоминается ДО checkout: после него `git describe` покажет уже
# новый, и откатываться будет некуда.
PREV="${HAVE:-$(git describe --tags --abbrev=0 HEAD 2>/dev/null || echo "")}"
git checkout --quiet "$WANT"

# ЗДОРОВЬЕ ЖДЁТ САМ COMPOSE, И ЭТО НЕ ЗАМЕНА НАШЕГО ЦИКЛА, А ЕГО ПОЧИНКА. Ниже
# стояла своя `healthy()`: `docker compose ps` + awk на `unhealthy`, и она
# возвращала успех на ПЕРВОМ тике, где `unhealthy` нет. А у пересозданного
# сервиса первые секунды здоровье равно `starting` — awk его чистым и считал.
# Измерено: сервис, который НИКОГДА не становится здоровым, старая проверка
# объявляла здоровым через 2 секунды со статусом «starting running»;
# `--wait` дождался конца start_period и упал на 24-й: «is unhealthy». Откат,
# который срабатывает только на отказ в первые две секунды, — это откат,
# которого нет.
#
# `--wait` (docker/compose start.go) ждёт `healthy` у сервисов с healthcheck и
# `running` у сервисов без него; `exited` и `unhealthy` — ошибка; по таймауту
# — ошибка. Код возврата — это и есть вердикт, и он берётся напрямую.
#
# 240 СЕКУНД — БОЛЬШЕ САМОГО ДЛИННОГО start_period, И ЭТО ПРОВЕРЯЕТСЯ НИЖЕ.
# Самый долгий — `billing`, 180 с: его здоровье означает «первый цикл прошёл»,
# а циклу надо дождаться Postgres и лицензионного сервера. Таймаут короче
# start_period — это ложный откат на каждой выкатке, и первая версия этой
# строки (120) была ровно такой. Больше — лишние минуты простоя на настоящем
# отказе, поэтому не 600.
WAIT_TIMEOUT=240
LONGEST_START="$(grep -oE 'start_period: *[0-9]+' "$HERE/compose.yml" | grep -oE '[0-9]+' | sort -n | tail -1)"
if [ "${LONGEST_START:-0}" -ge "$WAIT_TIMEOUT" ]; then
    notify crit "Агент: таймаут ожидания короче start_period" \
        "WAIT_TIMEOUT=$WAIT_TIMEOUT, а в compose есть start_period ${LONGEST_START}s.
Выкатка откатывалась бы ложно. Поднимите WAIT_TIMEOUT в agent.sh."
    exit 1
fi
# PSEUDEX_CONF_REV — ДЕРЕВО `deploy/` ТОГО ТЕГА, ЧТО ВЫКАТЫВАЕТСЯ. Compose
# решает «пересоздавать ли контейнер» по хешу описания сервиса, и содержимое
# файла за bind-mount в этот хеш не входит: тег, поменявший только Caddyfile
# или alerts.yml, оставлял контейнеры на старом файле, а `up -d` отвечал
# «нечего делать». Сервисы, монтирующие файлы из чекаута, несут эту
# переменную в environment (compose.yml, `x-conf-rev`), и смена дерева их
# пересоздаёт. Откат передаёт дерево ПРЕЖНЕГО тега тем же путём.
deploy() {
    conf_rev="$(git rev-parse "${1}:deploy")" || return 1
    VERSION="${1#v}" PSEUDEX_CONF_REV="$conf_rev" \
        docker compose -f "$HERE/compose.yml" pull --quiet
    VERSION="${1#v}" PSEUDEX_CONF_REV="$conf_rev" \
        docker compose -f "$HERE/compose.yml" up -d --remove-orphans \
        --wait --wait-timeout "$WAIT_TIMEOUT"
}


# КОД ВОЗВРАТА БЕРЁТСЯ У `deploy`, А НЕ У КОНВЕЙЕРА. Здесь стояло
# `if ! deploy … | tail -20`, и оно не срабатывало никогда: в конвейере код
# возвращает ПОСЛЕДНЯЯ команда, а `tail` успешен всегда. `pipefail` не спасает —
# POSIX sh его не знает, а dash не поддерживает вовсе.
#
# Чем это кончалось. Провалившийся `pull` (реестр недоступен, тега нет, ключ
# протух) читался как успех, и дальше решала `healthy`. Если старые контейнеры
# при этом продолжали работать — а они продолжают, `up -d` их не трогал, — то
# healthy отвечала «здоровы», агент писал НОВУЮ версию в файл состояния и
# рапортовал «Выкатка готова». Прод остаётся на старой, состояние врёт, и
# следующий обход видит HAVE == WANT и больше не пробует. Тихий отказ ровно
# того вида, ради устранения которого этот файл написан.
#
# Логи выкатки идут в журнал агента, а НЕ в тревогу: тут действует то же
# правило, что ниже — наружу уходит факт и место, читать человек идёт сам.
DEPLOY_LOG="${TMPDIR:-/tmp}/pseudex-deploy.$$"
if ! deploy "$WANT" >"$DEPLOY_LOG" 2>&1; then
    tail -20 "$DEPLOY_LOG" >&2
    # ПРИЧИНА — ОДНОЙ СТРОКОЙ В ТРЕВОГУ, остальное в журнале. `--wait` называет
    # нездоровый сервис сам («container X is unhealthy», «not healthy after»);
    # без этой строки человек в три ночи открывал бы journalctl, чтобы узнать
    # ЧТО именно не поднялось, а не только ЧТО откатились.
    WHY="$(grep -oE 'container [^ ]+ (is unhealthy|exited)|not healthy after [0-9]+s|timeout' "$DEPLOY_LOG" | head -1)"
    rm -f "$DEPLOY_LOG"
    notify crit "Выкатка $WANT не удалась" \
        "${WHY:-причина в журнале агента}
Откатываюсь на $PREV. Логи контейнеров не пересылаю — там могут быть данные
клиента. journalctl -u pseudex-agent -n 50"
    if [ -n "$PREV" ]; then
        git checkout --quiet "$PREV"
        # ОТКАТ ТОЖЕ ЖДЁТ ЗДОРОВЬЯ, и его исход называется вслух. Молчаливый
        # откат, который сам не поднялся, — худший из вариантов: тревога
        # сказала «откатился», а прод стоит.
        if deploy "$PREV" >/dev/null 2>&1; then
            printf '%s' "$PREV" > "$STATE"
            notify warn "Откат на $PREV выполнен" "Продакшен работает на прежней версии."
        else
            notify crit "ОТКАТ НА $PREV НЕ ПОДНЯЛСЯ" \
                "Ни новая, ни прежняя версия не здоровы. Нужен человек:
docker compose -f $HERE/compose.yml ps"
        fi
    fi
    exit 1
fi
rm -f "$DEPLOY_LOG"

printf '%s' "$WANT" > "$STATE"
notify info "Выкатка $WANT готова" "Все сервисы здоровы."

# Старые образы копятся быстрее, чем кончается диск, но кончается именно диск —
# и это единственный отказ из docs/operations.md §2, который останавливает всех.
docker image prune -af --filter "until=168h" >/dev/null 2>&1 || true
