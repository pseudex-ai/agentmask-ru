#!/usr/bin/env bash
# Что о домене думает ВНЕШНИЙ мир, а не панель регистратора.
#
# ЗАЧЕМ ОТДЕЛЬНЫЙ СКРИПТ. Панель показывает, что записано у регистратора;
# почта и браузеры видят то, что разошлось по резолверам, а это разные вещи и
# расходятся они на часы. «У меня в панели всё правильно» — самая частая фраза
# в такой отладке, и она ничего не значит.
#
# Спрашиваем ДВА резолвера: один публичный и один яндексовый. Если они
# расходятся — запись ещё в пути, и ждать надо, а не чинить.
#
#   bash deploy/check-dns.sh pseudex.ru
set -u
DOMAIN="${1:-pseudex.ru}"

ask() { dig +short @"$2" "$3" "$1" 2>/dev/null | sed 's/^/      /'; }

echo "── $DOMAIN ──────────────────────────────────────────────"
for pair in "8.8.8.8 Google" "77.88.8.8 Яндекс"; do
    set -- $pair
    echo
    echo "  через $2 ($1):"
    echo "    NS:"; ask "$DOMAIN" "$1" NS
    echo "    A:";  ask "$DOMAIN" "$1" A
    echo "    MX:"; ask "$DOMAIN" "$1" MX
    echo "    TXT:"; ask "$DOMAIN" "$1" TXT
    echo "    DKIM:"; ask "mail._domainkey.$DOMAIN" "$1" TXT
    echo "    DMARC:"; ask "_dmarc.$DOMAIN" "$1" TXT
done

echo
echo "──────────────────────────────────────────────────────────"
echo "  Пусто под NS у обоих — делегирование ещё не разошлось."
echo "  Разные ответы у двух резолверов — запись в пути, ждите."
echo "  Одинаковые и ожидаемые — можно нажимать «Проверить» у Яндекса."
