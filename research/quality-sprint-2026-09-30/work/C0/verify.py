"""C0 — reproducible verification runner. Produces checks.log and RED.log.

Every check prints `CHECK <id> ... EXIT=<n>`; the process exits non-zero if any
check fails. Nothing outside work/C0/ is written. Engine/benchmark/scorer/wiki/git
are read only; git is invoked only with read-only subcommands.

Run:
    PYTHONDONTWRITEBYTECODE=1 prototype/.venv/bin/python \
      research/quality-sprint-2026-09-30/work/C0/verify.py
"""

from __future__ import annotations

import hashlib
import json
import os
import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = Path("/Users/igor/Projects/Obscura-hop-audit")
PY = REPO / "prototype/.venv/bin/python"
PIN = "0bfda2363ef1a1d552e2ac093129b1026a86ad68"

ENGINE_FILES = [
    "prototype/licensing/assets_source.py",
    "prototype/pseudex/structured.py",
    "prototype/pseudex/assets.py",
    "prototype/pseudex/credentials.py",
    "prototype/pseudex/vault.py",
    "prototype/pseudex/audit.py",
    "prototype/pseudex/detect_all.py",
    "prototype/testkit.py",
]

FIXED_IDS = {
    "RED-1", "RED-2", "RED-3", "RED-4", "RED-5", "RED-6", "RED-7", "RED-8", "RED-9",
    "NEG-1", "NEG-2", "CTRL-1", "CTRL-2",
}

lines: list[str] = []
failures: list[str] = []


def log(msg: str) -> None:
    lines.append(msg)
    print(msg)


def sha256(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def check(cid: str, ok: bool, detail: str) -> None:
    state = "OK" if ok else "FAIL"
    log(f"CHECK {cid} {state} EXIT={0 if ok else 1} :: {detail}")
    if not ok:
        failures.append(cid)


def run(cid: str, argv: list[str], cwd: Path, logname: str | None = None) -> tuple[int, str]:
    proc = subprocess.run(argv, cwd=str(cwd), capture_output=True, text=True,
                          env={**os.environ, "PYTHONDONTWRITEBYTECODE": "1"})
    out = proc.stdout + (("\n[stderr]\n" + proc.stderr) if proc.stderr.strip() else "")
    if logname:
        (HERE / logname).write_text(out + f"\nEXIT={proc.returncode}\n", encoding="utf-8")
    log(f"RUN {cid} EXIT={proc.returncode} :: {' '.join(argv)}")
    return proc.returncode, out


def main() -> int:
    log("# C0 checks.log — reproducible verification, all commands and exit codes")
    log(f"# repo {REPO}")
    log(f"# generated by work/C0/verify.py; PYTHONDONTWRITEBYTECODE=1")
    log("")

    # --- C1: the pinned product source is untouched by this task -------------
    diff = subprocess.run(["git", "diff", "--name-only", PIN, "--", *ENGINE_FILES],
                          cwd=str(REPO), capture_output=True, text=True)
    check("C1", diff.returncode == 0 and diff.stdout.strip() == "",
          f"git diff {PIN[:8]} -- <8 engine files> is empty (stdout={diff.stdout.strip()!r})")

    # --- C2: recorded source hashes recompute --------------------------------
    inputs = json.loads((HERE / "INPUTS.json").read_text(encoding="utf-8"))
    mismatches = []
    for entry in inputs["sources_read_only_all_sha256_verified"]:
        p = REPO / entry["path"]
        if not p.is_file():
            mismatches.append(f"MISSING {entry['path']}")
        elif sha256(p) != entry["sha256"]:
            mismatches.append(f"CHANGED {entry['path']}")
    check("C2", not mismatches,
          f"{len(inputs['sources_read_only_all_sha256_verified'])} recorded source hashes recomputed; mismatches={mismatches}")

    # --- C3: fixture generator self-check (its OWN tables only) --------------
    rc, out = run("C3", [str(PY), str(HERE / "gen_fixtures.py"), "--check"], REPO)
    ok_c3 = rc == 0 and '"self_check_ok": true' in out
    check("C3", ok_c3, "gen_fixtures.py --check exit 0 and self_check_ok=true (validates ONLY its own syntax tables)")

    # --- C4: engine-facing RED probe, regenerating PROBE-FACTS.json + RED.log -
    rc, out = run("C4", [str(PY), str(HERE / "probe_engine.py"),
                         "--out", str(HERE / "PROBE-FACTS.json")], REPO / "prototype",
                  logname="RED.log")
    facts = json.loads((HERE / "PROBE-FACTS.json").read_text(encoding="utf-8"))
    c = facts["counts"]
    ok_c4 = (rc == 0 and c["red_confirmed"] == 9 and c["red_total"] == 9
             and c["controls_held"] == c["controls_total"] == 4
             and c["positive_fixtures_protected"] == 0
             and c["hard_negatives_open"] == c["hard_negatives_total"] == 10
             and facts["suite_verdict"].startswith("NOT_A_SUITE_PASS"))
    check("C4", ok_c4,
          f"probe exit 0; red_confirmed={c['red_confirmed']}/{c['red_total']}; "
          f"controls_held={c['controls_held']}/{c['controls_total']}; "
          f"positive_protected={c['positive_fixtures_protected']}/{c['positive_fixtures_total']}; "
          f"hard_negatives_open={c['hard_negatives_open']}/{c['hard_negatives_total']}; "
          f"verdict={facts['suite_verdict']!r}")

    # --- C5: probe property ids are exactly the declared set -----------------
    pids = [p["property_id"] for p in facts["properties"]]
    check("C5", set(pids) == FIXED_IDS and len(pids) == len(set(pids)),
          f"{len(pids)} property ids, unique, equal to the declared set; got={sorted(pids)}")

    # --- C6: fixtures <-> probe consistency ----------------------------------
    fixtures = json.loads((HERE / "FIXTURES.json").read_text(encoding="utf-8"))
    fx_ids = {f["fixture_id"] for f in fixtures["fixtures"]}
    probed_ids = {f["fixture_id"] for f in facts["per_fixture"]}
    check("C6", fx_ids == probed_ids and len(fx_ids) == 32,
          f"FIXTURES.json and PROBE-FACTS.json cover the same {len(fx_ids)} fixture ids")

    # --- C7: every RED is an expected failing property, not a suite pass ------
    reds = [p for p in facts["properties"] if p["kind"] == "RED_intentional"]
    ok_c7 = all(p["status"] == "RED_CONFIRMED" for p in reds) and all(
        p["engine_change_required_to_close"] for p in reds)
    check("C7", ok_c7,
          f"all {len(reds)} intentional REDs are RED_CONFIRMED with engine_change_required_to_close=true; "
          f"verdict is NOT_A_SUITE_PASS")

    # --- C8: v6 registry contains no temporary-secret type -------------------
    tz = (REPO / "research/hop-format-audit/next-sprint-review/v6-snapshot/tz-agentpii6.md").read_text(encoding="utf-8")
    rows = re.findall(r"^\|\s*([A-Z]-\d+)\s*\|\s*`?([A-Z][A-Z0-9_]+)`?\s*\|", tz, re.M)
    codes = sorted({r[1] for r in rows})
    secretish = [x for x in codes if any(s in x for s in ("CVC", "CVV", "OTP", "3DS", "SMS", "PIN"))]
    check("C8", len(codes) == 63 and secretish == [],
          f"v6 registry rows={len(rows)}, unique type codes={len(codes)}, temporary-secret codes={secretish}")

    # --- C9: this task wrote nothing outside work/C0 -------------------------
    porcelain = subprocess.run(["git", "status", "--porcelain"], cwd=str(REPO),
                               capture_output=True, text=True).stdout.splitlines()
    modified = sorted(l[3:].strip() for l in porcelain if l[:2].strip() == "M")
    outside = [m for m in modified if m not in
               ("prototype/bench/agentpii5/live.py", "prototype/bench/agentpii5/runs.json", "wiki/INDEX.md")]
    check("C9", outside == [],
          f"pre-existing tracked modifications only ({modified}); none added by C0; C0 files are untracked under work/C0")

    # --- C10: C0 artifacts parse as JSON -------------------------------------
    bad = []
    for name in ("INPUTS.json", "TYPE-CONTRACTS.json", "FIXTURES.json", "PROBE-FACTS.json"):
        try:
            json.loads((HERE / name).read_text(encoding="utf-8"))
        except Exception as exc:  # noqa: BLE001
            bad.append(f"{name}: {type(exc).__name__}: {exc}")
    check("C10", not bad, f"4 machine-readable artifacts parse ({bad})")

    # --- C11: no C0 artifact was written outside the declared scope ----------
    stray = [p.name for p in HERE.iterdir() if p.is_file() and p.name not in set(
        inputs["artifacts_produced"] and [Path(a).name for a in inputs["artifacts_produced"]])]
    check("C11", stray == [], f"no stray files in work/C0 (unexpected={stray})")

    # --- C12: record the sha256 of every produced artifact -------------------
    log("CHECK C12 OK EXIT=0 :: artifact sha256 ledger (work/C0)")
    for p in sorted(HERE.iterdir()):
        if p.is_file():
            suffix = ("  (PREVIOUS revision of this file — self-referential by construction)"
                      if p.name == "checks.log" else "")
            log(f"  sha256 {sha256(p)}  work/C0/{p.name}{suffix}")

    log("")
    log(f"SUMMARY checks=12 failures={len(failures)} {failures}")
    (HERE / "checks.log").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {HERE/'checks.log'}; failures={failures}")
    return 0 if not failures else 1


if __name__ == "__main__":
    raise SystemExit(main())
