HERE: Path = Path(__file__).resolve().parent
SEED: int = 4
PLAN: tuple[tuple[object, int], ...] = PLAN_A + PLAN_B
# The clustered-bootstrap parameters every MDE in the printed table is computed
# at: a 10% disagreement rate and a design effect of 2.1, which are v4's own
# measured numbers (`bench/agentpii4/build.py`). Restated as constants so the
# table's header and its arithmetic cannot disagree.
MDE_RATE: float = 0.10
MDE_DEFF: float = 2.1
# The modules that BUILD a case and must therefore never search what they built.
# `revise.py` writes 834 of the 1 594 and was outside v4's watched set; `build.py`
# is here because a "quick check" added to the assembly would be the next one.
WATCHED_V5: tuple[str, ...] = (str(HERE / "scenarios5"), str(HERE / "revise.py"),
                               str(HERE / "build.py"))
# The names a FINISHED string is bound to in this package: a message's text, a
# rendered result, a document body, the phrase a loop was given. A builder that
# asks one of them a question is recovering ground truth by search.
SEARCHED_SURFACES: tuple[str, ...] = (
    "content", "messages", "text", "result_text", "rendered", "body",
    "confirm_phrase", "message_template")
# The string methods that scan, and the `re` entry points. `replace` is absent
# on purpose: rewriting a string one BUILT is how a register transform works.
SCANNING_METHODS: tuple[str, ...] = ("find", "rfind", "index", "rindex",
                                     "startswith", "endswith", "count")
RE_SCANNERS: tuple[str, ...] = ("search", "match", "fullmatch", "finditer", "findall")


def build_corpus(seed: int) -> list[CaseV5]:
    """The whole v5 corpus: the revised 834, then every planned family."""
    cases: list[CaseV5] = list(revise_module.revise(revise_module.load_v4_corpus()))
    for module, count in PLAN:
        cases.extend(module.build(seed, count))          # type: ignore[attr-defined]
    return cases


def build_reporting(seed: int, allow_drop: bool) -> tuple[list[CaseV5], Counter[str], list[str]]:
    """`build_corpus` plus what had to be approximated: the cases, the downgrades
    COUNTED BY REASON, and the v4 ids that could not be revised.

    THE COUNTER RATHER THAN THE PRINTED LINES, because two readers need it: the
    table `main` prints, and `chain_table`, which reports how many cases left
    `sequential_chain` under R-49 by name. Formatting it here and parsing it back
    there would make a printed string the data structure.

    `allow_drop` is the ONE path that continues past an unrevisable v4 case, and
    it leaves K10 red on purpose — a corpus that is 833 of 834 is not the v4
    baseline, and a flag that hid that would be a flag that lies.
    """
    v4_cases = revise_module.load_v4_corpus()
    revisions, dropped = revise_module.revise_reporting(v4_cases)
    if dropped and not allow_drop:
        raise v4.InvalidCase(f"{len(dropped)} v4 cases could not be revised; "
                             f"pass --allow-drop to continue with K10 red:\n  "
                             + "\n  ".join(dropped))
    cases: list[CaseV5] = [one.case for one in revisions]
    downgrades: Counter[str] = Counter(
        f"{one.downgraded_from} → single · {one.reason}" for one in revisions
        if one.downgraded_from)
    for module, count in PLAN:
        cases.extend(module.build(seed, count))          # type: ignore[attr-defined]
    return cases, downgrades, dropped


def downgrade_lines(downgrades: Counter[str]) -> list[str]:
    """The downgrade table, one line per reason, most-reported first by name."""
    return [f"{count:>5} · {label}" for label, count in sorted(downgrades.items())]


# --- the proof that nothing searched a finished string ------------------------------

def prove_no_search_v5(seed: int) -> tuple[list[CaseV5], list[str]]:
    """v4's dynamic proof, widened to the v5 builders, PLUS a static one.

    TWO PROOFS, BECAUSE EACH IS BLIND WHERE THE OTHER LOOKS.
    `v4validate.prove_no_search` traces `c_call` events for the names in its
    `_SEARCHERS` table, so it sees `str.find` and `re.search` — and cannot see
    the `in` operator, which compiles to a `COMPARE_OP` and never calls a
    watched builtin at all. `revise.py` was outside the watched set entirely and
    did exactly that: `item.value in case.messages[turn].content` decided
    `LoopSpec.show_turn` for the whole `user_in_loop` family. So the watch is
    widened to the modules that BUILD (`scenarios5/`, `revise.py`, `build.py`)
    and a static pass reads their AST for containment as well.
    """
    watched = v4validate._WATCHED_DIRS                   # noqa: SLF001 - see the docstring
    v4validate._WATCHED_DIRS = watched + WATCHED_V5      # noqa: SLF001
    try:
        cases, hits = v4validate.prove_no_search(lambda: _build_bases(seed))
    finally:
        v4validate._WATCHED_DIRS = watched               # noqa: SLF001
    del cases
    return _last_built, list(hits) + static_search_hits()


def static_search_hits() -> list[str]:
    """Every containment or scan of a FINISHED string in the watched builders.

    A STATIC CHECK IS ENOUGH HERE BECAUSE THE SHAPE IS LITERAL. The forbidden
    move is asking a finished message, result or rendered document whether it
    contains a value the builder already knows it put there — `x in <that>`,
    `<that>.find(x)`, `<that>.index(x)`, `<that>.startswith(x)`,
    `re.search(..., <that>)`. Each is a syntactic shape over a name from
    `SEARCHED_SURFACES`, and reading it off the AST needs no run.
    """
    hits: list[str] = []
    for path in _watched_files():
        tree = ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
        for node in ast.walk(tree):
            surface = _searched_surface(node)
            if surface:
                hits.append(f"{path.name}:{node.lineno} searches {surface}")
    return sorted(hits)


def _watched_files() -> list[Path]:
    """The modules that BUILD a case, so the static pass reads exactly what the
    dynamic one traces."""
    files = [Path(one) for one in WATCHED_V5 if one.endswith(".py")]
    for directory in (one for one in WATCHED_V5 if not one.endswith(".py")):
        files.extend(sorted(Path(directory).glob("*.py")))
    return files


def _searched_surface(node: ast.AST) -> str:
    """The finished string this node searches, or "" when it searches none."""
    if isinstance(node, ast.Compare) and any(
            isinstance(operator, (ast.In, ast.NotIn)) for operator in node.ops):
        return _surface_name(node.comparators[0])
    if not isinstance(node, ast.Call):
        return ""
    function = node.func
    if isinstance(function, ast.Attribute) and function.attr in SCANNING_METHODS:
        return _surface_name(function.value)
    if isinstance(function, ast.Attribute) and function.attr in RE_SCANNERS \
            and isinstance(function.value, ast.Name) and function.value.id == "re":
        return " ".join(filter(None, (_surface_name(one) for one in node.args)))
    return ""


def _surface_name(node: ast.AST) -> str:
    """The `SEARCHED_SURFACES` name an expression ends in — `case.messages[t]
    .content` ends in `content` — or "" for anything else."""
    while isinstance(node, (ast.Subscript, ast.Call)):
        node = node.value if isinstance(node, ast.Subscript) else node.func
    if isinstance(node, ast.Attribute) and node.attr in SEARCHED_SURFACES:
        return node.attr
    if isinstance(node, ast.Name) and node.id in SEARCHED_SURFACES:
        return node.id
    return ""


_last_built: list[CaseV5] = []


def _build_bases(seed: int) -> list[Case]:
    """Build under the profiler and keep the v5 cases where the caller can reach
    them: `prove_no_search` is typed to a sequence of v4 `Case`, so the v5 half
    travels beside it rather than through it."""
    global _last_built                                   # noqa: PLW0603 - see the docstring
    _last_built = build_corpus(seed)
    return [case.base for case in _last_built]


# --- the tables --------------------------------------------------------------------

def coverage_table(cases: Sequence[CaseV5]) -> list[str]:
    """What the corpus covers, in the order a reader asks: how many, of what,
    in which register, carrying which types, reaching a result."""
    total = len(cases)
    authored = [case for case in cases if not case.revised_from_v4]
    lines = [f"случаев: {total} (ревизия v4 {total - len(authored)} · "
             f"написано в v5 {len(authored)})"]
    behaviours = Counter(case.behaviour for case in cases)
    lines.append("поведение: " + " · ".join(
        f"{name} {behaviours.get(name, 0)}" for name in c.BEHAVIOURS))
    for label, pool in (("регистр (весь корпус)", cases), ("регистр (написано в v5)", authored)):
        registers = Counter(case.base.register for case in pool)
        voice = sum(registers.get(name, 0) for name in c.SPEECH_REGISTERS)
        size = max(1, len(pool))
        lines.append(f"{label}: voice {voice} ({voice / size:.1%}) · " + " · ".join(
            f"{name} {registers.get(name, 0)} ({registers.get(name, 0) / size:.1%})"
            for name in c.REGISTERS if name not in c.SPEECH_REGISTERS))
    types = Counter(item.type for case in cases for item in case.base.pii)
    lines.append("значения: " + " · ".join(f"{name} {types.get(name, 0)}"
                                           for name in sorted(types)))
    for kind in sorted(c.MIN_CASES_BY_TYPE):
        carrying = sum(1 for case in cases
                       if any(item.type == kind for item in case.base.pii))
        lines.append(f"  {kind}: несут {carrying} случаев (нужно "
                     f"{c.MIN_CASES_BY_TYPE[kind]})")
    with_result = sum(1 for case in cases if case.has_result)
    lines.append(f"с результатом инструмента: {with_result} ({with_result / total:.1%}, "
                 f"нужно {c.MIN_SHARE_WITH_RESULT:.0%})")
    lines.append(f"потоковых: {sum(1 for case in cases if case.streaming)} "
                 f"(нужно {c.MIN_STREAMING_CASES})")
    owners = Counter(owner for case in cases for owner in {hop.owner for hop in case.hops})
    lines.append("владельцы переходов: " + " · ".join(
        f"{name} {owners.get(name, 0)}" for name in c.HOP_OWNERS))
    explicit = sum(1 for case in cases if case.base.conversation_id)
    lines.append(f"явный conversation_id: {explicit} · выведенный: {total - explicit}")
    distinct, counted = v4validate.find_distinct_share([case.base for case in cases])
    lines.append(f"доказательство: `find` не нашёл бы эталон в {distinct} из {counted} случаев")
    return lines


def mde_table(cases: Sequence[CaseV5]) -> list[str]:
    """Every family's size AND the effect it can see.

    A SIZE ALONE IS A NUMBER A READER WILL MISREAD. §8.2 gives four families
    fewer than the 120 cases ±10pp needs, and the honest answer is not to refuse
    them but to print the wider interval beside them — so a per-family verdict is
    read with the resolution it actually has.
    """
    counts = Counter(case.behaviour for case in cases)
    lines = [f"MDE по семьям (доля расхождений {MDE_RATE}, DEFF {MDE_DEFF}, мощность 80%):"]
    for behaviour in c.BEHAVIOURS:
        size = counts.get(behaviour, 0)
        floor = c.BEHAVIOUR_FLOORS[behaviour]
        mde = stats.mde_paired(size, MDE_RATE, MDE_DEFF) if size else 1.0
        mark = " " if size >= floor else "!"
        lines.append(f" {mark}{behaviour:<24} {size:>4} случаев (пол {floor:>3}) · "
                     f"MDE {mde * 100:.1f}pp")
    return lines


def form_disagreements(cases: Sequence[CaseV5]) -> list[str]:
    """Which tool the corpus expects which form from — and every form it does
    NOT get.

    R-17 ASKED FOR ACTUAL-VERSUS-EXPECTED AND THERE WAS NO COMPARISON ANYWHERE:
    flipping 1 215 of 1 594 cases to a wrong (but declared-by-the-tool) form
    passed every rule. The actual form needs no live run — the backend is right
    here — so `proof_problems` drives it and refuses the disagreement, and this
    table is what the reader sees when nothing disagrees.
    """
    seen: Counter[str] = Counter()
    for case in cases:
        for expectation in case.returns:
            seen[f"{expectation.tool_name}:{expectation.return_form}"] += 1
    return ["формы ответа (проверены на реальном моке): " + " · ".join(
        f"{label} {count}" for label, count in sorted(seen.items()))]


def proof_problems(cases: Sequence[CaseV5]) -> list[str]:
    """Every case whose declaration the real backend does not produce.

    THE DECLARATION IS NOT EVIDENCE OF ITSELF. `has_result`, K03 and the whole
    `leak` line are counted off DECLARED hops, and 42% of the revised half's
    IN/tool hops were crossings the mock never renders — 132 cases claiming a
    tool loop with nothing observable in it. So every case is seeded into a real
    `BackendV5`, its declared calls are made with its own argument values, and a
    hop whose span the result never carries is a corpus defect that cannot ship.
    """
    problems: list[str] = []
    for case in cases:
        problems.extend(mock.render_problems(case))
    return problems


def loop_table(cases: Sequence[CaseV5]) -> list[str]:
    """How many `single` cases actually carry the minimal loop, and who wrote
    them.

    §8.2's row for «одиночный вызов» names FOUR obligatory hops (IN/user →
    OUT/arg → IN/tool → OUT/answer), and the revised half of the family is mostly
    v4 two-hop cases that R-23's conversion downgraded into it. One number would
    read as «563 cases of the base shape»; these four say which is which — and
    the authored count is the one R-50 added, because a share read off the total
    would credit the family with a shape 379 of its cases do not have.
    """
    singles = [case for case in cases if case.behaviour == "single"]
    authored = [case for case in singles if not case.revised_from_v4]
    revised = [case for case in singles if case.revised_from_v4]
    looped = [case for case in singles if case.has_result]
    return [f"одиночные: {len(singles)} · написано в v5 {len(authored)} · "
            f"ревизия v4 {len(revised)} · с минимальной петлёй "
            f"({c.MIN_HOPS_WITH_RESULT} перехода) {len(looped)} · "
            f"двухходовых v4 {len(singles) - len(looped)}"]


def chain_table(cases: Sequence[CaseV5], downgrades: Counter[str]) -> list[str]:
    """What R-49 cost the chain family and what was written to replace it.

    THE TWO NUMBERS BELONG TOGETHER. R-49 says the argument of a MUTATING call
    is the value the customer just stated, never the stale one the earlier lookup
    returned — so the cases whose only hand-over was that kind leave
    `sequential_chain` honestly. Printing the departures without the top-up would
    read as a family that shrank; printing the total alone would hide that 85 of
    its transitions were never attainable.
    """
    left = sum(count for label, count in downgrades.items()
               if label.endswith(revise_module.MUTATING_REASON))
    family = [case for case in cases if case.behaviour == "sequential_chain"]
    authored = sum(1 for case in family if not case.revised_from_v4)
    return [f"цепочки: {len(family)} · написано в v5 {authored} · "
            f"ревизия v4 {len(family) - authored} · ушло по R-49 (аргумент "
            f"мутирующего вызова — сказанное клиентом) {left}"]


# --- the files ----------------------------------------------------------------------

def write_corpus(cases: Sequence[CaseV5], out: Path) -> str:
    """Both views of one corpus, from one list of objects. Returns the v5 digest."""
    digest = corpus_digest_v5(cases)
    (out / "corpus.v5.json").write_text(json.dumps({
        "version": 5, "cases": len(cases), "digest": digest,
        "corpus": [case_v5_to_json(case) for case in cases]},
        ensure_ascii=False, indent=1), encoding="utf-8")
    bases = [case.base for case in cases]
    (out / "corpus.json").write_text(json.dumps({
        "version": 4, "cases": len(bases), "digest": v4.corpus_digest(bases),
        "corpus": [case.to_json() for case in bases]},
        ensure_ascii=False, indent=1), encoding="utf-8")
    return digest


def write_ladder(cases: Sequence[CaseV5], seed: int, out: Path,
                 regenerate: bool, unfrozen: bool) -> tuple[Ladder | None, list[str], list[str]]:
    """The frozen ladder (K12), what to print, and what is WRONG with it.

    THE PROBLEMS ARE A THIRD VALUE RATHER THAN A PREFIX IN THE PRINTED LINES.
    `main` has to exit non-zero on them, and asking it to recognise its own
    output by the word it starts with is one rename away from an exit 0 that
    means nothing.

    KEPT, NOT REBUILT. The holdout is 20% drawn before any debug tier exists,
    and its whole value is that it was drawn before anyone looked. A build that
    silently redrew it every time the corpus grew would hand back a holdout that
    had seen every debugging run of the week.

    `unfrozen` IS THE ONE TIME THE HOLDOUT MAY MOVE (R-52), and it is an
    assertion about the world rather than a switch: adding a family and topping
    another one up changes v4's per-family draw, so 476 existing cases change
    tier — refusing that would freeze the ladder of a corpus nobody has run
    against yet, while accepting it silently at any later moment would hand back
    a holdout that had seen the debugging. The caller states which of the two it
    is in, the movement is PRINTED, and every regeneration without the assertion
    is refused exactly as before.
    """
    path = out / "ladder.json"
    bases = [case.base for case in cases]
    if path.exists() and not regenerate:
        # A FREEZE NOBODY HAS WATCHED FAIL IS NOT A FREEZE. The ladder names the
        # corpus it was drawn from; keeping it beside a DIFFERENT corpus silently
        # renames the holdout — rebuilding with another seed moved 162 of 319
        # holdout ids onto other cases and printed «оставлена как есть», exit 0.
        kept = json.loads(path.read_text(encoding="utf-8"))
        digest = v4.corpus_digest(bases)
        if str(kept.get("corpus_sha256", "")) != digest:
            return None, [], [f"ЛЕСТНИЦА: {path} была снята с корпуса "
                          f"{str(kept.get('corpus_sha256', ''))[:16]}, а записан "
                          f"{digest[:16]}; --regenerate-ladder чтобы пересобрать "
                          f"(холдаут увидит отладку) или верните прежний корпус"]
        return None, [f"лестница оставлена как есть: {path} "
                      f"(--regenerate-ladder чтобы пересобрать)"], []
    ladder = build_ladder(bases, seed)
    lines: list[str] = []
    if regenerate and path.exists():
        # REGENERATION KEEPS THE HOLDOUT OF EVERY CASE THAT STILL EXISTS. The
        # point of K12 is that the holdout was drawn before anybody looked; a
        # redraw that moved an existing case in or out would hand back a holdout
        # that had seen the week's debugging. New cases are distributed by the
        # same seed and may land anywhere.
        moved = _holdout_moved(json.loads(path.read_text(encoding="utf-8")), ladder,
                               {case.id for case in bases})
        if moved and not unfrozen:
            return ladder, [], [f"ЛЕСТНИЦА: {len(moved)} случаев сменили ярус при "
                                f"пересборке: {sorted(moved)[:5]}"]
        if moved:
            lines.append(f"лестница пересобрана: {len(moved)} случаев сменили ярус "
                         f"(--unfrozen-before-first-run: живого прогона по прежней "
                         f"лестнице не было, R-52)")
    broken = ladder_problems(bases, ladder)
    if broken:
        return ladder, [], [f"ЛЕСТНИЦА: {line}" for line in broken]
    path.write_text(json.dumps({
        "version": ladder.version, "seed": ladder.seed,
        "corpus_sha256": ladder.corpus_sha256,
        "tiers": {name: list(ids) for name, ids in ladder.tiers.items()}},
        ensure_ascii=False, indent=1), encoding="utf-8")
    return ladder, lines + ["лестница записана: " + " / ".join(
        f"{name} {len(ids)}" for name, ids in ladder.tiers.items())], []


def ladder_refusal(regenerate: bool, unfrozen: bool) -> str:
    """Why this run may not redraw the holdout, or "" when it may.

    R-52 LET THE LADDER MOVE ONCE, AND ONCE IS A CLAIM SOMEBODY HAS TO MAKE. The
    holdout's whole value is that it was drawn before anybody looked; after the
    first live run a redraw hands back twenty per cent of the corpus that has
    seen the week's debugging, and `--regenerate-ladder` alone cannot tell the
    two situations apart — the flag says WHAT to do and not what is true. So the
    caller asserts the fact, and the assertion is a separate word a script cannot
    acquire by copying yesterday's command line.

    A FUNCTION RATHER THAN THREE LINES INSIDE `main`, so both answers can be
    exercised: a refusal nobody has watched hold and give way is a refusal
    nobody has measured.
    """
    if regenerate and not unfrozen:
        return ("ОТКАЗ: --regenerate-ladder требует --unfrozen-before-first-run "
                "(R-52: лестницу можно пересобрать, только пока по ней не было "
                "ни одного живого прогона)")
    return ""


def _holdout_moved(kept: dict[str, object], ladder: Ladder,
                   alive: set[str]) -> set[str]:
    """Case ids that were in the old holdout and are not in the new one, or the
    other way round — counting only cases the new corpus still carries."""
    tiers = kept.get("tiers")
    before = set(tiers.get("holdout", ())) if isinstance(tiers, dict) else set()
    after = set(ladder.tiers.get("holdout", ()))
    return ((before ^ after) & alive)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="validate and print, write nothing")
    parser.add_argument("--regenerate-ladder", action="store_true",
                        help="redraw the holdout; needs --unfrozen-before-first-run")
    parser.add_argument("--unfrozen-before-first-run", action="store_true",
                        help="the assertion R-52 asks for: no live run has read this "
                             "ladder yet, so redrawing it hides no debugging")
    parser.add_argument("--allow-drop", action="store_true",
                        help="continue past an unrevisable v4 case, leaving K10 red")
    parser.add_argument("--seed", type=int, default=SEED)
    parser.add_argument("--out", default=str(HERE))
    args = parser.parse_args()

    refusal = ladder_refusal(args.regenerate_ladder, args.unfrozen_before_first_run)
    if refusal:
        print(refusal, file=sys.stderr)
        return 1
    cases, downgrades, dropped = build_reporting(args.seed, args.allow_drop)
    _, hits = prove_no_search_v5(args.seed)
    problems: list[str] = []
    for case in cases:
        problems.extend(validate_v5(case))
    problems.extend(validate_corpus_v5(cases, tuple(REGISTRY_V5)))
    problems.extend(proof_problems(cases))

    for identifier in dropped:
        print(f"НЕ РЕВИЗОВАН: {identifier}")
    for hit in hits:
        print(f"ПОИСК В ГЕНЕРАТОРЕ: {hit}")
    for problem in problems[:80]:
        print(problem)
    if downgrades:
        print("понижено до `single` (структура семьи отсутствует):")
        for line in downgrade_lines(downgrades):
            print(f"  {line}")
    for line in coverage_table(cases):
        print(line)
    for line in loop_table(cases):
        print(line)
    for line in chain_table(cases, downgrades):
        print(line)
    for line in form_disagreements(cases):
        print(line)
    for line in mde_table(cases):
        print(line)
    if hits or problems or dropped:
        print(f"ОТКАЗ: {len(hits)} поисков, {len(problems)} проблем, "
              f"{len(dropped)} не ревизовано", file=sys.stderr)
        return 1
    if args.check:
        print(f"корпус собран и проверен, не записан (--check) · "
              f"digest {corpus_digest_v5(cases)[:12]}")
        return 0
    out = Path(args.out)
    digest = write_corpus(cases, out)
    ladder, lines, broken = write_ladder(cases, args.seed, out, args.regenerate_ladder,
                                         args.unfrozen_before_first_run)
    for line in lines + broken:
        print(line)
    if broken:
        print(f"ОТКАЗ: лестница ({len(broken)})", file=sys.stderr)
        return 1
    del ladder
    # The round trip is checked on the file that was just written rather than in
    # a test alone: a corpus that cannot be read back is a corpus nobody can run.
    stored = json.loads((out / "corpus.v5.json").read_text(encoding="utf-8"))
    reread = [case_v5_from_json(row) for row in stored["corpus"]]
    if corpus_digest_v5(reread) != digest:
        print("ОТКАЗ: записанный корпус читается не как собранный", file=sys.stderr)
        return 1
    print(f"записан {out / 'corpus.v5.json'} · {len(cases)} случаев · digest {digest[:12]}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
