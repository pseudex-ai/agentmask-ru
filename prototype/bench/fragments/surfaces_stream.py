"""Поверхность потока: `/unmask_chunk`, по дельтам, с переносом между ними.

ЧЕМ ЭТА ПОВЕРХНОСТЬ ОТЛИЧАЕТСЯ ОТ ПРОЗЫ, И ПОЧЕМУ ЭТО НЕ ТА ЖЕ КЛЕТКА ДРУГИМИ
СЛОВАМИ. `/unmask` получает ответ целиком и отдаёт `residual_tokens`;
`/unmask_chunk` получает ответ кусками и не отдаёт остаток НИ В ТЕЛЕ, НИ В
ЗАГОЛОВКЕ — ответ ручки это `{text, carry}` и больше ничего. Значит на потоковом
плече ЛЮБОЙ отказ невидим заказчику по построению, и колонка «молча» этой
поверхности обязана равняться её колонке «потеряно». Объявить
`reports_residual = True` значило бы напечатать нули ровно там, где тихая потеря
единственно и интересна.

ПОЧЕМУ ДЕЛЬТА КОРОТКАЯ. Настоящий SSE несёт токен модели — несколько символов, —
и значение приезжает разрезанным. Послать всю прозу одной дельтой было бы
технически законно и бессмысленно: поверхность стала бы копией прозаической
клетки, а перенос (`carry`), ради которого ручка и существует, ни разу бы не
понадобился. `DELTA_CHARS` выбрана короче самого короткого значения корпуса
(«+7 999 123-45-67» — шестнадцать символов), поэтому каждое значение пересекает
границу дельты хотя бы раз.

ЧТО ЭТА ПОВЕРХНОСТЬ МЕРЯЕТ НА КОРОТКОМ ОТВЕТЕ, СКАЗАНО ЧЕСТНО: движок держит в
переносе последние `redact._STREAM_KEEP` (64) символа, поэтому проза корпуса —
она почти вся короче — целиком доезжает до `flush` и восстанавливается ОДНИМ
вызовом. Разница с прозаической клеткой на таких случаях — ровно видимость
остатка, и это само по себе число: одна и та же потеря там названа, а здесь нет.
Длинные случаи (`foreign_warehouse`, `foreign_documents`) переваливают за 64 и
проходят настоящий потоковый путь.
"""

import json
from collections.abc import Mapping

from bench.fragments.engine import Engine, EngineError
from bench.fragments.surfaces import Passage, Returned, Scope

# Короче самого короткого значения корпуса — см. докстроку модуля.
#
# ЧИСЛО НА ВТОРОЙ СТОРОНЕ ОТ НЕГО ЗАВИСИТ, И ЭТО ИЗМЕРЕНО. На 50 диалогах, три
# повтора, «чужое переписано»: дельта 3 → 2/144, дельта 5 → 2/144, дельта 11 →
# 3/144, дельта 40 → 5/144, а прозаическая клетка на тех же текстах — 0/144 при
# всех четырёх. Значит НАПРАВЛЕНИЕ («поток портит собственные числа заказчика
# там, где ответ целиком их не трогает») от размера дельты не зависит, а
# ВЕЛИЧИНА зависит: разрез решает, какой хвост увидит восстановление. Поэтому
# размер объявлен константой и назван в отчёте, а не подобран под число.
# Первая сторона («наше не вернулось») от него не зависит вовсе — 27/279,
# 34/279, 29/279, 28/279 и ровно столько же в прозе на тех же прогонах.
DELTA_CHARS = 5


def _deltas(text: str) -> tuple[str, ...]:
    """Проза, нарезанная на дельты ПО СИМВОЛАМ, а не по байтам.

    По символам, потому что дельта — это то, что уходит в JSON-тело запроса:
    разрез посреди кириллической буквы дал бы не «значение приехало разрезанным»,
    а сломанную кодировку, то есть поломку прибора, зачтённую движку.
    """
    return tuple(text[start:start + DELTA_CHARS]
                 for start in range(0, len(text), DELTA_CHARS))


def _text_and_carry(answer: Mapping[str, object]) -> tuple[str, str]:
    text, carried = answer.get("text"), answer.get("carry")
    if not isinstance(text, str) or not isinstance(carried, str):
        raise EngineError(
            f"/unmask_chunk вернул не пару строк {{text, carry}}: "
            f"{json.dumps(answer, ensure_ascii=False)[:300]}")
    return text, carried


class StreamSurface:
    """`POST /unmask_chunk` — ответ, который заказчик отдаёт человеку по мере прихода.

    Один перенос на весь вызов, и этого достаточно ровно потому, что случай
    прибора — это ОДИН `choice`. Движок требует переноса на `choice.index`
    (иначе хвост одного ответа приклеивается к голове другого), а с `n > 1`
    прибор дела не имеет: он меряет принадлежность куска, а не мультиплексор.
    """

    name = "stream"
    carries_fields = False
    carries_prose = True
    # Обязанность, а не оговорка: ручка остатка не отдаёт. См. докстроку модуля.
    reports_residual = False
    honours_conversation_id = True

    def __init__(self, engine: Engine) -> None:
        self._engine = engine

    def _chunk(self, org_id: str, delta: str, carried: str, flush: bool,
               scope: Scope) -> tuple[str, str]:
        body: dict[str, object] = {
            "org_id": org_id,
            "delta": delta,
            "carry": carried,
            "flush": flush,
            "pseudonym_scope": scope.pseudonym_scope,
        }
        if scope.conversation_id:
            body["conversation_id"] = scope.conversation_id
        return _text_and_carry(self._engine.post("/unmask_chunk", body))

    def carry(self, org_id: str, passage: Passage, scope: Scope) -> Returned:
        """Провести прозу случая через ручку по дельтам и склеить, что вышло наружу.

        ЗАКРЫВАЮЩИЙ ВЫЗОВ ДЕЛАЕТСЯ ВСЕГДА, и это не формальность: до `flush`
        движок держит в переносе последние 64 символа, и проза короче этого не
        выходит наружу вовсе. Шлюз заказчика поступает так же — `[DONE]` от
        апстрима закрывает поток пустой дельтой. Отдельная ветка «если проза
        пустая» не нужна: закрывающий вызов её и обслуживает.
        """
        emitted: list[str] = []
        carried = ""
        for delta in _deltas(passage.prose):
            text, carried = self._chunk(org_id, delta, carried, False, scope)
            emitted.append(text)
        text, carried = self._chunk(org_id, "", carried, True, scope)
        emitted.append(text)
        if carried:
            # Не-пустой перенос после `flush` означает, что часть ответа не
            # вышла наружу вообще. Молча склеить остальное значило бы записать
            # потерю прибора на счёт движка.
            raise EngineError(
                f"/unmask_chunk оставил перенос {carried!r} после flush — "
                f"часть ответа не была отдана заказчику")
        return Returned(surface=self.name, fields=(), prose="".join(emitted),
                        residual=())
