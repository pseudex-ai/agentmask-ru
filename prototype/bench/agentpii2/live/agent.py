"""One arm of one case, against a real Claude agent through the Agent SDK.

WHY THE TRANSCRIPT IS REPLAYED AND NOT REPLAYED. The corpus stores finished
dialogues: a user turn, an assistant turn holding `tool_calls`, and the tool
result that came back. The SDK has no way to inject somebody else's assistant
turn into a session, and forcing one would defeat the purpose — the question is
what THIS model does. So only the user turns are sent, and the assistant turns
the corpus recorded are regenerated by the model itself. What the corpus keeps is
the TOOL RESULT: when the model calls a tool the case recorded a result for, that
recorded result is what comes back. Which is the honest split — the customer's
CRM is a fixture, the agent is the thing under test.

A tool the case recorded nothing for answers `{"status": "ok"}`, IDENTICALLY in
both arms. That matters more than it looks: any difference between the arms that
the harness itself introduces is indistinguishable in the result from a
difference the gateway caused. A recorded result masked in arm B is a deliberate
difference and the product's own doing; a canned filler that differed between
arms would be the harness contaminating its own measurement.

AUTHENTICATION, verified on this machine and NOT to be improvised:

  * the credential lives in the macOS keychain, written by Claude Code.
    `ANTHROPIC_API_KEY` and `CLAUDE_CODE_OAUTH_TOKEN` are unset and must stay so.
  * `CLAUDE_CONFIG_DIR` must NOT be set. assay's `adapters/base.py` records the
    same finding the hard way: a pristine config dir is hermetic and has no
    credentials, so every call fails. Hermeticity here comes from
    `setting_sources=[]` and `strict_mcp_config=True` instead, which cost
    nothing.
  * `CLAUDECODE` is stripped from the child environment. This runner is normally
    launched from inside a Claude Code session and the nested one misbehaves
    otherwise.
  * `session_id` must be a canonical dashed UUID. Bare hex is rejected by the
    CLI. It is derived with `uuid5` from the run id, the case and the arm, so a
    result file names a session that can actually be found again.

`permission_mode="bypassPermissions"` because a batch run that stops on a
permission dialog is a batch run that hangs at case three overnight.
"""

import asyncio
import json
import os
import tempfile
import uuid
from dataclasses import dataclass, field

from claude_agent_sdk import (
    AssistantMessage,
    ClaudeAgentOptions,
    ClaudeSDKClient,
    ResultMessage,
    SystemMessage,
    TextBlock,
    create_sdk_mcp_server,
    tool,
)

from bench.agentpii2.live.gateway import LiveGateway
from bench.agentpii2.schema import Case, message_text

SERVER = "bench"
_PREFIX = f"mcp__{SERVER}__"
_NAMESPACE = uuid.UUID("6f0f6c1e-9b0a-4f1e-9a1a-2b3c4d5e6f70")

# The instruction both arms get when the case names no system message. Identical
# across arms by construction — a prompt that differed between them would put the
# harness's own wording inside the number the harness reports.
DEFAULT_SYSTEM = ("Ты оператор поддержки интернет-магазина. Выполняй просьбу "
                  "клиента через предложенные инструменты, не переспрашивай и "
                  "не выдумывай данных, которых нет в разговоре.")

FILLER_RESULT = '{"status": "ok"}'


@dataclass(frozen=True)
class ObservedCall:
    """A tool call exactly as the model emitted it. `arguments` is the plain dict
    the SDK hands the handler — no re-parsing, so a malformed argument object
    never becomes the harness's problem instead of the model's."""

    name: str
    arguments: dict[str, object]


@dataclass(frozen=True)
class ArmResult:
    arm: str
    calls: tuple[ObservedCall, ...]
    final_text: str
    cost_usd: float
    model: str
    turns: int
    duration_ms: int
    is_error: bool
    subtype: str
    api_error_status: int | None
    errors: tuple[str, ...]
    session_id: str
    model_usage: dict[str, object] = field(default_factory=dict)


def session_id(run_id: str, case_id: str, arm: str) -> str:
    """A canonical dashed UUID, stable for a given run. The CLI rejects bare hex,
    and a random one makes a failed case unfindable in the session store."""
    return str(uuid.uuid5(_NAMESPACE, f"{run_id}|{case_id}|{arm}"))


def _recorded_results(case: Case) -> dict[str, list[str]]:
    """Tool name -> the results the corpus recorded for it, in order.

    Joined through `tool_call_id`, never by position: a case may record two calls
    before either result comes back, and matching by position would hand the
    second tool's answer to the first.
    """
    by_id: dict[str, str] = {}
    for message in case.messages:
        if message.get("role") != "assistant":
            continue
        for call in message.get("tool_calls") or []:
            if isinstance(call, dict) and isinstance(call.get("function"), dict):
                by_id[str(call.get("id"))] = str(call["function"].get("name", ""))
    results: dict[str, list[str]] = {}
    for index, message in enumerate(case.messages):
        if message.get("role") != "tool":
            continue
        name = str(message.get("name") or by_id.get(str(message.get("tool_call_id")), ""))
        if name:
            results.setdefault(name, []).append(message_text(case, index))
    return results


def user_turns(case: Case) -> int:
    """How many times the harness will speak. Drives `max_turns` and the timeout,
    because a fixed 12 is right for a `short` case and silently truncates the
    `long` rung, where one case carries SIXTY-ONE user turns — and a truncated
    trajectory compared against a complete one reports a divergence the gateway
    did not cause."""
    return sum(1 for message in case.messages if message.get("role") == "user")


def _system_prompt(case: Case) -> str:
    for index, message in enumerate(case.messages):
        if message.get("role") == "system":
            return message_text(case, index)
    return DEFAULT_SYSTEM


def _mcp_tools(case: Case, gateway: LiveGateway | None,
               recorded: dict[str, list[str]], sink: list[ObservedCall]) -> list[object]:
    """One in-process MCP tool per function the case offers.

    The schemas are the corpus's own OpenAI function JSON, handed to the SDK
    unchanged — `@tool` accepts a full JSON Schema. Translating them would make
    the benchmark's published claim («replay this against any provider») false
    for the one provider it actually runs against.
    """
    schemas = case.tools if gateway is None else gateway.tools(list(case.tools))
    served: dict[str, list[str]] = {name: list(values)
                                    for name, values in recorded.items()}
    built: list[object] = []
    for schema in schemas:
        function = schema.get("function")
        if not isinstance(function, dict):
            continue
        name = str(function.get("name", ""))
        description = str(function.get("description", "") or name)
        parameters = function.get("parameters")
        parameters = parameters if isinstance(parameters, dict) else {
            "type": "object", "properties": {}}

        def make(tool_name: str) -> object:
            async def handler(args: dict[str, object]) -> dict[str, object]:
                sink.append(ObservedCall(name=tool_name, arguments=dict(args)))
                queue = served.get(tool_name) or []
                # The LAST recorded result is reused once the queue drains, rather
                # than falling back to the filler: a model that looks something up
                # twice must not be told the record vanished on the second try.
                raw = queue.pop(0) if len(queue) > 1 else (queue[0] if queue
                                                           else FILLER_RESULT)
                if gateway is not None:
                    call_id = f"live_{len(sink)}"
                    gateway.note({"role": "assistant", "content": "",
                                  "tool_calls": [{"id": call_id, "type": "function",
                                                  "function": {"name": tool_name,
                                                               "arguments": json.dumps(
                                                                   args, ensure_ascii=False)}}]})
                    raw = gateway.push({"role": "tool", "content": raw,
                                        "tool_call_id": call_id, "name": tool_name})
                return {"content": [{"type": "text", "text": raw}]}
            return tool(tool_name, description, parameters)(handler)

        built.append(make(name))
    return built


def options(case: Case, model: str, cap_usd: float, run_id: str, arm: str,
            servers: dict[str, object], allowed: list[str], system: str,
            workdir: str) -> ClaudeAgentOptions:
    """Hermetic options. Everything the CLI could pick up off the filesystem is
    off, and the ONE thing that must be inherited — the keychain credential —
    is inherited because `CLAUDE_CONFIG_DIR` is left alone."""
    env = {key: value for key, value in os.environ.items() if key != "CLAUDECODE"}
    return ClaudeAgentOptions(
        model=model,
        tools=[],                     # no built-in tools: only the case's own
        mcp_servers=servers,
        allowed_tools=allowed,
        strict_mcp_config=True,
        setting_sources=[],
        permission_mode="bypassPermissions",
        system_prompt=system,
        # Three assistant turns per user turn plus slack: a case whose model
        # looks something up, reads the result and then acts spends three on one.
        max_turns=3 * user_turns(case) + 10,
        max_budget_usd=cap_usd,
        session_id=session_id(run_id, case.id, arm),
        cwd=workdir,
        env=env,
    )


async def run_arm(case: Case, arm: str, model: str, cap_usd: float, run_id: str,
                  gateway: LiveGateway | None, timeout_s: float) -> ArmResult:
    """Replay one case's user turns and return what the model did.

    Raises `asyncio.TimeoutError` on the caller's timeout — deliberately NOT
    caught here. A timed-out run has no `ResultMessage` and therefore no measured
    cost, and the only honest thing to do with it is charge the reservation in
    full and record the case incomplete. Swallowing it here would let a partial
    trace be scored as if it were a finished one.
    """
    calls: list[ObservedCall] = []
    recorded = _recorded_results(case)
    system = _system_prompt(case)
    if gateway is not None:
        system = gateway.push({"role": "system", "content": system})
    server = create_sdk_mcp_server(SERVER, tools=_mcp_tools(case, gateway,
                                                            recorded, calls))
    allowed = [_PREFIX + str(schema["function"]["name"])
               for schema in case.tools if isinstance(schema.get("function"), dict)]

    texts: list[str] = []
    result: ResultMessage | None = None
    model_name = model
    workdir = tempfile.mkdtemp(prefix="agentpii2-live-")
    opts = options(case, model, cap_usd, run_id, arm, {SERVER: server}, allowed,
                   system, workdir)

    async def drive() -> None:
        nonlocal result, model_name
        async with ClaudeSDKClient(options=opts) as client:
            for index, message in enumerate(case.messages):
                if message.get("role") != "user":
                    continue
                text = message_text(case, index)
                if gateway is not None:
                    text = gateway.push({"role": "user", "content": text})
                await client.query(text)
                async for reply in client.receive_response():
                    if isinstance(reply, AssistantMessage):
                        turn = "".join(block.text for block in reply.content
                                       if isinstance(block, TextBlock))
                        if turn:
                            texts.append(turn)
                            if gateway is not None:
                                gateway.note({"role": "assistant", "content": turn})
                    elif isinstance(reply, SystemMessage) and reply.subtype == "init":
                        pass
                    elif isinstance(reply, ResultMessage):
                        result = reply
                        if reply.model_usage:
                            # The model the RUN billed, which is not always the
                            # one requested: Claude Code bills a small model for
                            # its own bookkeeping alongside the one under test,
                            # and a result claiming one model when two were
                            # charged is a cost number nobody can reconcile.
                            model_name = max(reply.model_usage.items(),
                                             key=lambda row: float(
                                                 (row[1] or {}).get("costUSD", 0.0)
                                                 if isinstance(row[1], dict) else 0.0))[0]

    await asyncio.wait_for(drive(), timeout=timeout_s)

    if result is None:
        raise RuntimeError(f"{case.id}/{arm}: поток закончился без ResultMessage")
    return ArmResult(
        arm=arm,
        calls=tuple(calls),
        final_text=texts[-1] if texts else "",
        cost_usd=float(result.total_cost_usd or 0.0),
        model=model_name,
        turns=int(result.num_turns),
        duration_ms=int(result.duration_ms),
        is_error=bool(result.is_error),
        subtype=str(result.subtype),
        api_error_status=result.api_error_status,
        errors=tuple(str(one) for one in (result.errors or ())),
        session_id=opts.session_id or "",
        model_usage=dict(result.model_usage or {}),
    )


def strip_prefix(name: str) -> str:
    """`mcp__bench__create_order` -> `create_order`. The prefix is the SDK's
    transport detail; the corpus names the function, and a comparison against a
    transport-decorated name would fail every case for the wrong reason."""
    return name[len(_PREFIX):] if name.startswith(_PREFIX) else name
