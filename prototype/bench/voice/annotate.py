"""Разметка голосового набора: адрес, не адрес, неоднозначно.

ОТКУДА. 122 уникальные реплики из OpenSTT `asr_calls_2_val` — настоящие русские
телефонные звонки, расшифрованные человеком, — отобранные по наличию адресной
лексики. Разметка сделана вручную и глазами; автоматической её сделать нельзя,
потому что весь смысл набора в том, что адресная лексика и адрес — разные вещи.

ТРИ КЛАССА, А НЕ ДВА. «квартира шестьдесят семь» в разговоре диспетчера почти
наверняка часть адреса, а в этой реплике, вырванной из звонка, опознать этого
нельзя. Такие уходят в `неоднозначно` и НЕ участвуют ни в полноте, ни в
точности. Загонять их в один из двух классов значило бы мерить не детектор, а
нашу готовность угадывать.

ЧТО ДЕЛАЕТ ЭТОТ НАБОР ЦЕННЫМ. Негативы здесь настоящие, из той же речи:
«на территории улицы лермонтова понимаете о чем мы» называет улицу и не является
адресом. Ни один генератор такого не построит, потому что для этого надо не
знать заранее, где адрес.

Лицензия исходника — CC BY-NC 4.0: мерить можно, отгружать нельзя. Поэтому здесь
лежат только НОМЕРА строк и метки, а тексты берутся из
~/.cache/pseudex-bench/speech_calls.jsonl, который в репозиторий не попадает.
"""
import json
import sys
from pathlib import Path

# ДВА КЛАССА АДРЕСА, А НЕ ОДИН, и разделяет их закон, а не интуиция.
#
# 152-ФЗ ст. 3 п. 1 называет персональными данными сведения, относящиеся к прямо
# или косвенно ОПРЕДЕЛЁННОМУ или ОПРЕДЕЛЯЕМОМУ лицу. Улица с номером дома
# определяет здание, то есть узкий круг людей. Голая улица — нет: на улице
# Пушкина сотни домов и тысячи жильцов, и она ровно на шаг конкретнее города,
# про который у нас уже записано, что он никого не идентифицирует и не
# маскируется намеренно.
#
# Голая улица становится персональными данными ОДНИМ способом — связкой с полной
# формой, названной в том же разговоре. Продукт это умеет (`link_partial_place`),
# но здесь реплики вырезаны из звонков по одной, и разговора нет по построению.
# Поэтому второй класс меряется отдельно и в правовое число не входит: иначе
# прибор считал бы промахом то, что маскировать не обязан.
#
# Первая разметка не делала этого различия и давала 71% одним числом на две
# разные правовые категории. Раздельно: 94% на том, что является ПД, и 47% на
# том, что ими само по себе не является.
NUMBERED = {13, 18, 23, 32, 46, 47, 58, 60, 71, 72, 85, 89, 95, 103, 109, 110, 117}
BARE_STREET = {7, 11, 20, 29, 31, 34, 42, 62, 64, 65, 69, 77, 106, 107, 108}
UNCLEAR = {2, 4, 28, 59, 67, 75, 78, 82, 90, 92, 97}
# всё остальное — адресная лексика без адреса

# ГРАНИЦЫ АДРЕСА для класса «с номером». Размечены вручную по тексту реплики.
#
# ЗАЧЕМ, ЕСЛИ ЕСТЬ МЕТКА. Метка отвечает «есть ли здесь адрес» — это полнота. Она
# сказала 17/17 и была права, а спаны при этом обрывались: «улица дербенёвская
# двадцать четыре строение пять» находилась без строения, «на рублёвском шоссе
# двадцать шесть корпус три» без корпуса, «бибиревская дом семнадцать» без улицы.
# Найденный наполовину адрес — это утёкшая половина, и в этом проекте полнота и
# покрытие не сливаются в одно число именно поэтому.
#
# Границы — то, что маскировать ОБЯЗАНЫ. Обращения, вводные и то, что человек
# сказал после адреса, в них не входят.
SPANS = {
    13: "улица лермонтова тридцать восемь",
    18: "красная площадь дом один",
    23: "улица дзержинского два дробь восемь",
    32: "петрозаводской улицу восемнадцать",
    46: "двадцать пять а корпус два квартира двадцать семь этаж четвёртый",
    47: "Колпино улица культуры восемь",
    58: "улица лермонтова триц восемь",
    60: "улица дербенёвская двадцать четыре строение пять",
    71: "дом двадцать пять а корпус два",
    72: "рублёвском шоссе двадцать шесть корпус три",
    85: "улицу культуры восемь",
    89: "даев переулок тринадцать",
    95: "москва пушкинская площадь страстной бульвар дом четыре",
    103: "бибиревская дом семнадцать в квартира двести двадцать девять",
    109: "дом три квартира двенадцать",
    110: "улица добролюбова двадцать пять а",
    117: "даев переулок дом тринадцать",
}

CACHE = Path.home() / ".cache" / "pseudex-bench"


def candidates() -> list[str]:
    import re
    rows = [json.loads(line)["text"]
            for line in (CACHE / "speech_calls.jsonl").open(encoding="utf-8")]
    st = re.compile(r"\b(улиц\w*|проспект\w*|переул\w*|бульвар\w*|шоссе|набережн\w*"
                    r"|площад\w*|проезд\w*|микрорайон\w*|мкр|тупик\w*|аллея|квартал\w*)\b",
                    re.IGNORECASE)
    house = re.compile(r"\b(дом|корпус|квартир\w*|подъезд\w*|этаж\w*|строени\w*)\b",
                       re.IGNORECASE)
    seen, out = set(), []
    for row in rows:
        if (st.search(row) or house.search(row)) and row not in seen:
            seen.add(row)
            out.append(row)
    return out


def build() -> list[dict]:
    out = []
    for number, text in enumerate(candidates(), 1):
        if number in UNCLEAR:
            label = "неоднозначно"
        elif number in NUMBERED:
            label = "адрес с номером"
        elif number in BARE_STREET:
            label = "улица без номера"
        else:
            label = "не адрес"
        row = {"n": number, "label": label, "text": text}
        if number in SPANS:
            row["span"] = SPANS[number]
        out.append(row)
    return out


if __name__ == "__main__":
    data = build()
    counts = {}
    for row in data:
        counts[row["label"]] = counts.get(row["label"], 0) + 1
    path = CACHE / "voice_addresses.json"
    path.write_text(json.dumps(data, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"{len(data)} реплик -> {path}")
    for label, count in sorted(counts.items()):
        print(f"   {label:<14} {count}")
