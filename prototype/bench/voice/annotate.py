# ЧИСЛИТЕЛЬНОЕ ИЛИ ЦИФРА — И ЭТО НЕ ЭВРИСТИКА, А ДОКАЗУЕМАЯ НАДМНОЖЕСТВЕННОСТЬ.
# Адрес с номером дома по определению содержит номер, а номер в расшифровке речи
# записан либо цифрой, либо словом. Поэтому фильтр не может спрятать ни одного
# адреса того класса, который мы меряем — в отличие от прежнего, который
# требовал слово-маркер и спрятал двадцать шесть.
#
# Голую улицу без числа он пропустил бы, но её ловят прежние слова-типы, и она
# и так не персональные данные.
_NUM = (r"(?:один|одна|одно|два|две|три|четыре|пять|шесть|семь|восемь|девять|десять"
        r"|одиннадцат|двенадцат|тринадцат|четырнадцат|пятнадцат|шестнадцат|семнадцат"
        r"|восемнадцат|девятнадцат|двадцат|тридцат|сорок|пятьдесят|шестьдесят|семьдесят"
        r"|восемьдесят|девяносто|сто|двести|триста|четыреста|пятьсот|шестьсот|семьсот"
        r"|восемьсот|девятьсот|перв|втор|трет|четв[её]рт|шест|седьм|восьм|девят)")
_NUMBER = re.compile(rf"\b{_NUM}\w*|\d", re.IGNORECASE)
_STREET = re.compile(r"\b(улиц\w*|проспект\w*|переул\w*|бульвар\w*|шоссе|набережн\w*"
                     r"|площад\w*|проезд\w*|микрорайон\w*|мкр|тупик\w*|аллея|квартал\w*)\b",
                     re.IGNORECASE)
_HOUSE = re.compile(r"\b(дом|корпус|квартир\w*|подъезд\w*|этаж\w*|строени\w*)\b",
                    re.IGNORECASE)


def text_key(text: str) -> str:
    """Устойчивый ключ реплики. Хеш, потому что тексты отгружать нельзя."""
    return hashlib.blake2b(text.encode(), digest_size=6).hexdigest()


def _marker_filter(text: str) -> bool:
    """Прежний фильтр — слово-тип улицы или маркер дома.

    Оставлен НЕ для совместимости, а как свидетельство: он и есть тот дефект,
    ради которого набор пересобран, и метка на каждой реплике говорит, какая
    половина набора была видна прибору до этого.
    """
    return bool(_STREET.search(text) or _HOUSE.search(text))


def candidates() -> list[str]:
    rows = [json.loads(line)["text"]
            for line in (CACHE / "speech_calls.jsonl").open(encoding="utf-8")]
    return [row for row in dict.fromkeys(rows)
            if _NUMBER.search(row) or _STREET.search(row) or _HOUSE.search(row)]


def build() -> list[dict]:
    out = []
    for text in candidates():
        key = text_key(text)
        if key in UNCLEAR:
            label = "неоднозначно"
        elif key in NUMBERED:
            label = "адрес с номером"
        elif key in BARE_STREET:
            label = "улица без номера"
        else:
            label = "не адрес"
        # КАКОЙ ФИЛЬТР ВПУСТИЛ РЕПЛИКУ. Расширение набора не имеет права стереть
        # прежнее измерение: `filter == "marker"` выделяет ровно те 122 реплики,
        # на которых считались опубликованные числа, поэтому старую арифметику
        # можно воспроизвести одной строкой, а переход на широкий набор остаётся
        # осознанным решением потребителя, а не побочным эффектом чужой правки.
        row = {"key": key, "label": label, "text": text,
               "pass": 2 if key in PASS2 else 1,
               "filter": "marker" if _marker_filter(text) else "number"}
        if key in NUMBERED:
            row["spans"] = NUMBERED[key]
        out.append(row)
    return out


def main() -> int:
    data = build()
    # КАЖДАЯ МЕТКА ДОЛЖНА НАЙТИ СВОЮ РЕПЛИКУ. Ключ — хеш текста, и если корпус
    # в кеше подменили, метки просто перестанут находиться, а числа останутся
    # правдоподобными. Поэтому это отказ, а не предупреждение.
    found = {row["key"] for row in data}
    lost = (set(NUMBERED) | BARE_STREET | UNCLEAR) - found
    if lost:
        print(f"МЕТКИ БЕЗ РЕПЛИК: {len(lost)} — корпус в кеше не тот",
              file=sys.stderr)
        return 1
    for row in data:
        for span in row.get("spans", ()):
            if span not in row["text"]:
                print(f"СПАН НЕ В ТЕКСТЕ: {span!r}", file=sys.stderr)
                return 1
    path = CACHE / "voice_addresses.json"
    path.write_text(json.dumps(data, ensure_ascii=False, indent=1), encoding="utf-8")
    counts = {}
    for row in data:
        counts[row["label"]] = counts.get(row["label"], 0) + 1
    print(f"{len(data)} реплик -> {path}")
    for label, count in sorted(counts.items()):
        print(f"   {label:<16} {count}")
    values = sum(len(row.get("spans", ())) for row in data)
    print(f"   значений-адресов {values} в {counts.get('адрес с номером', 0)} репликах")
    return 0


