# СКОЛЬКО ЭТОТ НАБОР НА САМОМ ДЕЛЕ ДОКАЗЫВАЕТ.
#
# Ноль ошибок на N фразах не означает точность 100%. Точная односторонняя
# граница Клоппера–Пирсона: истинная доля ошибок не выше 1 - 0.05**(1/N), то
# есть на 42 фразах ноль ошибок сертифицирует лишь «не ниже 93.1%».
#
# ЭТО НЕ ПРИДИРКА, А ИСТОРИЯ ЭТОГО ФАЙЛА. Он существует потому, что golden и
# dirty показывали 100% точности, пока «Счёт 1234 от 15.05.2025» маскировался:
# наборы не были неправы, в них просто не было такого текста. Печатать «100%»
# на 42 фразах — та же ошибка на этаж выше: величина верная, уверенность
# выдуманная. Продукт обещает клиенту 99.4%, и чтобы это ПОДТВЕРДИТЬ, нужно
# 500 чистых фраз, а не сорок две.
TARGET = 0.994


def certified_floor(clean: int, total: int, alpha: float = 0.05) -> float:
    """Нижняя граница точности, которую этот прогон действительно доказывает."""
    if total == 0:
        return 0.0
    if clean == total:
        return alpha ** (1.0 / total)
    from math import comb
    low, high = 0.0, 1.0
    for _ in range(200):
        mid = (low + high) / 2
        tail = sum(comb(total, i) * mid ** i * (1 - mid) ** (total - i)
                   for i in range(clean, total + 1))
        low, high = (mid, high) if tail < alpha / 2 else (low, mid)
    return (low + high) / 2


def phrases_for(target: float, alpha: float = 0.05) -> int:
    """Сколько безошибочных фраз нужно, чтобы подтвердить `target`."""
    from math import ceil, log
    return ceil(log(alpha) / log(target))


def main() -> int:
    testkit.load_dev_bundle()
    detector = Detector()
    def scan(corpus):
        out = []
        for text in corpus:
            spans = [(s.entity_type, s.value) for s in detector.detect(text)]
            if spans:
                out.append((text, spans))
        return out

    # ДВА БЛОКА, ДВА КОНТРАКТА, и это не смягчение, а честность.
    #
    # Написанные руками фразы — деловой и технический русский, где ни одна
    # маска не может быть правильной. Контракт строгий: ноль. Он держится, и
    # красный здесь означает настоящий регресс.
    #
    # Настоящая речь размечена третьей стороной, и в ней встречается то, что
    # правилом не решается: «алиса» — обращение к ассистенту и женское имя,
    # написанные одинаково. Требовать ноль здесь значит требовать
    # контекстного решения, которого у движка нет; набор станет вечно красным,
    # а вечно красный набор перестают читать. Поэтому здесь контракт — ДОЛЯ,
    # и рядом печатается то, что она сертифицирует.
    authored = scan(CLEAN)
    speech = scan(SPEECH_CLEAN)
    touched = authored + speech

    total = len(CLEAN) + len(SPEECH_CLEAN)
    precision = (total - len(touched)) / total * 100
    floor = certified_floor(total - len(touched), total)
    print(f"фраз, написанных руками: {len(CLEAN)}   затронуто {len(authored)}  (контракт: ноль)")
    print(f"фраз настоящей речи:     {len(SPEECH_CLEAN)}  затронуто {len(speech)}")
    print(f"всего:        {total}")
    print(f"затронуто:    {len(touched)}")
    print(f"наблюдаемая точность: {precision:.1f}%   (было 69.2% до правок 16.08)")
    print(f"СЕРТИФИЦИРУЕТ:        не ниже {floor * 100:.1f}%   (95%, точный биномиальный)")
    if floor < TARGET:
        if touched:
            print(f"   Подтверждено {floor * 100:.1f}% при цели {TARGET * 100:.1f}%: не хватает не")
            print(f"   объёма, а чистоты — {len(touched)} ложных срабатывания на {total} фразах.")
        else:
            print(f"   ЧТОБЫ ПОДТВЕРДИТЬ {TARGET * 100:.1f}% НУЖНО {phrases_for(TARGET)} безошибочных")
            print(f"   фраз, сейчас {len(CLEAN)}. Наблюдаемые 100% — это НЕ доказанные 100%.")

    if touched:
        print("\n--- ЛОЖНЫЕ СРАБАТЫВАНИЯ ---")
        for text, spans in touched:
            print(f"  {text}")
            print(f"      -> {spans}")

    # Красный — либо тронутая авторская фраза, либо доля ниже обещанной клиенту.
    # Недобор СЕРТИФИКАЦИИ красным не делает: это утверждение о размере выборки,
    # а не о продукте, и его чинят фразами, а не кодом.
    return 1 if authored or precision < TARGET * 100 else 0


