"""ГОЛОВА АДРЕСА — город, регион, район и начало названия внутри спана.

ЧТО ЭТОТ ФАЙЛ ЗАКРЫВАЕТ. Колонка ПОКРЫТИЯ на PII-Bench стояла на 88.6% при
полноте 93.2%: значение находилось, но его ГОЛОВА уходила к модели открытым
текстом внутри спана, который прибор уже считал найденным. Двенадцать значений
из 176 — это ровно те, что перечислены ниже; каждое взято ЦЕЛИКОМ, вместе с
окружающей репликой корпуса, чтобы красное нельзя было получить на выдуманной
строке.

ТРИ КЛАССА, И ВСЕ ТРИ — ОДИН И ТОТ ЖЕ ПРОМАХ:
  1. город / регион / район перед адресом: «омск, карла маркса 102», «екб,
     луначарского 156», «подмосковье, люберцы пр-т гагарина 15», «Владимир,
     Большая Московская, 14», «Санкт-Петербург, Васильевский остров, Средний
     проспект, 56, кв 89»;
  2. улица БЕЗ слова «улица», но с домом: «Арбат 25», «карла маркса 102»,
     «Космонавтов 4», «мельникайте 12», «куйбышева 22», «Большая Московская,
     14»;
  3. косвенная форма: «варшавке 24к3» — дательный, разобранный через
     `morph_places.to_nominative` и ГАР-стем, а не списком падежей.

ЧТО ФАЙЛ ЗАЩИЩАЕТ ОТ РЕГРЕССА, И ЭТО ВАЖНЕЕ ПЕРВОЙ ПОЛОВИНЫ.
  * ГОЛЫЙ ТОПОНИМ — НЕ ПЕРСОНАЛЬНЫЕ ДАННЫЕ. «Проживаю в Москве», «Я из
    Казани», «Офис в Екатеринбурге работает до 18:00» остаются
    незамаскированными: поглощение головы включается ТОЛЬКО когда в спане уже
    есть улица И дом. Это тот же инвариант, что пиннит test_overmasking.py.
  * ЧЕЛОВЕК ПЕРЕД АДРЕСОМ — ЧЕЛОВЕК. «Иван Петров улица Ленина 5»: «Петров» —
    фамилия в именительном, а не половинка названия улицы, и он обязан
    остаться NAME. Прилагательное, продолжающее название, — относительное
    («Васильевский остров»); притяжательное («Петров») им не является.
  * ИМЯ В ИМЕНИТЕЛЬНОМ ПЕРЕД ФАМИЛИЕЙ — НЕ «Карла Маркса». Название улицы
    ставит первое слово в РОДИТЕЛЬНЫЙ («Карла», «Фридриха», «Розы»); «Иван
    Петров» — именительный, и это человек.
  * ПОДСКАЗКА НЕ ДЕЛАЕТ АДРЕС. «счёт на Гагарина» — фамилия, не улица.

ЗАМЕР. `bench/eval_piibench.py` на этом дереве: ADDRESS покрытие 88.6% -> 95.5%
(156 -> 168 из 176), полнота 93.2% -> 95.5%; остальные восемь значений — голый
склонённый город в фразе о проживании, пиннутый негатив, а не промах.

Запуск из `prototype/`:
    .venv/bin/python test_address_head.py
"""

from __future__ import annotations

import testkit

testkit.load_dev_bundle()

from pseudex.detect_all import Detector  # noqa: E402

# Голова адреса обязана быть ВНУТРИ спана. Каждая строка — настоящая реплика
# PII-Bench из колонки ПОКРЫТИЕ 88.6%.
_HEAD: list[tuple[str, str, str]] = [
    ("PII-Bench 27", "подмосковье, люберцы пр-т гагарина 15",
     "адрес ихний в подмосковье, люберцы пр-т гагарина 15 — реально доедешь или это промзона?"),
    ("PII-Bench 38", "Арбат 25",
     "привезите на Арбат 25 это Юлия Смирнова тел +7 925 111 22 33"),
    ("PII-Bench 53", "Космонавтов 4",
     "Алла Тихонова номер 8 926 555 77 88 Космонавтов 4"),
    ("PII-Bench 119", "Владимир, Большая Московская, 14",
     "жду вас завтра в 10 утра, наш офис находится Владимир, Большая Московская, 14"),
    ("PII-Bench 130", "тюмень, мельникайте 12, кв 8",
     "привезите посылку на адрес тюмень, мельникайте 12, кв 8, норм?"),
    ("PII-Bench 139", "Санкт-Петербург, Васильевский остров, Средний проспект, 56, кв 89",
     "электрик придет в среду утром, адрес Санкт-Петербург, Васильевский остров, "
     "Средний проспект, 56, кв 89"),
    ("PII-Bench 141", "екатеринбург, куйбышева 22, кв 3",
     "привезите плз на екатеринбург, куйбышева 22, кв 3"),
    ("PII-Bench 143", "Воронеж, улица 20-летия Октября, дом 45, квартира 67",
     "Адрес места жительства: Воронеж, улица 20-летия Октября, дом 45, квартира 67"),
    ("PII-Bench 161", "Омск, улица 10 лет Октября, 45, подъезд 3, кв 67",
     "мастер выезжает сегодня днем, адрес Омск, улица 10 лет Октября, 45, подъезд 3, кв 67"),
    ("PII-Bench 171", "екб, луначарского 156, кв 89",
     "доставка на екб, луначарского 156, кв 89, плз"),
    ("PII-Bench 176", "омск, карла маркса 102, кв 15",
     "доставьте посылку срочно на омск, карла маркса 102, кв 15, спс"),
    # Косвенная форма: дательный падеж улицы, которой в ГАР нет, но чей
    # именительный стем там есть («Варшава»).
    ("PII-Bench 25", "варшавке 24к3",
     "адрес ихний на варшавке 24к3 реально существует или это фиктивный офис?"),
]

# ГОЛЫЙ ТОПОНИМ: ни одного символа внутри перечисленного слова.
_BARE_PLACE: list[tuple[str, str, str]] = [
    ("голый город", "Екатеринбурге", "Офис в Екатеринбурге работает до 18:00."),
    ("голый город", "Москве", "Проживаю в Москве, готов приезжать в офис."),
    ("голый город", "Казани", "Добрый день! Я Игорь Волков из Казани, рассматриваю вакансию."),
    ("голый город", "Новосибирске", "хотела бы узнать больше о вакансии бухгалтера. Живу в Новосибирске."),
    ("голый регион", "подмосковье", "доставка по подмосковье обсуждается отдельно"),
    ("голый город", "Тюмени", "Я живу в Тюмени уже десять лет"),
    # Сокращение города само по себе — тем более не адрес.
    ("сокращение города", "екб", "склад в екб закрыт на инвентаризацию"),
]

# ПОДСКАЗКА ЛИЦЕНЗИРУЕТ СОСЕДА, НО НЕ НАЗЫВАЕТ ЕГО. «счёт на Гагарина» — счёт
# на человека; адресом это не становится.
_TYPE: list[tuple[str, str, str, str]] = [
    ("человек перед адресом", "Иван Петров", "LOC", "Иван Петров улица Ленина 5"),
    ("человек перед адресом", "Петрова", "LOC", "курьер Петрова улица Садовая 3"),
    ("подсказка счёта", "Гагарина", "LOC", "счёт на Гагарина"),
    ("имя в именительном", "Владимир Петров", "LOC", "Владимир Петров родился 5 мая 1980 года"),
]


def _spans(detector: Detector, text: str):
    return [(span.entity_type, span.start, span.end) for span in detector.detect(text)]


def _covered(text: str, spans, gold: str) -> bool:
    start = text.index(gold)
    end = start + len(gold)
    cov: set[int] = set()
    for _, span_start, span_end in spans:
        cov |= set(range(max(start, span_start), min(end, span_end)))
    return len(cov) == end - start


def main() -> int:
    detector = Detector()
    rows: list[tuple[str, str, bool, str]] = []

    for section, gold, text in _HEAD:
        spans = _spans(detector, text)
        rows.append((section, f"голова внутри спана: {gold!r}",
                     _covered(text, spans, gold), f"spans={spans}"))

    for section, word, text in _BARE_PLACE:
        spans = _spans(detector, text)
        rows.append((section, f"{word!r} не замаскирован",
                     not _covered(text, spans, word), f"spans={spans}"))

    for section, word, forbidden, text in _TYPE:
        spans = _spans(detector, text)
        typed = [kind for kind, start, end in spans
                 if kind in ("LOC", "ADDR")
                 and start < text.index(word) + len(word) and text.index(word) < end]
        rows.append((section, f"{word!r} не читается адресом",
                     not typed, f"spans={spans}"))

    bad = 0
    section = ""
    for name_section, name, ok, detail in rows:
        if name_section != section:
            print(f"\n[{name_section}]")
            section = name_section
        if ok:
            print(f"  PASS  {name}")
        else:
            bad += 1
            print(f"  RED   {name}\n        {detail}")

    print(f"\naddress_head: {len(rows) - bad}/{len(rows)} проверок пройдено")
    if bad:
        print("ГОЛОВА АДРЕСА НЕ В СПАНЕ: часть значения уходит к модели открытым "
              "текстом внутри спана, который прибор считает найденным.")
    return 1 if bad else 0


if __name__ == "__main__":
    raise SystemExit(main())
