"""Одна точка, где запрос считается и где за него списывается ёмкость.

ДВА СЧЁТЧИКА В РАЗНЫХ МЕСТАХ РАЗЪЕХАЛИСЬ ДВАЖДЫ, И ОБА РАЗА НЕЗАМЕТНО.

  * `record_request` появился на сайдкаре и был забыт на прокси-леге — каждый
    клиент той формы поставки сообщал `{"requests": 0}` навсегда. Комментарий
    рядом с исправлением сохранился: «Counted here too, and it was not».
  * `consume` появился позже и был забыт ТАМ ЖЕ. Прокси — это форма, которую
    промпт на `/welcome` выдаёт клиенту первой, то есть ёмкость не расходовал
    основной путь продажи.

Плюс на сайдкаре `consume` стоял ДО разбора тела, так что запрос, отвергнутый
валидацией с четырёхсоткой, списывал ёмкость.

Одна функция чинит оба класса разом и делает инвариант греп-проверяемым:
`grep -c 'metering.bill(' pseudex/` обязан равняться числу легов, и оба
счётчика двигаются одной строкой.
"""

from pseudex.audit import AuditLog
from pseudex.license import LicenseClient


def bill(audit: AuditLog, license_client: LicenseClient, org_id: str,
         agent_id: str) -> None:
    """Один обслуженный запрос: посчитать и списать.

    Зовётся ПОСЛЕ успешного маскирования и никогда до: маскирование
    fail-closed, поэтому запрос, который упал, был заблокирован и до модели не
    дошёл. Брать за него деньги значило бы взять за единственный исход, который
    клиент не получил.
    """
    audit.record_request(org_id, agent_id)
    license_client.consume()
