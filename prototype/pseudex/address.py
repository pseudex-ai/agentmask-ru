# Natasha's AddrExtractor is a Yargy grammar, and it is EXPENSIVE: measured at
# ~137 ms per 1000 characters, ~100% of it inside the rule automaton (the morph
# tokenizer is 0.02 ms). It costs ~7 ms even on English text containing no
# address at all — the cost is a function of length, not of content. In the stage
# profiler it was 84% of total masking time.
#
# Against that: ablation across three independently-seeded address benchmarks
# (712 addresses) plus the dirty set with hard negatives found it contributes
# ZERO additional entities — the regex + morphology arms already caught every
# one, at 1/8th the cost.
#
# PSEUDEX_ADDR_EXTRACTOR:
#   off     (default) regex + morphology only — fast
#   on                union with the extractor — the original behaviour
#   shadow            union is used for MASKING (so recall is never reduced),
#                     and anything only the extractor found is logged at WARNING
#
# `shadow` is how you earn the right to run `off` in production: the benchmarks
# here are synthetic and generated by this repo, so they may share blind spots
# with the regex arm. Run `shadow` at a canary; if the log stays silent on real
# traffic, `off` is safe. Never infer that from the synthetic sets alone —
# dropping a recall arm from a fail-closed gateway is a one-way door.
_MODE = os.environ.get("PSEUDEX_ADDR_EXTRACTOR", "off").lower()
if _MODE not in ("off", "on", "shadow"):
    raise ValueError(
        f"PSEUDEX_ADDR_EXTRACTOR must be off|on|shadow, got {_MODE!r}"
    )

USE_EXTRACTOR = _MODE in ("on", "shadow")
SHADOW = _MODE == "shadow"

# Built lazily and only when actually used: constructing MorphVocab loads
# dictionaries into every worker process, so `off` should not pay that in memory
# or in startup time either.
_EXTRACTOR = None
_EXTRACTOR_LOCK = threading.Lock()


def _extractor():
    global _EXTRACTOR
    if _EXTRACTOR is None:
        with _EXTRACTOR_LOCK:
            if _EXTRACTOR is None:
                from natasha import AddrExtractor, MorphVocab
                _EXTRACTOR = AddrExtractor(MorphVocab())
    return _EXTRACTOR

# The street gazetteer, the core-part vocabulary and every pattern below are
# LEASED (see pseudex/assets.py) — this module holds the rules that consume them,
# not the vocabulary itself. Patterns are compiled once when the bundle loads.
_WORD_SPLIT_RE = re.compile(r"[\s-]")


def _part_is_core(part_type: str, address: AddressAssets) -> bool:
    return any(key in part_type for key in address.core_part)


def _word_is_street(word: str, address: AddressAssets) -> bool:
    low = word.lower()
    if low in address.street_gaz:
        return True
    tag = MORPH.parse(word)[0].tag
    if "Name" in tag and "Surn" not in tag:  # a bare first name is not a street
        return False
    # A SETTLEMENT IS NOT A STREET, and a house number does not attach to one.
    # «погода в Сочи 25 градусов» and «курс в Сочи 25 рублей» became addresses
    # because `Geox` alone was accepted — but Geox is what names a CITY, and a
    # city with a number after it is a temperature or a price, never a door.
    # Street names that happen to be toponyms carry another reading too:
    # «Тверская» is ADJF, «Ленина» and «Гагарина» are Surn. Only a word whose
    # ONLY reading is a place is refused.
    if "Geox" in tag and "Surn" not in tag and "ADJF" not in tag:
        return False
    if "ADJF" in tag or "Geox" in tag:
        return True
    # A SURNAME NAMES A STREET ONLY IN THE GENITIVE SINGULAR — the rule
    # `_street_shape` states and applies, and that this function did not.
    # «Букин Сергей 14.03.1987» came out as ONE LOC span «Букин Сергей 14»:
    # the person was masked as a STREET, «.03.1987» went to the model in the
    # clear, and the tool received «улица Кедровая 6.03.1987». Reproduced on
    # every name tried — «Иванов Пётр 05.05.1990», «Соколова Анна 21.09.1980»
    # — and it is the commonest shape in which an agent is given a patient or
    # a passenger: name plus date of birth, no comma. Lower case was already
    # right, because the lower-case arms ask the vocabulary instead.
    #
    # The same lesson was learned once for `_street_shape` («морозов 10»,
    # «кузнецов 12», «Артём Громов 8») and applied there only. One rule, one
    # function: the genitive PLURAL does not count either, which is what let
    # «Букин» through — pymorphy reads it as the genitive plural of an
    # invented «Букины».
    return _street_shape(word)


def _lower_is_street(phrase: str, address: AddressAssets) -> bool:
    """Street-name decided by VOCABULARY ALONE, for text with no capitals.

    Deliberately not `_is_street_name`: that one also accepts a morphological
    reading, which is the right trade when a capital letter is carrying half the
    evidence and the wrong one when it is not. Lower-case Russian prose is full
    of words pymorphy calls an adjective or a surname.
    """
    for word in _WORD_SPLIT_RE.split(phrase):
        low = word.lower()
        if not low or low not in address.street_gaz:
            continue
        # A MONTH NAMES A STREET ONLY BEHIND A NUMBER. «марта», «мая» and
        # «октября» are in the street vocabulary for «8 Марта» and «1 Мая», and
        # in lower case with no number they are simply dates: «14 марта ему
        # исполнилось 60» became an address on the strength of that entry alone.
        # The numbered form has its own pattern (`numbered_st`), which requires
        # the number, so excluding them here costs nothing and closes the only
        # place the vocabulary lies.
        if low in address.month_after or low in ("года", "год", "лет"):
            continue
        return True
    return False




def _bare_street_anchor(text: str, start: int, address: AddressAssets) -> bool:
    """Якорь ВПЛОТНУЮ перед словом — адресная подсказка или «на»/«по».

    ДВА СУЖЕНИЯ, ОБА ИЗМЕРЕНЫ, и оба нужны.

    1. ПОДСКАЗКА ДОЛЖНА СТОЯТЬ ВПЛОТНУЮ, а не где-то в клаузе. `_intent_before`
       спрашивает «есть ли в предложении слово об адресе» — и «посылку примет
       громова марина» отвечает «да» на «посылк», после чего ADDR (4) старше
       NAME (3) съедал найденную пару «громова марина» и оставлял улицу из
       фамилии. Здесь подсказка обязана КОНЧАТЬСЯ там, где начинается слово:
       «адрес репина», «адрес: репина» — да; «посылку примет громова» — нет.
    2. НЕЧЁТКОЕ ПРОЩЕНИЕ ОПЕЧАТОК НЕ УЧАСТВУЕТ. У `_intent_before` есть
       половина `_fuzzy_intent`, которая прощает одну опечатку в ЛЮБОМ слове и
       отвечает «да» на «поставь будильник»; у ветки, чей единственный
       структурный сигнал — это слово, такой степени свободы нет.
    """
    tail = text[max(0, start - _CUE_WINDOW):start]
    for found in address.addr_ctx.finditer(tail):
        # ХВОСТ ПОСЛЕ ПОДСКАЗКИ — ТОЛЬКО РАЗДЕЛИТЕЛЬ. Иначе подсказка стоит не
        # вплотную, а «где-то раньше».
        if not tail[found.end():].strip(" \t:.,;—–-"):
            return True
    return bool(address.street_nohouse_prep.search(tail))


def _bare_names_a_street(word: str, address: AddressAssets) -> bool:
    """Слово в РЕЕСТРЕ ГАР — и не месяц, назвавший улицу лишь за числом."""
    low = word.lower()
    if low not in address.street_gaz and low not in address.street_names:
        return False
    if low in address.month_after or low in ("года", "год", "лет"):
        return False
    return True


def _bare_street_morphology(word: str) -> bool:
    """Морфология читает слово как НАЗВАНИЕ МЕСТА, а не как обычный NOUN.

    Тот же тест, которым `_lower_names_a_street` судит слово рядом со
    словом-типом, но БЕЗ словарного ярлыка: у ГАР он есть у всех, и именно
    поэтому он здесь ничего не решает. Решает чтение — фамилия, топоним или
    относительное прилагательное. «репина» и «бибиревская» проходят, «правды»,
    «труда», «строителей», «победы» (NOUN,inan) — нет.
    """
    parses = MORPH.parse(word)
    if not parses:
        return False
    # ВСЕ ЧТЕНИЯ, СТОЯЩИЕ ВРОВЕНЬ С ПЕРВЫМ, и только они: победитель среди
    # равных произволен («марину» — мужчина Марин и женщина Марина, 0.500/0.500).
    best = max(parse.score for parse in parses)
    top = [parse for parse in parses if parse.score >= best]
    # «репина», «ленина», «гагарина» — родовое чтение фамилии на первом месте;
    # «московский» — прилагательное с фамильным чтением на 0.25, то есть проза
    # («на московский вокзал»), а не улица. «правды», «труда», «строителей» —
    # обычное существительное в родительном.
    #
    # ЧТЕНИЕ ПОСЕЛЕНИЯ (Geox) НЕ СЧИТАЕТСЯ, и это измерено: ГАР содержит и
    # названия городов («самара», «москва»), а голая топонимика — не улица
    # вовсе, у неё своя ветка и своё правило («голый топоним не ПД»). Приняв
    # Geox, эта ветка захлопывала `test_product`: «курьера на луговая 10 это в
    # самара» превращалось в ОДИН адрес с подменённым городом.
    if any("Surn" in parse.tag.grammemes for parse in top):
        return True
    # ЖЕНСКИЙ РОД И ИМЕНИТЕЛЬНЫЙ — СОГЛАСОВАНИЕ С «УЛИЦЕЙ»: «бибиревская»,
    # «заречная», «школьная». Регистр ГАР хранит ИМЕНИТЕЛЬНУЮ форму, поэтому
    # косвенные формы прозы («на новой», «на школьной») сюда не доходят вовсе —
    # отсекается ровно то, что согласуется с пропущенным существительным.
    return any("ADJF" in parse.tag and "femn" in parse.tag and "nomn" in parse.tag
               for parse in top)


def _names_a_settlement(phrase: str, address: AddressAssets) -> bool:
    """Whether every word here names a PLACE and nothing else.

    A city takes no house number. «погода в Сочи 25 градусов», «курс в Сочи 25
    рублей», «в Москве 12 филиалов» and «доставка по Казани 3 дня» all became
    addresses, and all four were licensed by nothing more than the preposition
    in front — `prep_before` is accepted as context on its own, so the
    morphological test never ran.

    So this is a veto rather than a vote: whatever the context says, a
    settlement plus a number is a temperature, a price or a count, never a door.
    Street names that happen to be toponyms are untouched, because they carry a
    second reading — «Тверская» is ADJF, «Ленина» and «Гагарина» are Surn — and
    only a word whose ONLY reading is a place is refused.
    """
    words = [word for word in _WORD_SPLIT_RE.split(phrase) if word]
    if not words:
        return False
    for word in words:
        if word.lower() in address.street_gaz:
            return False
        # EVERY READING, not the best one. «Тверская» has a Geox reading that
        # outranks its adjectival one, so `parse[0]` refused a real street — the
        # same trap that made «марину» resolve to a man. A word is a settlement
        # only when NOTHING it can be is a surname or an adjective.
        parses = MORPH.parse(word)
        if not any("Geox" in parse.tag for parse in parses):
            return False
        if any("Surn" in parse.tag or "ADJF" in parse.tag for parse in parses):
            return False
    return True


def _lower_names_a_street(phrase: str, address: AddressAssets) -> bool:
    """Whether a lower-case word beside a street-type word can be its NAME.

    Needed only where no house number stands to hold the match down. «улица была
    пустой» is the shape this refuses, and it refuses it the same way the city
    adjective is judged: a QUALITATIVE adjective describes a street, a relative
    one names it. «пустой», «длинной», «главной», «новой», «красивой» and
    «широкой» are all Qual; «тверской», «центральной» and «садовой» are not.
    Pronominal readings («нашей», «этой») go out with `Apro`.

    The vocabulary path stays first, because the commonest Russian street names
    are genitive nouns with no adjective reading at all — «мира», «ленина»,
    «строителей».
    """
    for word in _WORD_SPLIT_RE.split(phrase):
        low = word.lower()
        if not low:
            continue
        # BOTH VOCABULARIES, and the second one arrived later than this line.
        # `street_gaz` is the seed list — nineteen entries — and `street_names`
        # is the ГАР register at 65 768. The docstring below has always said the
        # vocabulary path comes first; it was reading the wrong vocabulary, so
        # «улицу культуры восемь» failed on a street the register knows, while
        # «улица лермонтова тридцать восемь» passed only because morphology
        # happens to read «лермонтова» as a surname.
        #
        # Widening a gate that guards the arms with NO house number is exactly
        # the move CLAUDE.md warns about — but both callers carry a second
        # signal: `street_lower_nohouse` also demands an intent word, and the
        # spoken arms demand a spelled number after the name. The vocabulary is
        # never alone here.
        if low in address.street_gaz or low in address.street_names:
            return True
        parses = MORPH.parse(word)
        if any("Surn" in parse.tag or "Geox" in parse.tag for parse in parses):
            return True
        adjectives = [parse for parse in parses if "ADJF" in parse.tag]
        if adjectives and all("Qual" not in parse.tag and "Apro" not in parse.tag
                              for parse in adjectives):
            return True
    return False


_PART_AFTER_RE = re.compile(
    r"^\s*(?:[а-яё]+\s+)?(?:подъезд|корпус|квартир|этаж|строени|дом|литер)", re.IGNORECASE)
_NEXT_WORD_RE = re.compile(r"[а-яё]+", re.IGNORECASE)


def _gar_reaches(word: str, address: AddressAssets) -> bool:
    """The ГАР register names this word, as written or through morphology.

    Three forms, the same three `_fuzzy_street_candidates` allows: the register
    stores nominatives («Клубная») and speech says them as written, but it also
    stores genitives that ARE the name («Котовского», «Победы»), and a spoken
    address inflects neither.
    """
    low = word.lower()
    if low in address.street_names or low in address.street_gaz:
        return True
    for parse in MORPH.parse(word):
        # A SHORT ADJECTIVE DOES NOT REACH THE REGISTER. «репна» — «Репина»
        # with a letter dropped — is the short form of «репный», its lemma
        # lands on a real street, and the word was then judged as a register
        # street by its shape (which a short adjective fails) instead of as
        # the typo it is. Only full forms take the lemma road.
        if parse.tag.POS in _NEVER_A_STREET_POS:
            continue
        if parse.normal_form in address.street_names:
            return True
        nominative = parse.inflect({"nomn"})
        if nominative is not None and nominative.word in address.street_names:
            return True
    return False


def _register_vouches(word: str, address: AddressAssets) -> bool:
    """The register names EXACTLY this form, so no case question is asked."""
    low = word.lower()
    return low in address.street_names or low in address.street_gaz


def _in_the_nominative(word: str) -> bool:
    """The word is written in the NOMINATIVE — the form the register stores.

    ГАР keeps «Маросейка», «Плющиха», «Клубная» in the nominative, and speech
    says a bare street that way too. A word the veto must keep refusing stands in
    the oblique case after its preposition — «погода в Сочи», «доставка в Сочи 3
    дня» — and that is the shape `_names_a_settlement` was written against.
    Indeclinable words («сочи») have no nominative form of their own, and their
    principal reading is locative: excluding them from the relaxation keeps the
    veto, which is the safe direction.
    """
    parses = MORPH.parse(word)
    return bool(parses) and parses[0].tag.case == "nomn"


def _street_shape(word: str) -> bool:
    """A Russian street name is a NOMINATIVE ADJECTIVE or an OBLIQUE NOUN.

    The grammar is the whole rule, and it is not a coincidence: the name agrees
    with «улица» when it is an adjective («улица Клубная» → «клубная»), and
    stands in the genitive when it is a noun («улица Победы» → «победы»,
    «улица Барышникова» → «барышникова»). Both halves are load-bearing:

      * an oblique adjective is a word agreeing with something else in the
        sentence — «общего 23» — unless a preposition put it there, which the
        caller checks separately;
      * a NOMINATIVE noun is a thing, not a street. «время двадцать двадцать
        один» is a clock, «школа двести десять» a school number, «вышка триста
        тридцать три» a radio call sign, and «путин четыре» a person — all four
        are in the leased register as written, and all four were masked as
        addresses until the case was asked for.

    A surname is the same rule seen from the other side: a street named after a
    person is «Ленина», «Гагарина», «Барышникова» — genitive, always. «Путин»
    nominative names the man.
    """
    parses = MORPH.parse(word)
    if any("ADJF" in parse.tag and parse.tag.case == "nomn" for parse in parses):
        return True
    if any("Geox" in parse.tag for parse in parses):
        return True
    # ФАМИЛИЯ НАЗЫВАЕТ УЛИЦУ ТОЛЬКО В РОДИТЕЛЬНОМ ЕДИНСТВЕННОГО, и это
    # утверждение стояло абзацем выше, а код принимал ЛЮБОЙ падеж. «морозов 10»,
    # «кузнецов 12», «Артём Громов 8» — человек и номер, — читались как адрес, и
    # спан LOC съедал имя целиком: один человек и одно место сливались в одну
    # подмену, а в аргумент «имя» уходил адрес.
    #
    # Родительное МНОЖЕСТВЕННОГО не считается: у «морозов» оно есть («улица
    # Морозов» не существует, существует «улица Морозова»), и именно оно
    # пропускало самый частый случай. «Станкевич» остаётся неоднозначным честно
    # — у несклоняемой фамилии все падежи совпадают, и разделить их нечем.
    return any("Surn" in parse.tag and parse.tag.case == "gent"
               and parse.tag.number == "sing" for parse in parses)


def _is_numeral(word: str) -> bool:
    """The word IS a number, so it cannot be the name standing before one.

    Eight of the ten Russian digit-words are literal entries in the ГАР register
    — «Семь Ветров», «Пятая Парковая», «Первая» — and every one of them is a
    legitimate street. But in speech every digit is a word, so a dictated order
    number presents as exactly the shape this arm looks for: «номер заказа шесть
    семь восемь девять» read as the street «шесть» at house «семь восемь», and
    «телефон восемь девять один шесть шесть четыре шесть» became an address
    instead of a phone.

    Those are the values that must reach the tool IN THE CLEAR — a track number,
    an invoice, a contract — so masking them does not leak, it breaks the call.

    Same rule the months already carry, for the same reason and with the same
    cost: a numeral names a street only INSIDE a longer name, and every such name
    has a second word this one-word arm never sees. `Anum` covers the ordinals
    («Первая», «Пятая»), `NUMR` the cardinals.

    NOT VISIBLE TO A SINGLE WRITTEN CORPUS WE OWN. NEREL, `test_overmasking` and
    news prose all write digits as digits, so a run of spelled-out numbers cannot
    occur in them and this whole class is structurally unreachable — the same
    blindness the voice benchmark's own selection filter had.
    """
    # A KNOWN reading only. Numerals are a closed class, and a PREDICTED numeral
    # reading is a mistyped word that happens to end like one — «толстго» read
    # as «тридцатого» — which then refused a real address as a number.
    return any(parse.is_known and ("NUMR" in parse.tag or "Anum" in parse.tag)
               for parse in MORPH.parse(word))


def _never_oblique(word: str) -> bool:
    """A noun with no genitive reading at all cannot be a street name.

    Russian names a street after a thing IN THE GENITIVE — «улица Победы»,
    «улица Труда», «улица Барышникова»: the name is what the street belongs to.
    A word that has no genitive form is a thing standing next to a number:
    «школа двести десять» is a school, «вышка триста тридцать три» a radio call
    sign, «время двадцать двадцать один» a clock. All three ARE in the leased
    register — they name streets somewhere — which is precisely why the register
    on its own cannot decide this, and why the relaxation it earns behind a
    spelled number needs this floor under it.

    An adjective is exempt: it agrees with «улица» and is nominative by
    construction, so asking it for a genitive would refuse every «клубная».
    """
    parses = MORPH.parse(word)
    if any("ADJF" in parse.tag and parse.tag.case == "nomn" for parse in parses):
        return False
    return not any(parse.tag.case == "gent" for parse in parses)


def _plural_or_pronoun(word: str) -> bool:
    """A street is never plural, and «своей» does not name one.

    «за последние тридцать», «первые 50», «необходимых 68» all reached the
    register through a normal form and were held down by nothing else.
    """
    parses = MORPH.parse(word)
    if not parses:
        return False
    numbers = [parse.tag.number for parse in parses if parse.tag.number]
    if numbers and all(number == "plur" for number in numbers):
        return True
    return all("Apro" in parse.tag for parse in parses)


def _counts_next_word(text: str, end: int, number: str,
                      address: AddressAssets) -> bool:
    """The numeral GOVERNS the next word — so it is a quantity, not a door.

    Russian numerals decide the case of what they count: «один день» takes the
    nominative, «два дня» the genitive singular, «восемь обвиняемых» the
    genitive plural. A house number governs nothing; after it comes the end of
    the utterance, the next part of the address, or a verb.

    Agreement, not a word list. A list would have to be extended with every
    Russian noun, and «ограничения свободы один день» is what that costs: a
    genitive-only veto did not fire, because after «один» the noun stands in
    the nominative.
    """
    tail = text[end:end + 24].lstrip()
    # ЛИТЕРА ДОМА — НЕ СЧИТАЕМОЕ СЛОВО. «химзаводская 81 б»: одна буква после
    # номера читается морфологией как существительное в родительном, гейт видел
    # согласование и отвергал адрес ЦЕЛИКОМ — то есть настоящий адрес с литерой
    # не находился вовсе и уходил к модели открытым текстом. Дом с литерой —
    # обычная городская форма, и остальные ветки её давно знают: `_LITERA` стоит
    # в каждой из них.
    #
    # Буква пропускается, и судится то, что стоит ЗА ней: «81 б первый подъезд»
    # остаётся адресом, «81 б рублей» — нет.
    litera = _LITERA_AFTER_NUMBER.match(tail)
    if litera is not None:
        tail = tail[litera.end():].lstrip()
    match = _NEXT_WORD_RE.match(tail)
    if match is None:
        return False
    # THE ADDRESS PART IS JUDGED ON THE TAIL, NOT THE FIRST WORD. Russian
    # dispatch says «второй подъезд» — the ordinal comes BEFORE the marker — and
    # a veto reading only «второй» threw away thirteen real addresses.
    if _PART_AFTER_RE.match(tail) or _opens_address_part(tail, address):
        return False
    last = number.split()[-1].lower()
    if last in ("один", "одна", "одно"):
        want_case, want_number = "nomn", "sing"
    elif last in ("два", "две", "три", "четыре"):
        want_case, want_number = "gent", "sing"
    else:
        want_case, want_number = "gent", "plur"
    # AN UNKNOWN WORD AGREES WITH EVERYTHING AND IS EVIDENCE OF NOTHING. For
    # «этоо» pymorphy returns the whole paradigm at one score, so the numeral
    # «девять» found its genitive plural and «калашникова девять» was refused as
    # an address — and typed as a PERSON instead (live v4, 5 of 42 `compare`).
    # The same discipline the fuzzy street arm applies: a guess about a word
    # morphology does not know is not a signal.
    parses = MORPH.parse(match.group(0))
    if not parses or not parses[0].is_known:
        return False
    # A PRONOMINAL ADJECTIVE IS NOT A COUNTED THING. «добролюбова сорок один
    # это в сарапуул»: «это» reads as the neuter of «этот», agrees with «один»
    # in the nominative, and the customer's street went to the model as a
    # person. «это», «такой», «мой» open the next clause; they count nothing.
    return any(parse.tag.POS in ("NOUN", "ADJF", "PRTF") and "Apro" not in parse.tag
               and parse.tag.case == want_case and parse.tag.number == want_number
               for parse in parses)


def _opens_address_part(tail: str, address: AddressAssets) -> bool:
    """Открывается ли хвост АДРЕСНОЙ ЧАСТЬЮ — по арендованному словарю маркеров.

    `_PART_AFTER_RE` рядом перечисляет маркеры сам, и только в ПОЛНОЙ форме, а
    чат и JSON пишут их сокращённо: «армейская 16 кв 4» не находилось вовсе —
    «кв» читается морфологией как существительное в родительном, согласование с
    «16» находилось, и вето отвергало адрес ЦЕЛИКОМ. «армейская 16 квартира 4»
    при этом работало. Утечка стоила квартиры, подъезда и всего адреса разом.

    Второго списка здесь быть не должно: `apt` и `spoken_apt` арендованы, знают
    каждое сокращение («кв», «эт», «стр», «корп», «оф», «пом») и требуют после
    маркера ЧИСЛО — поэтому «рублей 500», «гектаров 5» и «филиалов 7» через них
    не проходят, а именно они и есть то, ради чего вето существует.
    """
    return (address.apt.match(tail) is not None
            or address.spoken_apt.match(tail) is not None)


def _is_street_type(word: str, address: AddressAssets) -> bool:
    """A street TYPE is not a street NAME, and the register does not separate them.

    «улица», «проезд», «площадь», «шоссе», «дорога» all sit inside the ГАР NAME
    vocabulary — there are streets literally called that — so the bare arm read
    «на дороге семьдесят» as the street «дороге» at house 70. Caught by the
    over-masking suite the hour it grew from 42 phrases to 538, on a sentence
    about roadworks that no set of ours had ever contained.

    The stems are already leased for the arms that look for a type word; asking
    them here costs nothing and needs no second list to keep in step.
    """
    low = word.lower()
    stems = tuple(address.street_type_house) + tuple(address.street_type_nohouse)
    return any(low.startswith(stem) for stem in stems if len(stem) >= 4)


def _address_continues(text: str, end: int, address: AddressAssets) -> bool:
    """Идёт ли сразу за номером дома продолжение адреса, а не остаток фразы."""
    tail = text[end:end + 32]
    for rx in (address.spoken_apt, address.apt):
        found = rx.search(tail)
        # СРАЗУ за номером, а не где-то в остатке фразы: «строителей пять
        # пришло на объект в доме два» договорилось бы до продолжения.
        if found is not None and found.start() <= 1:
            return True
    return False


_TIME_AFTER = re.compile(r"\s*(?:[а-яё]\s+)?(?:в|к|до|с|на|около|после)\s+\d{1,2}[:.]\d{2}\b")


def _bare_street_candidates(text: str, address: AddressAssets
                            ) -> list[tuple[int, int, bool]]:
    """A lower-case street name with no type word at all, plus a house number.

    «барышникова шестьдесят три первый подъезд» is how a person says an address
    out loud, and measured on 400 hand-labelled utterances of real taxi dispatch
    it is the MAJORITY form: 100 of the 156 address values there carry no
    «улица», no «проспект», no capital and no digit. Every existing arm needs one
    of those, so the whole class scored zero.

    This is the riskiest shape in the engine — a lower-case word plus a number —
    so it is admitted only past four gates, and each rejects something different:

      1. THE ГАР REGISTER, in the three forms speech produces. Rejects the
         language: «доставка цветов пять», «привезите воды пять».
      2. THE SHAPE OF THE NAME. A surname in any case, an adjective only in the
         nominative, never a plural and never a pronoun, never a bare settlement
         (a city takes no house number — the existing veto). Rejects «общего 23»,
         «за последние тридцать», «в Ленинграде 28».
      3. NOTHING QUANTIFIED BY THE NUMBER, and nothing that turns it into an age
         or a measurement. Rejects «свободы один день», «пост пять раз»,
         «31-летний», «5 гектаров».
      4. A DIGIT MUST SATISFY (2) EVEN IF THE REGISTER NAMES THE FORM. The
         register vouches for «Победы» and «Труда» — the genitive IS the street
         name — but those same words stand in the genitive in prose for the
         ordinary reason, and prose writes its numbers as DIGITS while speech
         writes them as WORDS. «статьи 19 Федерации 2» and «порядка 71 сайта»
         are what the relaxation costs when the number is a digit; measured, 21
         false addresses on news prose. Behind a spelled number it costs none.

    Measured on 2691 sentences of NEREL prose: zero false addresses. On the two
    speech corpora: 77% of the class that previously scored zero.
    """
    out: list[tuple[int, int, bool]] = []
    for match in address.street_bare_lower.finditer(text):
        name = match.group("bare")
        number = match.group("bnum")
        low = name.lower()
        # ДЕШЁВОЕ ВПЕРЁД. Всё, что решается набором или регуляркой, стоит
        # перед всем, что зовёт морфологию: шаблон срабатывает на любом слове
        # с числом после него, то есть много раз на обычном тексте, и почти
        # каждое такое срабатывание отбивается ещё до разбора. Порядок стоил
        # 0.8 мс на сообщение — треть стоимости всей детекции.
        if low in address.month_after or low in ("года", "год", "лет"):
            continue
        if address.measure_after.match(text, match.end("bnum")):
            continue
        if address.age_after.match(text, match.end("bnum")):
            continue
        # A TIME AFTER THE NUMBER: «переговорной 2 в 15:00» is a meeting room,
        # and the «в» was read as the house litera because a lone letter after a
        # house number usually is one. What follows the letter decides: a clock
        # time or a bare number is a schedule, not an address.
        if _TIME_AFTER.match(text, match.end("bnum")):
            continue
        # A MISTYPED BARE STREET, behind an INTENT word. «курьера на вишёнвая
        # 28», «на нидняя 59», «на пушкна шестьдесят пять» — the sloppy and the
        # voice register both damage the street name, and with no type word
        # the fuzzy arm could not see it; every one reached the model in the
        # clear (live v4: 15 of the 46 leaked values). Same discipline as that
        # arm — unknown to morphology, one typo from the register, five letters
        # or more — and one signal on top, because a bare word plus a number is
        # the riskiest shape here: somebody must be saying they live or receive
        # things there, not a preposition alone.
        fuzzy = False
        if not _gar_reaches(name, address):
            # THE DOOR IS THE INTENT. «теперь гагрина 71кв169», «стоп правильно
            # толстго одиннадцать квартира двадцать восемь» — the intent word
            # sits in the previous turn or sixty characters back, and a flat
            # after the number is something no quantity carries. With a door a
            # mistyped street needs no intent word; without one it does.
            # The door is looked for after the WHOLE match — the litera
            # included («новя 86 в квартира 186»), not after the digits.
            door = (_address_continues(text, match.end(), address)
                    or re.search(r"\d(?:кв|к)\.?\d", number) is not None)
            intent = _intent_before(text, match.start(), address)
            marked_here = re.match(r"\s+дом\s", text[match.end("bare"):match.start("bnum")]) is not None
            # A TWO-LETTER TYPO IN THE ENDING is reachable on the stem, and a
            # four-letter word («новя» for «Новая») on the plain index — both
            # only behind a door, because a bare word plus a number is the
            # riskiest shape here. The «дом» marker with an intent word keeps
            # «курьера на ленна дом сорок три а» an address after the
            # dictionary calls «ленна» a short adjective.
            # An intent word with a SPOKEN number reaches the stem too: «курьера
            # на шумайлого восемь» — the register is speech, the ending is what
            # speech damages, and nobody dictates a quantity to a courier.
            # A DECLINED STREET WHOSE REGISTER FORM IS ANOTHER WORD. «варшавке
            # 24к3»: the dative of «Варшавка», which ГАР does not hold — but it
            # holds «Варшава», and the STEM of the nominative is the same six
            # letters. Judged through `to_nominative`, never a per-case list,
            # and only where an intent word already stands.
            if not ((intent and _fuzzy_names_a_street(name, address))
                    or (intent and _declined_reaches_register(name, address))
                    or (intent and not number[0].isdigit() and _fuzzy_stem_names_a_street(name, address))
                    or (door and (_fuzzy_names_a_street(name, address)
                                  or _fuzzy_stem_names_a_street(name, address)
                                  or _typo_of_a_street(name, address)
                                  or _short_fuzzy_street(name, address)))
                    or (marked_here and intent and _typo_of_a_street(name, address))):
                continue
            fuzzy = True
        if _is_numeral(name) or _is_street_type(name, address):
            continue
        # A mistyped word is unknown to morphology, and morphology GUESSES a
        # settlement reading for it («луогвая»); the register just said the
        # word is one typo from a street, and a guess does not outrank that.
        # РЕЕСТР ГАР СИЛЬНЕЕ МОРФОЛОГИЧЕСКОЙ ДОГАДКИ О ПОСЕЛЕНИИ. Вето ниже
        # право и нужно: город с числом — это температура, цена или количество.
        # Но оно выбросило и настоящие улицы, которых морфология не отличает от
        # города: «маросейка 123», «плющиха дом двенадцать» — ГАР называет эти
        # слова улицами (в реестре они есть как написано), а `_is_toponym` по
        # одному Geox-чтению объявляет их населённым пунктом. Вето не
        # спрашивало реестр, и четыре адреса — это все четыре чистых промаха
        # v5 по LOC — уходили к модели открытым текстом.
        #
        # ТРИ УСЛОВИЯ, И ВСЕ ТРИ НУЖНЫ. Слово обязано быть в арендованном
        # реестре улиц (`_bare_names_a_street`, буквально, а не по нормальной
        # форме — «казани», «сочи» так не проходят), в предложении обязано
        # стоять слово-намерение (`_intent_before`: «доставка по Казани 3 дня»
        # намерение имеет, но реестра у «казани» нет и вето стоит), и спан
        # обязан читаться улицей общим читателем (`looks_like_street`).
        # Вето сохраняет полную силу для «погода в Сочи 25 градусов», «курс в
        # Сочи 25 рублей» и «строителей пять пришло»: у первых двух нет
        # намерения, у третьего нет реестра.
        #
        # …И СЛОВО НАПИСАНО В ИМЕНИТЕЛЬНОМ — форма, которую хранит реестр.
        # Косвенная при предлоге («доставка в Сочи 3 дня»: «сочи» — locative)
        # остаётся во власти вето, иначе реестр, где есть улица Сочи, вернул бы
        # в язык ровно ту конструкцию, ради которой вето написано.
        registered_settlement_street = (
            not fuzzy
            and _names_a_settlement(name, address)
            and _bare_names_a_street(name, address)
            # A DECLINED FORM OF A REGISTER WORD COUNTS TOO, and this is the
            # half the nominative test was missing. «екатеринбург, куйбышева
            # 22»: «Куйбышева» IS in ГАР as written, and it is the GENITIVE of
            # «Куйбышев» — the case a street named after a person always stands
            # in. The nominative floor exists for the INDECLINABLE city
            # («доставка в Сочи 3 дня»), and that one stays refused because
            # «сочи» inflects to itself — `_declined_register_form` answers
            # False for it.
            and (_in_the_nominative(name) or _declined_register_form(name))
            and _intent_before(text, match.start(), address)
            and morph_places.looks_like_street(text[match.start():match.end()]))
        if _names_a_settlement(name, address) and not fuzzy \
                and not registered_settlement_street:
            continue
        # ПЛЮРАЛЬ ПРОПУСКАЕТСЯ ТОЛЬКО С АДРЕСНЫМ ПРОДОЛЖЕНИЕМ ПОСЛЕ НОМЕРА.
        # «улица Коммунаров», «Металлистов», «Строителей», «Космонавтов»,
        # «Декабристов» — огромный и совершенно обычный класс русских улиц, и
        # вето на множественное число выбрасывало его целиком. Но снять вето
        # нельзя: родительный падеж множественного числа перед числом — это
        # русская конструкция приблизительного количества, «строителей пять
        # пришло на объект», «шахтёров двести спасли», «моряков тридцать на
        # борту», и реестр её не отличит, потому что реестр ПРАВ — все эти
        # слова где-то называют улицу. Измерено: снятие вето делает ложными
        # адресами десять из двенадцати таких фраз.
        #
        # Разделяет их то, что стоит ПОСЛЕ номера. За домом следует подъезд,
        # квартира или корпус; за количеством — глагол или предлог. Продолжение
        # покупает «металлистов пятьдесят шесть первый подъезд» и не покупает
        # «коммунаров сто восемьдесят шесть» — узко и намеренно.
        # THE MARKER IS THE DOOR TOO: «коммунаров дом сто девяносто шесть» — a
        # quantity is never introduced by «дом», so the plural veto stands down
        # when the customer wrote the marker.
        marked = re.match(r"\s+дом\s", text[match.end("bare"):match.start("bnum")]) is not None
        # A mistyped word's number reading is a guess («толстго» predicted
        # plural), so the plural veto is not asked of a fuzzy match.
        # THE DOOR OPENS BEHIND A DIGIT TOO: «коммунаров 22 квартира 113» is
        # chat's spelling of the dictated form, and «строителей 5 пришло» has
        # no flat after its number.
        # …AND AN INTENT WORD WITH A DIGIT: «курьера на коммунаров 115» is the
        # chat register saying where to send the courier; the approximate
        # quantity («строителей пять пришло») is speech and spells its number.
        plural_door = _register_vouches(name, address) and (
            _address_continues(text, match.end("bnum"), address)
            or (number[0].isdigit() and _intent_before(text, match.start(), address)))
        if _plural_or_pronoun(name) and not marked and not fuzzy and not plural_door:
            continue
        spelled = not number[0].isdigit()
        # AN OBLIQUE ADJECTIVE IS LICENSED BY A PREPOSITION, NOT BY AGREEMENT.
        # «на октябрьскую сто двадцать пять» and «на литейном четыре» stand in
        # the accusative and the prepositional because «на» PUT them there —
        # which is how a person says where to go. «общего 23» is a genitive
        # agreeing with the noun beside it and names no street. Same word class,
        # and only what stands in front separates them.
        # A PREPOSITION IS DIRECT EVIDENCE THAT THE WORD IS OBLIQUE, so it
        # settles both questions at once and the `_never_oblique` floor below is
        # not asked. «на литейном четыре» and «на октябрьскую сто двадцать пять»
        # carry no genitive form of their own; «на» put them where they are, and
        # that is how a person says where to go.
        preposition = address.prep_before.search(text[:match.start()][-8:]) is not None
        # A mistyped word's case is morphology's GUESS, so the oblique floor is
        # not asked of it — the register's neighbour and the intent word are
        # the evidence, and the preposition may stand two words back.
        #
        # И НЕ СПРАШИВАЕТСЯ У СЛОВА, ЧЬЁ ВЕТО О ПОСЕЛЕНИИ УЖЕ СНЯТО ПО РЕЕСТРУ.
        # «маросейка сто пятьдесят пять квартира сто семьдесят один» стоит без
        # предлога, морфология даёт ей только именительный, и `_never_oblique`
        # («у имени нет родительного, значит это вещь, а не улица») выбрасывала
        # четвёртый из четырёх промахов M2. Улица, которую ГАР хранит в
        # именительном и которую читатель читает улицей, — ровно тот случай, где
        # именительный и есть форма имени, а не признак вещи.
        # …AND A PROPER NAME THE REGISTER KNOWS IS NOT A «THING». «мельникайте
        # 12»: morphology has no noun reading for the word at all — every parse
        # is a verb — so `_never_oblique` declared it a thing, while ГАР names
        # exactly that form as a street. The floor was written for «время»,
        # «школа», «вышка», which DO carry a noun reading and stay refused.
        if not preposition and not fuzzy and not registered_settlement_street \
                and not _register_only_as_proper(name, address) \
                and _never_oblique(name):
            continue
        # A GENITIVE-PLURAL NOUN THE REGISTER NAMES, WITH THE DOOR AFTER THE
        # NUMBER, is a street behind a DIGIT too: «челюскинцев 159 квартира
        # 183» is how chat writes what speech spells out, and the shape gate
        # (a surname in the genitive, a nominative adjective) has no reading
        # for «Челюскинцев», «Строителей», «Космонавтов». The door is what the
        # spelled branch above already trusts; a quantity («строителей 5
        # пришло») has no flat after it.
        licensed = _street_shape(name) or preposition or fuzzy or plural_door
        if not (spelled and _register_vouches(name, address)) and not licensed:
            continue
        # A NUMBER WITH A FLAT GLUED TO IT IS NEVER A QUANTITY. «депутатская
        # 55кв18 стоп правильно…» — «18» agreed with «стоп» (feet, genitive
        # plural) and the customer's first address went to the model in the
        # clear; the agreement veto is about a bare number, and «кв18» is not.
        if not re.search(r"\d(?:кв|к)\.?\d", number) and _counts_next_word(text, match.end("bnum"), number, address):
            continue
        out.append((match.start(), match.end(), True))   # core: street + house
    return out


def _person_not_street(phrase: str) -> bool:
    """«Фамилия Имя» is a person, and no Russian street is named that way.

    «Соколова Анна 21.09.1980» came out as the street «Соколова Анна» at house
    21, because «Соколова» IS a genitive singular surname and улица Соколова
    exists — the shape rule cannot separate them, and the SECOND word can.
    Streets named after people carry the surname alone («Ленина», «Гагарина»,
    «Барышникова») or put the given name FIRST and in the genitive («Максима
    Горького»), which is a multi-word register entry and never reaches here.

    The given name must be NOMINATIVE: that is what makes it an address to a
    person rather than a part of «улицы Максима Горького»."""
    words = [word for word in _WORD_SPLIT_RE.split(phrase) if word]
    if len(words) != 2 or not is_surname_shaped(words[0]):
        return False
    if not is_known_name(words[1]):
        return False
    return any("Name" in parse.tag and parse.tag.case == "nomn"
               for parse in MORPH.parse(words[1]))


def _is_street_name(phrase: str, address: AddressAssets) -> bool:
    """Street-name if ANY word (or hyphen part) looks like a toponym/surname/adj."""
    if _person_not_street(phrase):
        return False
    for word in _WORD_SPLIT_RE.split(phrase):
        if word and _word_is_street(word, address):
            return True
    return False


def _natasha_candidates(text: str, address: AddressAssets) -> list[tuple[int, int, bool]]:
    if not USE_EXTRACTOR:
        return []
    out: list[tuple[int, int, bool]] = []
    for match in _extractor()(text):
        part_type = getattr(match.fact, "type", None) or ""
        out.append((match.start, match.stop, _part_is_core(part_type, address)))
    return out


def _log_shadow_diff(text: str, natasha: list[tuple[int, int, bool]],
                     regex: list[tuple[int, int, bool]]) -> None:
    """Report spans ONLY the extractor found, so a canary can prove whether the
    regex arm is a superset on real traffic. Logs offsets and lengths, never the
    matched text — this runs on live customer data and the log must stay PII-free."""
    uncovered = [
        (start, stop) for start, stop, _ in natasha
        if not any(start < r_stop and stop > r_start for r_start, r_stop, _ in regex)
    ]
    if uncovered:
        _log.warning(
            "addr_shadow: extractor found %d span(s) the regex arm missed "
            "(offsets=%s, text_len=%d) — regex arm is NOT a superset here",
            len(uncovered), uncovered, len(text),
        )


_GAP_AND_WORD_RE = re.compile(r"([\s,.;]{0,3})([А-Яа-яЁё][А-Яа-яЁё-]*)")


def _given_name_after_a_bare_street(text: str, end: int, name: str) -> bool:
    """Имя человека сразу за голой улицей без дома означает, что это был ЧЕЛОВЕК.

    «здравствуйте оформите доставку на миллера валерия телефон …» маскировало
    «миллера» улицей: подсказка доставки лицензировала слово, реестр ГАР знает
    «Миллера», фамилия в родительном прошла морфологический гейт — а ADDR (4)
    старше NAME (3), поэтому ЦЕЛОЕ имя «миллера валерия» уезжало в инструмент
    как место. 25 таких случаев в v5, три вида фразы, — крупнейший измеренный
    дефект точности у этого плеча.

    Читатель это уже знал: `morph_places.looks_like_street('миллера валерия')`
    отвечает «нет» для всех 25 и «да» для настоящих бездомовых улиц, ради
    которых ветка написана («сивкова сто девять» — число дома словами и есть
    улица). Поэтому вето спрашивается, только когда верно И ТО, И ДРУГОЕ: пара
    не читается улицей И второе слово — известное имя. Кандидат, за которым
    ничего не стоит («адрес репина», «на бибиревская»), не трогается вовсе.
    """
    match = _GAP_AND_WORD_RE.match(text[end:])
    if match is None:
        return False
    gap, other = match.group(1), match.group(2)
    # ТОЧКА — ЭТО СОКРАЩЕНИЕ ИЛИ КОНЕЦ ПРЕДЛОЖЕНИЯ, и «адрес репина. Иван
    # приедет» не должен потерять адрес из-за имени, открывающего следующее
    # предложение: то же правило, что уже применяет `_merge`.
    if _ends_sentence(gap, other):
        return False
    if morph_places.looks_like_street(f"{name} {other}"):
        return False
    return is_known_name(other)


# ЧАСТЬ АДРЕСА, НАЗВАННАЯ ЧИСЛОМ ПЕРЕД МАРКЕРОМ: «, 3 подъезд», «, 2 под»,
# «, 3-й этаж». Слева обязателен РАЗДЕЛИТЕЛЬ — см. `_regex_candidates`.
# «под[ъь]езд» с мягким знаком и «этаж» здесь потому, что чат пишет и то и
# другое, а живой корпус — «Победы 81 подьезд 3». «под» без уточнения допущен
# как сокращение, но только после разделителя: «, 2 под.» — адрес, «дом 2 под
# ключ» — нет.
_NUMBER_BEFORE_PART = re.compile(
    r"(?i)(?<=[,.;])(\s*\d{1,3}(?:\s*-\s*(?:ый|ий|ой|ая|ое|ья|й|я|е))?\s*,?\s*"
    r"(?:под[ъь]езд\w*|под|этаж\w*)\b)")


def _regex_candidates(text: str, address: AddressAssets) -> list[tuple[int, int, bool]]:
    out: list[tuple[int, int, bool]] = []
    for rx in (address.street_first, address.street_last, address.street_lower_first,
               address.street_lower_last, address.street_abbr_lower,
               address.street_abbr_lower_last,
               address.house, address.mkr, address.rural):
        for m in rx.finditer(text):
            out.append((m.start(), m.end(), True))   # core
    # ЧИСЛО ПЕРЕД МАРКЕРОМ — вторая основная форма диспетчерской речи, и её не
    # знает ни один арендованный шаблон: `apt` строит часть как «маркер, затем
    # число» («подъезд 3»), а `spoken_apt` допускает слева только ПОРЯДКОВОЕ
    # слово («второй подъезд»). Цифра слева — «…, кв. 87, 3 подъезд», «…, 67,
    # 3 этаж», «…, кв. 23, 2 под» — не находилась вовсе, поэтому спан кончался
    # на квартире, а подъезд уезжал к модели ОТКРЫТЫМ ТЕКСТОМ внутри адреса,
    # который колонка полноты уже считала найденным. Это 11 из 176 значений
    # ADDRESS на PII-Bench.
    #
    # РАЗДЕЛИТЕЛЬ ОБЯЗАТЕЛЕН, и это не оформление. Без него «Победы 81 подьезд
    # 3» даёт кандидата «81 подьезд»: дом 81 уезжает в роль подъезда, домом
    # становится 3, а спан обрывается на «подьезд» — то есть правка теряет
    # ровно тот хвост, ради которого написана. Разделитель и есть то, что
    # отличает «названную часть» от номера дома перед словом.
    for m in _NUMBER_BEFORE_PART.finditer(text):
        out.append((m.start(1), m.end(1), False))    # support
    for rx in (address.apt, address.spoken_apt, address.settlement,
               address.index, address.district):
        for m in rx.finditer(text):
            out.append((m.start(), m.end(), False))  # support
    for m in address.markerless.finditer(text):
        # words is always Capitalized here. Accept if it has a morphological
        # street signal, is a numbered street ("8 Марта"), or sits in an address
        # context (Presidio-style enhancement for signal-less "Миклухо-Маклая 6").
        before = text[:m.start()]
        has_ctx = _cue_before(text, m.start(), address)
        # A NUMBER FOLLOWED BY A MONTH IS A DATE, not a house. «подписана
        # Президентом Российской Федерации 5 августа 2000 года» matched as a
        # marker-less street with house 5: «Российской» is an adjective, which
        # is all the morphology gate asks for, and the date was destroyed along
        # with it. Found on 993 sentences of ordinary Russian — the shape is
        # ordinary legal prose, and no set of ours contained it.
        after = text[m.end():m.end() + 12].lstrip()
        if any(after.lower().startswith(month) for month in address.month_after):
            continue
        words = m.group("words")
        # A COMMA BEFORE THE HOUSE IS THE DIRECTORY FORM, and it matched
        # nowhere: «Владимир, Большая Московская, 14» is how every CRM writes
        # an address, the asset pattern demanded whitespace, and the whole
        # street name went to the model in the clear. Admitted only for a
        # MULTI-WORD name: one capitalised word, a comma and a number is a
        # person in a list («Смирнов, 14»), not a street.
        if "," in m.group("hsep") and len(words.split()) < 2:
            continue
        # A BARE TOPONYM IS NOT PII — unless the register also names it as a
        # street AND a real address structure stands around it («Арбат 25»,
        # «Тверская 25»). The veto keeps «в Москве 25 градусов» and «доставка
        # по Казани 3 дня» exactly as refused as before.
        if (_names_a_settlement(words, address)
                and not _settlement_is_a_street(words, text, m, address)):
            continue
        # A LEADING NUMBER IS PART OF THE NAME ONLY FOR A NUMBERED STREET. The
        # pattern accepts one so «8 Марта 12» stays whole, and THAT is what let
        # «… телефон 8 926 555 77 88 Космонавтов 4» match from the tail of the
        # PHONE: the span began at «88», overlapped the phone, lost the
        # priority contest (PHONE 5 > ADDR 4) and took the real street down
        # with it — the corpus value «Космонавтов 4» had NO span at all. The
        # number is kept only where the word after it is the month or the
        # spelled unit of a numbered name.
        start = m.start()
        if m.group("num") is not None and words.split():
            first = words.split()[0].lower()
            if first not in address.month_after and first not in ("лет", "года", "год"):
                start = m.start("words")
        if _is_street_name(words, address) or m.group("num") or has_ctx:
            out.append((start, m.end(), True))   # core (street + house number)
    for m in address.street_lower_nohouse.finditer(text):
        # AN INTENT WORD, NOT A PREPOSITION. Every other lower-case arm accepts
        # `prep_before` as its context, and here that is far too little: «на
        # улицах Каира собрались десятки» and «на улицах американских городов»
        # both open with «на». What separates a person's address from prose
        # ABOUT streets is somebody saying they live or receive things there —
        # «проживает», «адрес:», «доставка» — and that is `addr_ctx` alone.
        name = m.group("after") or m.group("before") or ""
        if not _intent_before(text, m.start(), address):
            continue
        if _lower_names_a_street(name, address):
            out.append((m.start(), m.end(), True))   # core
    for rx, group in ((address.street_spoken_first, "sfirst"),
                      (address.street_spoken_last, "slast")):
        for m in rx.finditer(text):
            # THE NUMBER IS A WORD, SO THE STREET NAME MUST CARRY THE PROOF.
            # Every other lower-case arm is held down by a digit after the type
            # word, which ordinary prose almost never produces. A spoken number
            # is an ordinary Russian word and holds nothing: measured, folding
            # it into those arms found all seven real call transcripts and also
            # made addresses out of «на улице минус десять» and «проспект был
            # построен сорок лет назад». The vocabulary is the one signal that
            # does not generalise to prose — same rule, same reason, as
            # `markerless_lower` directly below.
            # TWO SIGNALS, AND THE TYPE WORD IS THE FIRST ONE. `_lower_is_street`
            # was tried here and is wrong for the opposite reason it is right in
            # `markerless_lower`: there the vocabulary is the ONLY evidence, so it
            # must not generalise; here the street TYPE already stands next to the
            # name, and demanding the vocabulary as well rejected «лермонтова»,
            # «рублёвском», «красная» and «петрозаводскую» — 4 of 6 real call
            # transcripts — because the shipped street list has NINETEEN entries.
            # Morphology alone would be too broad without the type word; with it,
            # measured on the same probes, it takes every real street and refuses
            # «минус», «плюс», «был», «построен», «темно» and «три».
            if _lower_names_a_street(m.group(group), address):
                out.append((m.start(), m.end(), True))   # core
    for m in address.spoken_chain.finditer(text):
        # A CHAIN OF MARKERS IS ITS OWN PROOF, so no vocabulary and no intent
        # word is asked for. «дом двадцать пять а корпус два квартира двадцать
        # семь этаж четвёртый» is a complete address minus the street, and the
        # street is often not said at all when a courier already knows it. Two
        # markers is the floor: one — «программу дом два» — is a television show
        # and sits in our own negative set.
        out.append((m.start(), m.end(), True))   # core
    for m in address.markerless_lower.finditer(text):
        # LOWER CASE, SO THE GATE IS THE VOCABULARY AND NOTHING ELSE.
        # `_is_street_name` would be wrong here: it accepts a morphological
        # signal, and in lower case «течение», «решение», «Вашингтоне» all carry
        # one. The capital was the second signal; with it gone, the only
        # admissible evidence is a word the leased street vocabulary actually
        # names. That cannot generalise to ordinary prose, which is exactly the
        # property needed.
        if not _lower_is_street(m.group("lwords"), address):
            continue
        # THE VOCABULARY ALONE IS NOT ENOUGH, and the corpus said so: «14 марта
        # ему исполнилось 60», «в конце марта 55» and «в виде лишения свободы 2»
        # all matched, because «марта» and «свободы» are in the street
        # vocabulary — they name real streets — and in lower case there was
        # nothing left to tell a street from the date and the sentence it
        # actually was. The capitalised arm never had this problem: the capital
        # WAS the second signal.
        #
        # So the lower-case arm demands an address context in its place — a cue
        # word («адрес», «доставка») or a preposition directly before it. Both
        # already exist and are already leased. «вы находитесь на ленина 14»
        # keeps its «на»; «лишения свободы 2» has «лишения» before it and is
        # refused.
        if not _cue_before(text, m.start(), address):
            continue
        after = text[m.end():m.end() + 12].lstrip()
        if any(after.lower().startswith(month) for month in address.month_after):
            continue
        out.append((m.start(), m.end(), True))   # core (street + house number)
    for m in address.street_nohouse_bare.finditer(text):
        # СТРОЧНАЯ УЛИЦА БЕЗ ДОМА: ЯКОРЬ ВПРАВЕ ДОПУСКАТЬ, А НЕ ТОЛЬКО ЗАПРЕЩАТЬ.
        # «адрес репина», «на бибиревская» — слово потеряло заглавную, а номер
        # дома здесь не написан, поэтому его не видит ни одна ветка: маркированные
        # хотят слово-тип, безмаркерные — заглавную или цифру, а `markerless_lower`
        # держится номером. Якорь перед словом при этом уже был в коде —
        # `names._street_reference` читает ровно «на/по» + реестр ГАР + отсутствие
        # номера, — но умел только ОТБИРАТЬ спан у имён.
        #
        # ДВА СИГНАЛА, И ЯКОРЬ ПЕРВЫЙ. Адресная подсказка («адрес», «доставка»,
        # «проживает») — свидетельство о том, что человек называет место; «на/по»
        # вплотную — слабее, и тогда регистр обязан подтверждаться МОРФОЛОГИЕЙ:
        # ГАР полон родительного падежа обычных существительных («правды»,
        # «труда», «строителей»), и «на строителей» — это проза, а не улица.
        # «репина» (Surn) и «бибиревская» (относительное ADJF) морфология
        # подтверждает, «правды» (NOUN,inan) — нет.
        name = m.group("bare")
        if not _bare_names_a_street(name, address):
            continue
        # ДВА СИГНАЛА, И ОБА ОБЯЗАТЕЛЬНЫ. Реестр ГАР называет и «правды», и
        # «восемь», и «московский» (улица Правды, площадь Восемь, Московский
        # проспект), поэтому одного попадания мало: морфология обязана читать
        # слово как НАЗВАНИЕ МЕСТА. «репина» (Surn) и «бибиревская»
        # (относительное ADJF женского рода) проходят, «правды» (NOUN) и
        # «московский» (мужской род — согласование с пропущенным
        # существительным, а не с «улицей») — нет.
        if not _bare_street_morphology(name):
            continue
        # ЯКОРЬ: точная адресная подсказка («адрес», «доставка») или местный
        # предлог вплотную. НЕ `_intent_before`: его нечёткая половина прощает
        # одну опечатку в ЛЮБОМ слове и отвечает «да» на «поставь будильник».
        if not _bare_street_anchor(text, m.start(), address):
            continue
        # ЧЕЛОВЕК ЗА ПОДСКАЗКОЙ — НЕ УЛИЦА БЕЗ ДОМА. См.
        # `_given_name_after_a_bare_street`: «доставку на миллера валерия»
        # отдавало всё имя целиком в LOC, и 25 таких случаев — крупнейший
        # измеренный дефект точности LOC.
        if _given_name_after_a_bare_street(text, m.end(), name):
            continue
        out.append((m.start(), m.end(), True))   # core (street without a house)
    for m in address.numbered_st.finditer(text):  # lowercase names ("1905 года 12")
        # AN INTENT WORD, not merely a preposition. «на 8 марта 5 подарков» is a
        # date and a quantity — the commonest sentence in Russian retail in
        # March — and it opens with «на» exactly as an address does. Nothing in
        # the shape separates them, so the separation has to come from somebody
        # saying they live or receive things there. The marked form («улица 8
        # марта 5») has its own pattern and needs no cue.
        if not _intent_before(text, m.start(), address):
            continue
        out.append((m.start(), m.end(), True))
    for m in address.numbered_marked.finditer(text):  # "1905 года тупик"
        out.append((m.start(), m.end(), True))
    return out



# --- typo-tolerant street matching ---------------------------------------
#
# WHY A TOKEN SCAN AND NOT ANOTHER REGEX. Every arm above is anchored on a
# literal — «улиц», «проспект» — so one dropped letter turns the whole address
# off. Measured on the noise ladder, street recall goes 100 → 100 → 64 → 4 at
# one typo per value: not degraded, gone. Half of that damage is in the TYPE
# word («уилце ленина») and half in the NAME («улице гагаина»), so tolerating a
# typo in only one of them buys about half of it back.
#
# THE THREE SIGNALS, and each one rejects a different thing. This is the same
# discipline `_looks_misspelt_name` needed and for a worse version of the same
# reason: the street vocabulary is larger than the name dictionary and about
# half of it is a single ordinary-looking word, so a bare fuzzy lookup against
# it matches a large part of the language.
#
#   1. A STREET-TYPE WORD stands next to it. Rejects every bare
#      word-plus-number in ordinary prose — which is what the marker-less arms
#      spend all their guards on. The type word is the cheap gate and it runs
#      first.
#   2. THE OTHER WORD IS IN THE LEASED ГАР VOCABULARY, as written, as its
#      normal form, or as its nominative. Rejects «улица была пустой» and «на
#      улицах Каира собрались десятки»: «была», «пустой» and «каира» are
#      ordinary words that name no street, and morphology — which admits all
#      three — is deliberately not consulted for this.
#   3. ADDRESS INTENT: a house number attached to the pair, or a cue word in
#      the sentence tail. Rejects prose ABOUT streets, exactly as
#      `street_lower_nohouse` already does, and the split between the two type
#      tiers is the same one: a type word whose only meaning is a street may
#      lean on the cue, everything else needs the number.
#
# AND A FOURTH THING, which is what makes signals 1 and 2 usable at this size:
# a FUZZY hit is only ever accepted for a token pymorphy3 does not know, and
# never for both words at once. A typo makes a word unknown; «линии»,
# «территории», «съезда» and «алло» are known, so they can only ever match
# exactly. That is the guard `_looks_misspelt_name` learned the hard way — in a
# dictionary this dense the distance-1 neighbourhood of an ordinary word is
# never empty — and it is imported here wholesale rather than re-derived.
_CYR_TOKEN_RE = re.compile(r"[А-Яа-яЁё]+(?:-[А-Яа-яЁё]+)*")
# TWO TOKENS ARE NEIGHBOURS ONLY IF NOTHING STANDS BETWEEN THEM. The scan skips
# everything that is not a Cyrillic word, so «улице 89985435346 ленина» would
# otherwise present «улице» and «ленина» as adjacent and mask the phone number
# between them as part of the street. Separators and a marker's dot, nothing
# else.
_PAIR_GAP_RE = re.compile(r"[\s,.:;()«»\"'-]{0,3}\Z")
# The house number that may hang off the pair, in the shapes the tuned arms
# already accept: «ленина 14», «ленина, д. 5», «ленина д14». Three digits, not
# four, exactly as `markerless` limits it — a fourth digit is a year far more
# often than a door, and «улица Ленина 2024 года» must not swallow the year.
_HOUSE_AFTER_RE = re.compile(
    r"[\s,]{0,3}(?:дом|д)?\.?\s*\d{1,3}[А-ЯЁа-яё]?(?:/\d+)?(?![0-9A-Za-zА-Яа-яёЁ])")


@functools.lru_cache(maxsize=4)
def _spoken_house_after_for(version: str) -> re.Pattern[str]:
    alternation = spoken.numeral_alternation()
    return re.compile(
        rf"[\s,]{{0,3}}(?:дом\s+)?(?:(?:{alternation})\b\s*){{1,4}}(?:[а-яё](?![а-яё]))?")


def _house_after(text: str, stop: int) -> re.Match[str] | None:
    """The house after a street — digits, or SAID IN WORDS with or without
    «дом»: the fuzzy type-word arm took only digits, so «переулок коммнаров
    дом сто восемьдесят семь б» had no house, no intent word in reach, and
    the mistyped street went to the model in the clear."""
    house = _HOUSE_AFTER_RE.match(text, stop)
    if house is not None:
        return house
    return _spoken_house_after_for(ASSETS.version or "").match(text, stop)
# Below five letters a single edit reaches too much of the language, and the
# bucket index cannot see all of it anyway: its guarantee — that an edit at
# position p is caught by one key or the other — only closes at six letters, so
# a shorter word gets partial coverage that would look like a rule and is not
# one. The vocabulary holds every short street name exactly, which is where
# they are found.
_MIN_FUZZY_NAME = 5


@functools.lru_cache(maxsize=4)
def _street_index(version: str) -> dict[tuple[str, int], tuple[str, ...]]:
    """The ГАР vocabulary bucketed for one-edit lookup.

    Keyed on the BUNDLE VERSION, so a re-lease cannot serve an index built from
    the previous vocabulary. The version is a content hash, so equal version
    means equal contents — the same contract `_misspelling_index` runs on."""
    return build_index(ASSETS.get().address.street_names)


def register_spelling(word: str) -> str:
    """The ГАР register's spelling of a street name the customer mistyped, or "".

    THE AGENT REPAIRS A TYPO AND THE GATEWAY TAKES THAT AWAY. A customer writes
    «курьера на мончгорская 195»; without us the model silently sends
    «Мончегорская» to the CRM and the address is found. With us the model is
    shown a CLEAN substitute, has nothing to repair, writes it verbatim, and
    the customer's literal words reach the tool — a street that does not exist.
    Measured on the 06.09 live run: 42 of the 103 street/address conflicts.

    THREE SIGNALS, THE SAME DISCIPLINE `_fuzzy_street_candidates` RUNS ON, and
    the reason each is needed:

      * THE REGISTER DOES NOT REACH THE WORD — asked in all three forms
        `_gar_reaches` asks, not just as written. This is the signal that
        cost the most to get right: the register stores nominatives, and a
        customer who writes a CORRECT street in an oblique case («на
        мончегорской 195», «к вишнёвой 8») is not in it as written. Asked
        only as written, the gateway rewrote «мончегорской» to «мончегорское»
        and «вишнёвой» to «вишневый» — corrupting an address that was right;
      * EXACTLY ONE register entry is one Damerau edit away — «лениа» reaches
        «лена», «ленин», «ленина» and «ленца», and choosing among four would be
        the gateway sending a courier somewhere the customer never named;
      * the word is long enough that one edit is not most of it. Below six
        letters the neighbourhood is dense and a real short street name would
        be rewritten into a commoner one.

    Returns the register's form, never a guess. The caller decides where it is
    allowed to matter — a tool argument, never prose.
    """
    written = word.strip().lower()
    low = written.replace("ё", "е")
    if len(low) < 6 or not low.isalpha():
        return ""
    address = ASSETS.get().address
    if _gar_reaches(written, address) or _gar_reaches(low, address):
        return ""
    # A NUMERAL AND A STREET TYPE ARE NOT NAMES TO BE REPAIRED, the same two
    # vetoes the bare-street arm applies before it consults the register.
    if _is_numeral(written) or _exact_type(written, address.street_type_house) is not None:
        return ""
    index = _street_index(ASSETS.version or "")
    found: set[str] = set()
    for key in deletion_keys(low):
        for candidate in index.candidates(key):
            if candidate != low and within_one_typo(low, candidate):
                found.add(candidate)
    if len(found) == 1:
        return next(iter(found))
    # SEVERAL NEIGHBOURS, AND THE REGISTER SAYS WHICH ONE PEOPLE LIVE ON.
    # «садвая» reaches садовая and садвал, «полвая» reaches полевая and полная,
    # «неркасова» reaches некрасова and черкасова — refusing all of them was
    # refusing nearly every real typo: the repair fired on one of six mistyped
    # streets on the 06.09 live run. The margins are not close (17 325 to 1,
    # 12 087 to 1, and 1 565 to 24 at the narrowest), and only ONE candidate
    # may be in the frequent set — two common neighbours is a genuine ambiguity
    # and is still refused, as «лениа» was.
    frequent = found & ASSETS.get().address.street_frequent
    # «ЗЕЛЕНЫЙ» И «ЗЕЛЁНЫЙ» — ОДНО ИМЯ, И РЕЕСТР ХРАНИТ ОБА. Two spellings of
    # one word are not an ambiguity: refusing them refused «зелный», a plain
    # typo of the commonest adjective in the register. Grouped by the ё-fold,
    # and the form returned is the one the register spells more often — which,
    # for a name that reached this set at all, is the one people write.
    by_fold: dict[str, list[str]] = {}
    for candidate in frequent:
        by_fold.setdefault(candidate.replace("ё", "е"), []).append(candidate)
    if len(by_fold) != 1:
        return ""
    same = sorted(next(iter(by_fold.values())))
    return same[0] if len(same) == 1 else min(same, key=lambda one: ("ё" in one, one))


def repair_street(value: str) -> str:
    """`value` with every mistyped word of its STREET NAME put into the
    register's spelling; the rest of the address, its case and its punctuation
    are untouched. Returns `value` unchanged when nothing qualifies.

    Only the street span, and only the words `register_spelling` vouches for:
    the house number, the flat, the settlement and the type word are the
    customer's and stay his. A type word is never rewritten because every one
    of them IS in the register as a street name in its own right («улица
    Улица» exists), so the first of the three signals refuses it.
    """
    spans = morph_places.role_spans(value)
    span = spans.get("street")
    if span is None:
        return value
    start, end = span
    out: list[str] = []
    cursor = start
    for match in _CYR_TOKEN_RE.finditer(value, start, end):
        fixed = register_spelling(match.group())
        if not fixed:
            continue
        out.append(value[cursor:match.start()])
        out.append(_in_case_of(match.group(), fixed))
        cursor = match.end()
    if not out:
        return value
    return value[:start] + "".join(out) + value[cursor:]


def _in_case_of(pattern: str, produced: str) -> str:
    """`produced` in the letter case `pattern` uses."""
    if pattern[:1].isupper():
        return produced[:1].upper() + produced[1:]
    return produced


def _is_unknown(token: str) -> bool:
    """Whether pymorphy3 has never seen this word.

    `any`, not `parse[0]`: a word is known if ANY reading comes from the
    dictionary. Taking the best parse would call «марину» unknown whenever the
    predicted reading happened to outscore the dictionary one, and unknown is
    the state that OPENS the fuzzy path — so the wrong answer here is the
    permissive one."""
    parses = MORPH.parse(token)
    return bool(parses) and not any(parse.is_known for parse in parses)


def _exact_type(token: str, stems: tuple[str, ...]) -> str | None:
    # The tuple form of `startswith` is one C-level call over all 31 stems and
    # answers "any of them" without saying which. This runs on EVERY token of
    # every message, so the Python loop that names the stem — which the tier
    # check needs — may only run for the few tokens that already matched.
    if not token.startswith(stems):
        return None
    for stem in stems:
        if token.startswith(stem):
            return stem
    return None


def _fuzzy_type(token: str, stems: tuple[str, ...]) -> str | None:
    """A street type one typo away, compared on the PREFIX rather than the word.

    The vocabulary is stems («улиц», «проспект») because the type word is
    inflected in every real address — «на улице», «по проспекту» — and a stem
    plus a suffix is how every other arm here reads it. So the comparison takes
    the token's prefix at the stem's length and at one either side: an edit
    inside the stem region moves that boundary by at most one, and «поспекте»
    only reveals its missing «р» when seven characters are compared against
    eight."""
    for stem in stems:
        for length in (len(stem) - 1, len(stem), len(stem) + 1):
            if 3 <= length <= len(token) and within_one_typo(token[:length], stem):
                return stem
    return None


def _names_a_street(token: str, address: AddressAssets) -> bool:
    """Whether the ГАР vocabulary claims this word, in any form it can take.

    THE INFLECTED FORM IS THE COMMON ONE, not the exception: ГАР registers
    «Садовая» and «Центральная» and a customer writes «на садовой», «по
    центральной». The ten commonest street names in Russia are all adjectives,
    so a lookup that only matched the registered spelling would miss the half of
    the register it exists for.

    EVERY reading, never `parse[0]` — the trap that made «марину» resolve to a
    man and «Тверская» stop being a street. `inflect` keeps the gender it found
    and only moves the case, which is what turns «тверской» back into
    «Тверская» without inventing one."""
    if token in address.street_names:
        return True
    for parse in MORPH.parse(token):
        if parse.normal_form in address.street_names:
            return True
        nominative = parse.inflect({"nomn"})
        if nominative is not None and nominative.word in address.street_names:
            return True
    return False


def _fuzzy_names_a_street(token: str, address: AddressAssets) -> bool:
    if len(token) < _MIN_FUZZY_NAME or not _is_unknown(token):
        return False
    return lookup(token, _street_index(ASSETS.version or ""))


# THE ENDING IS WHERE SPEECH DAMAGES A STREET, and an ending is two letters.
# «лермонтого» for «Лермонтова», «добролюбого» for «Добролюбова» — the
# transcript bent the genitive into an adjective's, which is TWO edits from
# the register and out of the one-edit index's reach. Compared on the STEM
# (the word minus a case ending, five letters or more) the same typo is one
# edit again. Stems are shorter and their neighbourhoods denser, so this is
# asked only where the other signals already stand: unknown to morphology,
# and a type word beside it or a spoken number with a door after it.
# The stem is the word minus its LAST TWO LETTERS on both sides — not a list of
# endings, because the typo is precisely a wrong ending, and stripping «ого»
# from the typo but «а» from the register left «лермонт» two edits from
# «лермонтов».
_STEM_CUT = 2


def _street_stem(word: str) -> str:
    return word[:-_STEM_CUT]


@functools.lru_cache(maxsize=4)
def _street_stems(version: str) -> tuple[frozenset[str], dict[tuple[str, int], tuple[str, ...]]]:
    stems = frozenset(_street_stem(name) for name in ASSETS.get().address.street_names
                      if len(name) >= _MIN_FUZZY_NAME + _STEM_CUT + 1)
    return stems, build_index(stems)


def _fuzzy_stem_names_a_street(token: str, address: AddressAssets) -> bool:
    if len(token) < _MIN_FUZZY_NAME + _STEM_CUT + 1 or not _is_unknown(token):
        return False
    stem = _street_stem(token)
    stems, index = _street_stems(ASSETS.version or "")
    # `lookup` answers ONE edit and deliberately not zero; a stem equal to the
    # register's («шумайлого» → «шумайло» = «шумайлова» → «шумайло») is the
    # commonest case here, the ending being exactly what the typo damaged.
    return stem in stems or lookup(stem, index)


def _short_fuzzy_street(word: str, address: AddressAssets) -> bool:
    """A four-letter unknown word one edit from the register — asked only
    behind a door, where «новя 86 в квартира 186» is an address and the
    dense four-letter neighbourhood has nothing else to offer."""
    if len(word) != _MIN_FUZZY_NAME - 1 or not _is_unknown(word):
        return False
    return lookup(word, _street_index(ASSETS.version or ""))


def _typo_of_a_street(word: str, address: AddressAssets) -> bool:
    """One edit from the register, and NOT an ordinary word: unknown to
    morphology, or known only as a proper name («ленна» is in the dictionary
    as a rare given name and nothing else, and «курьера на ленна дом сорок
    три» names no person)."""
    if len(word) < _MIN_FUZZY_NAME:
        return False
    parses = MORPH.parse(word)
    # …or known only in a part of speech that cannot stand where a street
    # stands: «ленна» is in the dictionary as the short adjective of «ленный»,
    # and a short adjective is a predicate — it does not follow «на» and
    # precede «дом». A noun or a full adjective reading keeps the word.
    proper_only = bool(parses) and all(
        not parse.is_known or ({"Name", "Surn", "Geox"} & set(parse.tag.grammemes))
        or parse.tag.POS in _NEVER_A_STREET_POS for parse in parses)
    if not proper_only:
        return False
    return lookup(word, _street_index(ASSETS.version or "")) or _fuzzy_stem_names_a_street(word, address)


_NEVER_A_STREET_POS = frozenset({"ADJS", "PRED", "VERB", "INFN", "GRND", "PRTS", "ADVB", "PRCL", "CONJ", "PREP", "INTJ"})


def _fuzzy_street_candidates(text: str, address: AddressAssets
                             ) -> list[tuple[int, int, bool]]:
    tokens = [(match.start(), match.end(), match.group().lower())
              for match in _CYR_TOKEN_RE.finditer(text)]
    exact_type = [_exact_type(token, address.street_type_house)
                  for _, _, token in tokens]
    exact_name = [token in address.street_names for _, _, token in tokens]

    # A MULTI-WORD NAME IS THREE TOKENS, AND THE PAIR LOOP CANNOT SEE IT.
    # «переулок сивцев вражек» is (type, name, name), so every pair it forms —
    # («переулок», «сивцев») and («сивцев», «вражек») — fails, and the street was
    # unreachable whenever the type word carried a typo, since the fuzzy-type
    # path is the one that demands the vocabulary. Fifty-five per cent of the
    # register is multi-word and it is not the tail: «Карла Маркса» names 1 512
    # streets, «8 Марта» 1 953.
    #
    # The phrase is looked up WHOLE, against a set that holds only phrases. That
    # is what keeps the single-word rule honest — «карла» on its own still has
    # no claim to name a street, because it is not in `street_names` and the
    # phrase set cannot be reached by one token.
    phrase_spans: set[tuple[int, int]] = set()
    for index in range(len(tokens) - 2):
        a, b, c = tokens[index], tokens[index + 1], tokens[index + 2]
        if not (_PAIR_GAP_RE.fullmatch(text[a[1]:b[0]])
                and _PAIR_GAP_RE.fullmatch(text[b[1]:c[0]])):
            continue
        for type_at, first, second in ((a, b, c), (c, a, b)):
            stem = _exact_type(type_at[2], address.street_type_house)
            if stem is None and _is_unknown(type_at[2]):
                stem = _fuzzy_type(type_at[2], address.street_type_house)
            if stem is None:
                continue
            if f"{first[2]} {second[2]}" not in address.street_phrases:
                continue
            start = min(type_at[0], first[0])
            stop = max(type_at[1], second[1])
            house = _house_after(text, stop)
            if house is not None and address.measure_after.match(text, house.end()):
                house = None
            if house is not None:
                stop = house.end()
            elif stem not in address.street_type_nohouse:
                continue
            elif not _intent_before(text, start, address):
                continue
            phrase_spans.add((start, stop))

    out: list[tuple[int, int, bool]] = [(s, e, True) for s, e in phrase_spans]
    for index in range(len(tokens) - 1):
        if not _PAIR_GAP_RE.fullmatch(text[tokens[index][1]:tokens[index + 1][0]]):
            continue
        for type_at, name_at in ((index, index + 1), (index + 1, index)):
            # ONE OF THE TWO MUST BE INTACT, and the cheap side decides which
            # expensive test is worth running. Both words misspelt is two
            # guesses stacked, and the pair that survives it is no longer
            # evidence of anything.
            stem = exact_type[type_at]
            if stem is not None:
                named = (exact_name[name_at]
                         or _names_a_street(tokens[name_at][2], address)
                         or _fuzzy_names_a_street(tokens[name_at][2], address)
                         or _fuzzy_stem_names_a_street(tokens[name_at][2], address))
            elif exact_name[name_at] and _is_unknown(tokens[type_at][2]):
                stem = _fuzzy_type(tokens[type_at][2], address.street_type_house)
                named = stem is not None
            else:
                continue
            if stem is None or not named:
                continue
            start = min(tokens[type_at][0], tokens[name_at][0])
            stop = max(tokens[type_at][1], tokens[name_at][1])
            # A NUMBER WITH A UNIT AFTER IT IS NOT A HOUSE NUMBER. «территория
            # завода 5 гектаров» satisfied every signal — type word, name in the
            # vocabulary, a bare «5» — because nothing looked past the number.
            # The veto is on the NUMBER rather than on the span, so the match
            # simply falls back to needing an intent word, and the two tiers
            # then decide it themselves: the weak tier has nothing left, the
            # strong tier asks for the cue.
            house = _house_after(text, stop)
            if house is not None and address.measure_after.match(text, house.end()):
                house = None
            if house is not None:
                stop = house.end()
            elif stem not in address.street_type_nohouse:
                # The weak tier without its number: «съезд Ленина» is a party
                # congress until a door number says otherwise.
                continue
            elif not _intent_before(text, start, address):
                # The strict cue, not `_cue_before`: with no house number the
                # preposition is worth nothing, because «на улицах Каира
                # собрались десятки» opens with the same «на» an address does.
                continue
            out.append((start, stop, True))   # core (street + type word)
    return out


# A word and the punctuation that may stand between it and an address part.
_NEIGHBOUR_LEFT = re.compile(r"([А-Яа-яЁё][А-Яа-яЁё-]*)[\s,.;]{0,3}$")
_TYPE_WORD_FIRST = re.compile(
    r"(?i)^\s*(?:улиц|проспект|переул|бульвар|шоссе|проезд|площад|набережн|алле|лини|просек|тупик"
    r"|квартал|микрорайон|ул\.|пр-т|пр\.|пер\.|б-р|наб\.|мкр)")
_NEIGHBOUR_RIGHT = re.compile(r"^[\s,.;]{0,3}([А-Яа-яЁё][А-Яа-яЁё-]*)")


def _is_toponym(word: str) -> bool:
    # «праавильно» is unknown to the dictionary and pymorphy3 PREDICTS a
    # Geox reading for it, so the customer's «ой нет, праавильно подленая
    # 18» became the town Праавильно and the courier's `locality` field
    # received it. A word one doubled letter away from an ordinary word is
    # that word, not a town.
    if _names_typo_of_ordinary(word):
        return False
    # THE SETTLEMENT DICTIONARY HOLDS THE SURNAME-COLLIDING TOWNS. «одоев»,
    # «венёв», «белёв» are real settlements pymorphy reads only as a surname, so
    # `_is_toponym_by_morphology` says «no» and the city never joined the street
    # it stands in front of. A word on the leased list is a toponym — the caller
    # already demands the address structure (a street beside it), so the list
    # cannot promote a bare word: «фамилия одоев» never reaches this check as a
    # place.
    if word.lower() in ASSETS.get().address.settlement_gaz:
        return True
    return _is_toponym_by_morphology(word)


def _is_toponym_by_morphology(word: str) -> bool:
    """Whether morphology calls this word a place name.

    pymorphy's dictionary already carries the toponym vocabulary and tags it
    `Geox`, INDEPENDENTLY OF CASE — «екатеринбург», «москва» and «люберцы» all
    carry it. That is the whole reason no city gazetteer is leased for this: a
    tuned list of a thousand cities would be a new asset to maintain and to
    ship, and it would buy a separation the dictionary already makes cleanly.
    Measured on every word this rule can see, the split is exact: every city
    carries Geox and «приезжайте», «спасибо», «заказ», «доставка», «офис» carry
    none.
    """
    return any("Geox" in parse.tag for parse in MORPH.parse(word))



def _city_first_word(text: str, city_start: int) -> int:
    """Extend a city left over the adjective that is part of its NAME.

    «Нижний Новгород» is two words and only the second carries `Geox`, so the
    span began at «Новгород» — the address was masked, and detokenisation handed
    the tool a city that does not exist. Six of AgentPII-RU's round trips broke
    exactly there.

    Two signals, because ADJF alone is far too wide: «красивый», «большой»,
    «новый», «этот» and «наш» are all ADJF too, and swallowing them would put
    ordinary words inside an address.

      * the reading must not be QUALITATIVE (`Qual`) or pronominal (`Apro`) —
        that alone separates «Нижний», «Великий» and «Набережные» from
        «красивый», «большой» and «наш»;
      * OR the word must be capitalised the same way the city is, which is what
        keeps «Старый Оскол» and «Новый Уренгой» (both `Qual`) while refusing
        «красивый Екатеринбург», where the adjective is lower case and the city
        is not.

    In all-lowercase chat the second signal is unavailable on both sides, so the
    first decides — and it is the one that holds there.
    """
    head = _NEIGHBOUR_LEFT.search(text[:city_start])
    if head is None:
        return city_start
    word = head.group(1)
    parses = [parse for parse in MORPH.parse(word) if "ADJF" in parse.tag]
    if not parses:
        return city_start
    naming = any("Qual" not in parse.tag and "Apro" not in parse.tag
                 for parse in parses)
    agrees = word[:1].isupper() == text[city_start:city_start + 1].isupper()
    return head.start(1) if naming or agrees else city_start



# HOW FAR A CUE WORD REACHES. `addr_ctx` used to be searched over the ENTIRE
# preceding text, so one «адрес» near the top of a system prompt licensed every
# capitalised-word-plus-number for the rest of it: «Наш адрес: …, д. 14. Часы
# 9-21» masked «Часы 9» as a second address, and the model could no longer say
# when the shop opens.
#
# Bounded to the tail, and never across a sentence end — a cue in one sentence
# says nothing about the next. The window is generous enough for the phrasings
# the cue vocabulary is written for («мой адрес для доставки — …»).
_CUE_WINDOW = 60
_SENTENCE_SPLIT = re.compile(r"[.!?]\s+(?=[А-ЯЁA-Z])")


def _fuzzy_intent(clause: str) -> bool:
    if not ASSETS.is_loaded:
        return False
    stems = [stem for stem in ASSETS.get().context.addr_intent if " " not in stem and len(stem) >= 5]
    for token in _CYR_TOKEN_RE.findall(clause):
        word = re.sub(r"([а-яё])\1+", r"\1", token.lower())
        if len(word) < 5:
            continue
        for stem in stems:
            for length in (len(stem) - 1, len(stem), len(stem) + 1):
                if 4 <= length <= len(word) and within_one_typo(word[:length], stem):
                    return True
    return False


def _intent_before(text: str, start: int, address: AddressAssets) -> bool:
    """An INTENT word in the sentence tail — never a bare preposition.

    The stricter half of `_cue_before`, and the arms that have no house number
    use only this one. «на улицах Каира собрались десятки» and «на улицах
    американских городов» open with «на» exactly as an address does, so
    `prep_before` cannot separate prose ABOUT streets from somebody's address;
    only a person saying they live or receive things there can. Measured,
    accepting the preposition here cost 0.1pp of NEREL precision.

    One function rather than the same three lines in three arms: they have to
    agree about the window and the sentence boundary, and a copy is where two
    of them stopped agreeing."""
    tail = text[max(0, start - _CUE_WINDOW):start]
    clause = _SENTENCE_SPLIT.split(tail + text[start:start + 1])[-1]
    if address.addr_ctx.search(clause):
        return True
    # THE INTENT WORD MAY BE MISTYPED, like every cue («курьеа на мончегорсуая
    # 195»): a stretched or one-typo intent word is the same intent, judged on
    # the stem the way a mistyped street type is.
    if _fuzzy_intent(clause):
        return True
    # AND AFTER IT, because speech puts the intent on the other side. Written
    # traffic says «адрес доставки: улица Пушкина»; a telephone says «улица
    # пушкина дом колотушкина ПОДЪЕЗЖАЙ» and «милашекова улицу знаешь ПРИЕЗЖАЙ
    # туда». Measured on real call transcripts, looking only backwards left
    # those unfound while the intent word sat four words to the right.
    #
    # Same window and the same sentence boundary as the backward half — an intent
    # word in the NEXT sentence is about something else, and «Улица» capitalised
    # after a period is exactly the boundary the split is built to see.
    head = text[start:start + _CUE_WINDOW]
    return bool(address.addr_ctx.search(_SENTENCE_SPLIT.split(head)[0]))


def _cue_before(text: str, start: int, address: AddressAssets) -> bool:
    # The candidate's own first character joins the tail before splitting: a
    # sentence end is «. » FOLLOWED BY A CAPITAL, and that capital is the first
    # letter of the span being judged. Without it «Адрес склада: Тверская 7.
    # Отгрузка 5 коробок» kept the cue alive across the period and masked
    # «Отгрузка 5».
    return (_intent_before(text, start, address)
            or bool(address.prep_before.search(text[:start])))


def _toponym_neighbours(text: str, cands: list[tuple[int, int, bool]]
                        ) -> list[tuple[int, int, bool]]:
    """A bare city touching an address part, as SUPPORT.

    «ул. Садовая 23, Екатеринбург» and «москва, проспект вернадского 45» kept
    their street and lost their city — so the address was masked and the CITY
    the person lives in went to the model beside it, inside a span that already
    looked protected.

    SUPPORT, never core, and that is what keeps the «bare toponym is not PII»
    rule intact: a city standing alone produces a candidate that merges with
    nothing and is dropped, so «доставка по Москве» is untouched exactly as
    before. Only a city that TOUCHES a street or a house becomes part of it.

    Looked up only beside an existing candidate rather than over every word in
    the text. That is not a shortcut for its own sake — morphology holds the GIL
    and this runs on the request path, so the cost has to be O(candidates).
    """
    out: list[tuple[int, int, bool]] = []
    for start, stop, core in cands:
        if not core:
            continue
        left = _NEIGHBOUR_LEFT.search(text[:start])
        if left and _is_toponym(left.group(1)):
            out.append((_city_first_word(text, left.start(1)), left.end(1), False))
        right = _NEIGHBOUR_RIGHT.match(text[stop:])
        if right and _is_toponym(right.group(1)):
            out.append((stop + right.start(1), stop + right.end(1), False))
    return out


# A SENTENCE ENDED BETWEEN THE TWO PARTS. The gap vocabulary has to contain the
# period, because «ул.» and «д.» are built from it — and that let an address run
# straight through the end of its sentence: «Наш адрес: г. Москва, ул. Ленина,
# д. 14. Часы 9-21» masked as ONE address ending in «Часы 9», so a shop's
# opening hours were replaced by a house number and the model could no longer
# answer what time it opens.
#
# A period is an abbreviation when a lower-case word or a single letter follows
# it, and a sentence end when a capital does. That is the only signal available
# here and it is the one Russian actually uses.
_SENTENCE_END = re.compile(r"\.\s*$")


def _ends_sentence(gap: str, follows: str) -> bool:
    return bool(_SENTENCE_END.search(gap)) and follows[:1].isupper()


# «дом» as a marker, not as the first syllable of «домой» or «домашний».
_HOUSE_MARKER_RE = re.compile(r"(?i)(?:дом(?![а-яё])|д\.)")
# The one word standing immediately in front of it. Four letters, because that
# is the shortest name the ГАР register actually holds («Мира», «Тихая»).
_NAME_BEFORE_HOUSE_RE = re.compile(r"([А-Яа-яЁё]{4,})\s+$")
_NAME_COMMA_BEFORE_HOUSE_RE = re.compile(r"([А-Яа-яЁё]{4,}),\s*$")
_CITY_STREET_HOUSE_RE = re.compile(
    r"(?<![А-Яа-яЁё])([А-ЯЁ][а-яё-]+(?:\s[А-ЯЁ][а-яё-]+)?),\s*([А-Яа-яЁё]{4,}),\s*(\d{1,3}(?:[а-яё](?![а-яё]))?)(?!\d)")
_CITY_CLAUSE_BEFORE_RE = re.compile(r"[А-ЯЁ][а-яё-]+(?:\s[А-ЯЁ][а-яё-]+)?,\s*$")


def _street_before_house(text: str, cands: list[tuple[int, int, bool]],
                         address: AddressAssets) -> list[tuple[int, int, bool]]:
    """A bare street name standing in front of «дом N», with no type word.

    «бибиревская дом семнадцать в квартира двести двадцать девять» — dictated
    into a telephone, and every arm that could have found the street wants
    something this utterance does not have. The marked arms want «улица»; the
    marker-less ones want a capital or a digit; the chain starts at «дом» by
    construction. So the address was masked from «дом» onwards and the street
    name — the half that says WHICH building — went to the model in the clear,
    inside a span the polnota column was already counting as found.

    THE VOCABULARY IS THE ONLY EVIDENCE ACCEPTED, and exactly as written. Not
    morphology: in lower case «бибиревская», «широкая» and «пустая» are one
    part of speech, and the whole point of a leased register is that it cannot
    generalise to prose the way a grammar rule does. Not the normal form and
    not the nominative either — those are what `_fuzzy_street_candidates` may
    afford, because it conjoins three signals; here there are two.

    The second one is the marker. «дом» followed by a number says a building
    comes next, and Russian does not put an adjective in front of it for any
    other reason — the word order saves us as much as the vocabulary does,
    since «дом культуры» and «дом отдыха» put the register word AFTER.

    SUPPORT, never core: it can only ever lengthen an address somebody else
    already found, and alone it is dropped.
    """
    out: list[tuple[int, int, bool]] = []
    for start, _stop, core in cands:
        if not core:
            continue
        core_out = False
        if _HOUSE_MARKER_RE.match(text, start) is not None:
            before = _NAME_BEFORE_HOUSE_RE.search(text[:start])
        else:
            # THE WRITTEN FORM WITH COMMAS: «Ижевск, Маяковского, 141» — the
            # street is a surname in the genitive, a comma stands between it
            # and the house, and the town's own clause stands before it. With
            # no marker the number alone opened nothing, so the street went
            # to the model as a PERSON and the house as an address (clean
            # register, decompose-016). The city clause is what licenses it:
            # «Иванова, 25 лет» has no town in front.
            before = _NAME_COMMA_BEFORE_HOUSE_RE.search(text[:start])
            if before is None or _CITY_CLAUSE_BEFORE_RE.search(text[:before.start(1)]) is None:
                continue
            # Vouched three ways — the register, a town in front, a house after —
            # so it is a core the town can attach to (`_toponym_neighbours`).
            core_out = True
        if before is None:
            continue
        word = before.group(1).lower()
        # A MONTH IS IN THE REGISTER AND IS NOT A STREET HERE. «8 Марта» is a
        # real street name, which is why «марта» is in the vocabulary at all —
        # and «марта дом» is a date meeting a noun. The same exclusion
        # `_lower_is_street` makes, for the same reason.
        if word in address.month_after or word in ("года", "год", "лет"):
            continue
        if word not in address.street_names and word not in address.street_gaz:
            # A MISTYPED STREET IN FRONT OF «ДОМ N», behind an intent word:
            # «курьера на ленна дом сорок три а» — the marker and the number
            # say a building follows, somebody says they are sending a
            # courier there, and the word is one edit from the register and
            # no ordinary word. Three signals, the same count the fuzzy arms
            # ask for; the register as written stays the rule without them.
            if not (_typo_of_a_street(word, address) and _intent_before(text, before.start(1), address)):
                continue
        out.append((before.start(1), start, core_out))
    return out


def _city_street_house_candidates(text: str, address: AddressAssets) -> list[tuple[int, int, bool]]:
    """«Москва, Ленина, 14» — the commonest WRITTEN form of a Russian address,
    and no arm opened it: a bare number is never a core, so the street had
    nothing to stand in front of, and the street — a surname in the genitive
    — was minted as a PERSON. The town's clause, a street the register knows
    in any of its forms and a number after it, with the age and measure vetoes
    the bare arm already applies. A core, so the town attaches to it."""
    out: list[tuple[int, int, bool]] = []
    for match in _CITY_STREET_HOUSE_RE.finditer(text):
        if not _is_toponym(match.group(1).split()[-1]):
            continue
        if not _gar_reaches(match.group(2), address):
            continue
        if address.measure_after.match(text, match.end(3)) or address.age_after.match(text, match.end(3)):
            continue
        if _counts_next_word(text, match.end(3), match.group(3), address):
            continue
        out.append((match.start(2), match.end(3), True))
    return out


def _merge(cands: list[tuple[int, int, bool]], text: str,
           address: AddressAssets) -> list[tuple[int, int, bool]]:
    cands = sorted(cands)
    groups: list[list[object]] = []
    for start, stop, core in cands:
        if groups:
            gs, ge, gcore = groups[-1]
            joinable = start <= ge or (
                start - ge <= 4 and address.gap.fullmatch(text[ge:start]) is not None
                and not _ends_sentence(text[ge:start], text[start:]))
            if joinable:
                groups[-1] = [gs, max(ge, stop), gcore or core]
                continue
        groups.append([start, stop, core])
    return [(g[0], g[1], g[2]) for g in groups]


def _strip(start: int, stop: int, text: str) -> tuple[int, int]:
    while start < stop and text[start] in " ,.;-/№#()":
        start += 1
    while stop > start and text[stop - 1] in " ,.;-/№#()":
        stop -= 1
    return start, stop


