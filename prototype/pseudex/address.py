"""High-recall Russian address detection (problem B).

No single local tool catches marker-less RU addresses at high recall, so recall
comes from the UNION of three sources, merged into maximal spans:

  1. Natasha AddrExtractor (Yargy grammar, via pymorphy3) — marker-bearing parts
     (город/улица/дом/квартира/посёлок/индекс), incl. marker-LAST streets.
  2. Broadened regex anchors — street types in both orders, house/корпус/строение,
     микрорайон, settlements, apartments, compact forms ("д12", "д5к2") that
     AddrExtractor misses.
  3. Morphology-gated marker-less streets ("Ленина 5", "Советская 8"): a
     Capitalized token tagged Surn/ADJF/Geox (or in a street gazetteer) + a
     1-3 digit house number. The name is also caught by NAME detection; this
     rule additionally masks the trailing house number.

Adjacent candidates are merged into one LOC span and a trailing bare house
number is swallowed. PRECISION: a merged span survives only if it holds a CORE
part (street/house/микрорайон/marker-less-street) — a lone city or lone
apartment is dropped (so "магазин в Москве" stays unmasked). A negative
dictionary kills square-meters ("5 кв.м") and abbreviations ("и т.д.").
"""

import logging
import os
import re
import threading

from pseudex import _morph_compat  # noqa: F401  (aliases pymorphy2->pymorphy3 before natasha)

from pseudex.assets import ASSETS, AddressAssets
from pseudex.detect import Span
from pseudex.morph import MORPH

_log = logging.getLogger("pseudex.address")

# Natasha's AddrExtractor is a Yargy grammar, and it is EXPENSIVE: measured at
# ~137 ms per 1000 characters, ~100% of it inside the rule automaton (the morph
# tokenizer is 0.02 ms). It costs ~7 ms even on English text containing no
# address at all — the cost is a function of length, not of content. In the stage
# profiler it was 84% of total masking time.
#
# Against that: ablation across three independently-seeded address benchmarks
# (712 addresses) plus the dirty set with hard negatives found it contributes
# ZERO additional entities — the regex + morphology arms already caught every
# one, at 1/8th the cost.
#
# PSEUDEX_ADDR_EXTRACTOR:
#   off     (default) regex + morphology only — fast
#   on                union with the extractor — the original behaviour
#   shadow            union is used for MASKING (so recall is never reduced),
#                     and anything only the extractor found is logged at WARNING
#
# `shadow` is how you earn the right to run `off` in production: the benchmarks
# here are synthetic and generated by this repo, so they may share blind spots
# with the regex arm. Run `shadow` at a canary; if the log stays silent on real
# traffic, `off` is safe. Never infer that from the synthetic sets alone —
# dropping a recall arm from a fail-closed gateway is a one-way door.
_MODE = os.environ.get("PSEUDEX_ADDR_EXTRACTOR", "off").lower()
if _MODE not in ("off", "on", "shadow"):
    raise ValueError(
        f"PSEUDEX_ADDR_EXTRACTOR must be off|on|shadow, got {_MODE!r}"
    )

USE_EXTRACTOR = _MODE in ("on", "shadow")
SHADOW = _MODE == "shadow"

# Built lazily and only when actually used: constructing MorphVocab loads
# dictionaries into every worker process, so `off` should not pay that in memory
# or in startup time either.
_EXTRACTOR = None
_EXTRACTOR_LOCK = threading.Lock()


def _extractor():
    global _EXTRACTOR
    if _EXTRACTOR is None:
        with _EXTRACTOR_LOCK:
            if _EXTRACTOR is None:
                from natasha import AddrExtractor, MorphVocab
                _EXTRACTOR = AddrExtractor(MorphVocab())
    return _EXTRACTOR

# The street gazetteer, the core-part vocabulary and every pattern below are
# LEASED (see pseudex/assets.py) — this module holds the rules that consume them,
# not the vocabulary itself. Patterns are compiled once when the bundle loads.
_WORD_SPLIT_RE = re.compile(r"[\s-]")


def _part_is_core(part_type: str, address: AddressAssets) -> bool:
    return any(key in part_type for key in address.core_part)


def _word_is_street(word: str, address: AddressAssets) -> bool:
    low = word.lower()
    if low in address.street_gaz:
        return True
    tag = MORPH.parse(word)[0].tag
    if "Name" in tag and "Surn" not in tag:  # a bare first name is not a street
        return False
    # A SETTLEMENT IS NOT A STREET, and a house number does not attach to one.
    # «погода в Сочи 25 градусов» and «курс в Сочи 25 рублей» became addresses
    # because `Geox` alone was accepted — but Geox is what names a CITY, and a
    # city with a number after it is a temperature or a price, never a door.
    # Street names that happen to be toponyms carry another reading too:
    # «Тверская» is ADJF, «Ленина» and «Гагарина» are Surn. Only a word whose
    # ONLY reading is a place is refused.
    if "Geox" in tag and "Surn" not in tag and "ADJF" not in tag:
        return False
    return "Surn" in tag or "ADJF" in tag or "Geox" in tag


def _lower_is_street(phrase: str, address: AddressAssets) -> bool:
    """Street-name decided by VOCABULARY ALONE, for text with no capitals.

    Deliberately not `_is_street_name`: that one also accepts a morphological
    reading, which is the right trade when a capital letter is carrying half the
    evidence and the wrong one when it is not. Lower-case Russian prose is full
    of words pymorphy calls an adjective or a surname.
    """
    for word in _WORD_SPLIT_RE.split(phrase):
        low = word.lower()
        if not low or low not in address.street_gaz:
            continue
        # A MONTH NAMES A STREET ONLY BEHIND A NUMBER. «марта», «мая» and
        # «октября» are in the street vocabulary for «8 Марта» and «1 Мая», and
        # in lower case with no number they are simply dates: «14 марта ему
        # исполнилось 60» became an address on the strength of that entry alone.
        # The numbered form has its own pattern (`numbered_st`), which requires
        # the number, so excluding them here costs nothing and closes the only
        # place the vocabulary lies.
        if low in address.month_after or low in ("года", "год", "лет"):
            continue
        return True
    return False




def _names_a_settlement(phrase: str, address: AddressAssets) -> bool:
    """Whether every word here names a PLACE and nothing else.

    A city takes no house number. «погода в Сочи 25 градусов», «курс в Сочи 25
    рублей», «в Москве 12 филиалов» and «доставка по Казани 3 дня» all became
    addresses, and all four were licensed by nothing more than the preposition
    in front — `prep_before` is accepted as context on its own, so the
    morphological test never ran.

    So this is a veto rather than a vote: whatever the context says, a
    settlement plus a number is a temperature, a price or a count, never a door.
    Street names that happen to be toponyms are untouched, because they carry a
    second reading — «Тверская» is ADJF, «Ленина» and «Гагарина» are Surn — and
    only a word whose ONLY reading is a place is refused.
    """
    words = [word for word in _WORD_SPLIT_RE.split(phrase) if word]
    if not words:
        return False
    for word in words:
        if word.lower() in address.street_gaz:
            return False
        # EVERY READING, not the best one. «Тверская» has a Geox reading that
        # outranks its adjectival one, so `parse[0]` refused a real street — the
        # same trap that made «марину» resolve to a man. A word is a settlement
        # only when NOTHING it can be is a surname or an adjective.
        parses = MORPH.parse(word)
        if not any("Geox" in parse.tag for parse in parses):
            return False
        if any("Surn" in parse.tag or "ADJF" in parse.tag for parse in parses):
            return False
    return True


def _lower_names_a_street(phrase: str, address: AddressAssets) -> bool:
    """Whether a lower-case word beside a street-type word can be its NAME.

    Needed only where no house number stands to hold the match down. «улица была
    пустой» is the shape this refuses, and it refuses it the same way the city
    adjective is judged: a QUALITATIVE adjective describes a street, a relative
    one names it. «пустой», «длинной», «главной», «новой», «красивой» and
    «широкой» are all Qual; «тверской», «центральной» and «садовой» are not.
    Pronominal readings («нашей», «этой») go out with `Apro`.

    The vocabulary path stays first, because the commonest Russian street names
    are genitive nouns with no adjective reading at all — «мира», «ленина»,
    «строителей».
    """
    for word in _WORD_SPLIT_RE.split(phrase):
        low = word.lower()
        if not low:
            continue
        if low in address.street_gaz:
            return True
        parses = MORPH.parse(word)
        if any("Surn" in parse.tag or "Geox" in parse.tag for parse in parses):
            return True
        adjectives = [parse for parse in parses if "ADJF" in parse.tag]
        if adjectives and all("Qual" not in parse.tag and "Apro" not in parse.tag
                              for parse in adjectives):
            return True
    return False


def _is_street_name(phrase: str, address: AddressAssets) -> bool:
    """Street-name if ANY word (or hyphen part) looks like a toponym/surname/adj."""
    for word in _WORD_SPLIT_RE.split(phrase):
        if word and _word_is_street(word, address):
            return True
    return False


def _natasha_candidates(text: str, address: AddressAssets) -> list[tuple[int, int, bool]]:
    if not USE_EXTRACTOR:
        return []
    out: list[tuple[int, int, bool]] = []
    for match in _extractor()(text):
        part_type = getattr(match.fact, "type", None) or ""
        out.append((match.start, match.stop, _part_is_core(part_type, address)))
    return out


def _log_shadow_diff(text: str, natasha: list[tuple[int, int, bool]],
                     regex: list[tuple[int, int, bool]]) -> None:
    """Report spans ONLY the extractor found, so a canary can prove whether the
    regex arm is a superset on real traffic. Logs offsets and lengths, never the
    matched text — this runs on live customer data and the log must stay PII-free."""
    uncovered = [
        (start, stop) for start, stop, _ in natasha
        if not any(start < r_stop and stop > r_start for r_start, r_stop, _ in regex)
    ]
    if uncovered:
        _log.warning(
            "addr_shadow: extractor found %d span(s) the regex arm missed "
            "(offsets=%s, text_len=%d) — regex arm is NOT a superset here",
            len(uncovered), uncovered, len(text),
        )


def _regex_candidates(text: str, address: AddressAssets) -> list[tuple[int, int, bool]]:
    out: list[tuple[int, int, bool]] = []
    for rx in (address.street_first, address.street_last, address.street_lower_first,
               address.street_lower_last, address.street_abbr_lower,
               address.house, address.mkr, address.rural):
        for m in rx.finditer(text):
            out.append((m.start(), m.end(), True))   # core
    for rx in (address.apt, address.settlement, address.index, address.district):
        for m in rx.finditer(text):
            out.append((m.start(), m.end(), False))  # support
    for m in address.markerless.finditer(text):
        # words is always Capitalized here. Accept if it has a morphological
        # street signal, is a numbered street ("8 Марта"), or sits in an address
        # context (Presidio-style enhancement for signal-less "Миклухо-Маклая 6").
        before = text[:m.start()]
        has_ctx = _cue_before(text, m.start(), address)
        # A NUMBER FOLLOWED BY A MONTH IS A DATE, not a house. «подписана
        # Президентом Российской Федерации 5 августа 2000 года» matched as a
        # marker-less street with house 5: «Российской» is an adjective, which
        # is all the morphology gate asks for, and the date was destroyed along
        # with it. Found on 993 sentences of ordinary Russian — the shape is
        # ordinary legal prose, and no set of ours contained it.
        after = text[m.end():m.end() + 12].lstrip()
        if any(after.lower().startswith(month) for month in address.month_after):
            continue
        if _names_a_settlement(m.group("words"), address):
            continue
        if _is_street_name(m.group("words"), address) or m.group("num") or has_ctx:
            out.append((m.start(), m.end(), True))   # core (street + house number)
    for m in address.street_lower_nohouse.finditer(text):
        # AN INTENT WORD, NOT A PREPOSITION. Every other lower-case arm accepts
        # `prep_before` as its context, and here that is far too little: «на
        # улицах Каира собрались десятки» and «на улицах американских городов»
        # both open with «на». What separates a person's address from prose
        # ABOUT streets is somebody saying they live or receive things there —
        # «проживает», «адрес:», «доставка» — and that is `addr_ctx` alone.
        name = m.group("after") or m.group("before") or ""
        tail = text[max(0, m.start() - _CUE_WINDOW):m.start()]
        if not address.addr_ctx.search(_SENTENCE_SPLIT.split(tail + text[m.start():m.start() + 1])[-1]):
            continue
        if _lower_names_a_street(name, address):
            out.append((m.start(), m.end(), True))   # core
    for m in address.markerless_lower.finditer(text):
        # LOWER CASE, SO THE GATE IS THE VOCABULARY AND NOTHING ELSE.
        # `_is_street_name` would be wrong here: it accepts a morphological
        # signal, and in lower case «течение», «решение», «Вашингтоне» all carry
        # one. The capital was the second signal; with it gone, the only
        # admissible evidence is a word the leased street vocabulary actually
        # names. That cannot generalise to ordinary prose, which is exactly the
        # property needed.
        if not _lower_is_street(m.group("lwords"), address):
            continue
        # THE VOCABULARY ALONE IS NOT ENOUGH, and the corpus said so: «14 марта
        # ему исполнилось 60», «в конце марта 55» and «в виде лишения свободы 2»
        # all matched, because «марта» and «свободы» are in the street
        # vocabulary — they name real streets — and in lower case there was
        # nothing left to tell a street from the date and the sentence it
        # actually was. The capitalised arm never had this problem: the capital
        # WAS the second signal.
        #
        # So the lower-case arm demands an address context in its place — a cue
        # word («адрес», «доставка») or a preposition directly before it. Both
        # already exist and are already leased. «вы находитесь на ленина 14»
        # keeps its «на»; «лишения свободы 2» has «лишения» before it and is
        # refused.
        if not _cue_before(text, m.start(), address):
            continue
        after = text[m.end():m.end() + 12].lstrip()
        if any(after.lower().startswith(month) for month in address.month_after):
            continue
        out.append((m.start(), m.end(), True))   # core (street + house number)
    for m in address.numbered_st.finditer(text):  # lowercase names ("1905 года 12")
        # AN INTENT WORD, not merely a preposition. «на 8 марта 5 подарков» is a
        # date and a quantity — the commonest sentence in Russian retail in
        # March — and it opens with «на» exactly as an address does. Nothing in
        # the shape separates them, so the separation has to come from somebody
        # saying they live or receive things there. The marked form («улица 8
        # марта 5») has its own pattern and needs no cue.
        tail = text[max(0, m.start() - _CUE_WINDOW):m.start()]
        if not address.addr_ctx.search(
                _SENTENCE_SPLIT.split(tail + text[m.start():m.start() + 1])[-1]):
            continue
        out.append((m.start(), m.end(), True))
    for m in address.numbered_marked.finditer(text):  # "1905 года тупик"
        out.append((m.start(), m.end(), True))
    return out



# A word and the punctuation that may stand between it and an address part.
_NEIGHBOUR_LEFT = re.compile(r"([А-Яа-яЁё][А-Яа-яЁё-]*)[\s,.;]{0,3}$")
_NEIGHBOUR_RIGHT = re.compile(r"^[\s,.;]{0,3}([А-Яа-яЁё][А-Яа-яЁё-]*)")


def _is_toponym(word: str) -> bool:
    """Whether morphology calls this word a place name.

    pymorphy's dictionary already carries the toponym vocabulary and tags it
    `Geox`, INDEPENDENTLY OF CASE — «екатеринбург», «москва» and «люберцы» all
    carry it. That is the whole reason no city gazetteer is leased for this: a
    tuned list of a thousand cities would be a new asset to maintain and to
    ship, and it would buy a separation the dictionary already makes cleanly.
    Measured on every word this rule can see, the split is exact: every city
    carries Geox and «приезжайте», «спасибо», «заказ», «доставка», «офис» carry
    none.
    """
    return any("Geox" in parse.tag for parse in MORPH.parse(word))



def _city_first_word(text: str, city_start: int) -> int:
    """Extend a city left over the adjective that is part of its NAME.

    «Нижний Новгород» is two words and only the second carries `Geox`, so the
    span began at «Новгород» — the address was masked, and detokenisation handed
    the tool a city that does not exist. Six of AgentPII-RU's round trips broke
    exactly there.

    Two signals, because ADJF alone is far too wide: «красивый», «большой»,
    «новый», «этот» and «наш» are all ADJF too, and swallowing them would put
    ordinary words inside an address.

      * the reading must not be QUALITATIVE (`Qual`) or pronominal (`Apro`) —
        that alone separates «Нижний», «Великий» and «Набережные» from
        «красивый», «большой» and «наш»;
      * OR the word must be capitalised the same way the city is, which is what
        keeps «Старый Оскол» and «Новый Уренгой» (both `Qual`) while refusing
        «красивый Екатеринбург», where the adjective is lower case and the city
        is not.

    In all-lowercase chat the second signal is unavailable on both sides, so the
    first decides — and it is the one that holds there.
    """
    head = _NEIGHBOUR_LEFT.search(text[:city_start])
    if head is None:
        return city_start
    word = head.group(1)
    parses = [parse for parse in MORPH.parse(word) if "ADJF" in parse.tag]
    if not parses:
        return city_start
    naming = any("Qual" not in parse.tag and "Apro" not in parse.tag
                 for parse in parses)
    agrees = word[:1].isupper() == text[city_start:city_start + 1].isupper()
    return head.start(1) if naming or agrees else city_start



# HOW FAR A CUE WORD REACHES. `addr_ctx` used to be searched over the ENTIRE
# preceding text, so one «адрес» near the top of a system prompt licensed every
# capitalised-word-plus-number for the rest of it: «Наш адрес: …, д. 14. Часы
# 9-21» masked «Часы 9» as a second address, and the model could no longer say
# when the shop opens.
#
# Bounded to the tail, and never across a sentence end — a cue in one sentence
# says nothing about the next. The window is generous enough for the phrasings
# the cue vocabulary is written for («мой адрес для доставки — …»).
_CUE_WINDOW = 60
_SENTENCE_SPLIT = re.compile(r"[.!?]\s+(?=[А-ЯЁA-Z])")


def _cue_before(text: str, start: int, address: AddressAssets) -> bool:
    # The candidate's own first character joins the tail before splitting: a
    # sentence end is «. » FOLLOWED BY A CAPITAL, and that capital is the first
    # letter of the span being judged. Without it «Адрес склада: Тверская 7.
    # Отгрузка 5 коробок» kept the cue alive across the period and masked
    # «Отгрузка 5».
    before = text[:start]
    tail = _SENTENCE_SPLIT.split(before[-_CUE_WINDOW:] + text[start:start + 1])[-1]
    return bool(address.addr_ctx.search(tail)) or bool(address.prep_before.search(before))


def _toponym_neighbours(text: str, cands: list[tuple[int, int, bool]]
                        ) -> list[tuple[int, int, bool]]:
    """A bare city touching an address part, as SUPPORT.

    «ул. Садовая 23, Екатеринбург» and «москва, проспект вернадского 45» kept
    their street and lost their city — so the address was masked and the CITY
    the person lives in went to the model beside it, inside a span that already
    looked protected.

    SUPPORT, never core, and that is what keeps the «bare toponym is not PII»
    rule intact: a city standing alone produces a candidate that merges with
    nothing and is dropped, so «доставка по Москве» is untouched exactly as
    before. Only a city that TOUCHES a street or a house becomes part of it.

    Looked up only beside an existing candidate rather than over every word in
    the text. That is not a shortcut for its own sake — morphology holds the GIL
    and this runs on the request path, so the cost has to be O(candidates).
    """
    out: list[tuple[int, int, bool]] = []
    for start, stop, core in cands:
        if not core:
            continue
        left = _NEIGHBOUR_LEFT.search(text[:start])
        if left and _is_toponym(left.group(1)):
            out.append((_city_first_word(text, left.start(1)), left.end(1), False))
        right = _NEIGHBOUR_RIGHT.match(text[stop:])
        if right and _is_toponym(right.group(1)):
            out.append((stop + right.start(1), stop + right.end(1), False))
    return out


# A SENTENCE ENDED BETWEEN THE TWO PARTS. The gap vocabulary has to contain the
# period, because «ул.» and «д.» are built from it — and that let an address run
# straight through the end of its sentence: «Наш адрес: г. Москва, ул. Ленина,
# д. 14. Часы 9-21» masked as ONE address ending in «Часы 9», so a shop's
# opening hours were replaced by a house number and the model could no longer
# answer what time it opens.
#
# A period is an abbreviation when a lower-case word or a single letter follows
# it, and a sentence end when a capital does. That is the only signal available
# here and it is the one Russian actually uses.
_SENTENCE_END = re.compile(r"\.\s*$")


def _ends_sentence(gap: str, follows: str) -> bool:
    return bool(_SENTENCE_END.search(gap)) and follows[:1].isupper()


def _merge(cands: list[tuple[int, int, bool]], text: str,
           address: AddressAssets) -> list[tuple[int, int, bool]]:
    cands = sorted(cands)
    groups: list[list[object]] = []
    for start, stop, core in cands:
        if groups:
            gs, ge, gcore = groups[-1]
            joinable = start <= ge or (
                start - ge <= 4 and address.gap.fullmatch(text[ge:start]) is not None
                and not _ends_sentence(text[ge:start], text[start:]))
            if joinable:
                groups[-1] = [gs, max(ge, stop), gcore or core]
                continue
        groups.append([start, stop, core])
    return [(g[0], g[1], g[2]) for g in groups]


def _strip(start: int, stop: int, text: str) -> tuple[int, int]:
    while start < stop and text[start] in " ,.;-/№#()":
        start += 1
    while stop > start and text[stop - 1] in " ,.;-/№#()":
        stop -= 1
    return start, stop


_CYRILLIC_TAIL_RE = re.compile(r"[А-Яа-яёЁ]$")
_LEADING_WORD_RE = re.compile(r"^([А-Яа-яёЁ]+)(\s+)")
# A number and the word after it, for the numbered-street case («8 Марта»).
_LEADING_NUMBER_RE = re.compile(r"^(\d+)\s+([А-Яа-яёЁ]+)\s")


def _trim_lead(start: int, stop: int, text: str, address: AddressAssets) -> int:
    """Drop leading words that INTRODUCE the address instead of naming it.

    A marker-less street is «прилагательное + тип» («ленинский проспект»), and
    the pattern that finds it cannot see where the name begins — so «адрес
    ленинский проспект 55» matched with «адрес» inside the street name, and
    «адрес» went to the customer's tool as part of the delivery address. The
    same swallow the NER person spans had, on the other entity.

    Two signals, both already present and neither a new list:

      * `addr_ctx` is the address CUE vocabulary — «адрес», «доставка»,
        «курьер». A cue is by definition context and never content.
      * `Apro` separates «мой»/«наш» from «Ленинский»/«Профсоюзная». All four
        parse as ADJF, so part of speech alone does not decide it; the
        pronominal flag does.

    A street TYPE word survives both tests, which is what keeps «улица
    Тверская» intact — trimming there would have eaten the half that makes the
    span an address at all.
    """
    while True:
        # A LEADING NUMBER IS A STREET ONLY IF A STREET NAME FOLLOWS. The
        # marker-less pattern accepts one so «8 Марта 12» stays whole, and that
        # is what swallowed «заказ 55512 на Новосибирск Красный проспект 88»
        # from the digits onwards: the model was handed «заказ Сосновый
        # проспект 4» and the order number was simply gone. A preposition after
        # the number settles it — «на» can begin a sentence about an address but
        # never a street's name.
        numbered = _LEADING_NUMBER_RE.match(text[start:stop])
        if numbered is not None:
            follower = MORPH.parse(numbered.group(2))
            if follower and follower[0].tag.POS == "PREP":
                start += numbered.start(2)
                continue
        match = _LEADING_WORD_RE.match(text[start:stop])
        if match is None:
            return start
        word = match.group(1)
        parses = MORPH.parse(word)
        best = parses[0].tag if parses else None
        pronominal = best is not None and "Apro" in best.grammemes
        preposition = best is not None and best.POS == "PREP"
        if not (pronominal or preposition or address.addr_ctx.fullmatch(word)):
            return start
        start += match.end()


def detect_address(text: str) -> list[Span]:
    address = ASSETS.get().address
    natasha = _natasha_candidates(text, address)
    regex = _regex_candidates(text, address)
    if SHADOW:
        _log_shadow_diff(text, natasha, regex)
    cands = natasha + regex
    if not cands:
        return []
    cands = cands + _toponym_neighbours(text, cands)
    # THE TRAILING HOUSE NUMBER HAS TO JOIN BEFORE THE SECOND MERGE, not after.
    #
    # «ул. Гагарина, 45, кв. 12» lost its flat while «ул. Гагарина 45 кв 12»
    # kept it, and the only difference is a comma. The street candidate is «ул.
    # Гагарина»; the house «, 45» arrives through `trail_house`, which used to
    # run AFTER merging. So at merge time the distance from the street to «кв»
    # was «, 45, » — six characters with digits in them — and the flat was
    # dropped for being too far. Extending first and merging again puts the flat
    # two characters away, where it belongs.
    #
    # 21 of the addresses PII-Bench annotates lose their «кв» exactly this way,
    # which makes it the single largest hole in address coverage.
    extended: list[tuple[int, int, bool]] = []
    for start, stop, core in _merge(cands, text, address):
        trail = address.trail_house.match(text[stop:])  # swallow "ул. Садовая, 3"
        if trail and _CYRILLIC_TAIL_RE.search(text[:stop]):
            stop += trail.end()
        extended.append((start, stop, core))

    spans: list[Span] = []
    for start, stop, core in _merge(extended + cands, text, address):
        if not core:
            continue
        start, stop = _strip(start, stop, text)
        start = _trim_lead(start, stop, text, address)
        start, stop = _strip(start, stop, text)
        value = text[start:stop]
        if not value or address.neg.search(value):
            continue
        spans.append(Span(start, stop, "LOC", value))
    return spans
