# ПАСПОРТ, ЗАПИСАННЫЙ СЛОВАМИ: серия и номер названы порознь, между ними слова.
# Значение пары — часть, которая обязана быть закрыта ЦЕЛИКОМ.
PASSPORT_PHRASES: tuple[tuple[str, str], ...] = (
    ("серия 4607 номер 238914", "серия 4607 номер 238914"),
    ("мой паспорт серия 4805 номер 234567 выдан", "серия 4805 номер 234567"),
    ("серия 5506 номер 789012", "серия 5506 номер 789012"),
    ("паспорт: серия 6203 номер 789012", "серия 6203 номер 789012"),
)


def check(ok: bool, name: str, detail: str = "") -> None:
    RESULTS.append((ok, name, detail))
    print(f"  {'PASS' if ok else 'RED '}  {name}" + (f"   {detail}" if detail else ""))


def spans(text: str) -> list[tuple[str, int, int]]:
    return [(s.entity_type, s.start, s.end) for s in DET.detect(text)]


def covered(text: str, gold: str) -> bool:
    """Каждый символ эталона накрыт хоть одним спаном — как считает прибор.

    Множество покрытых позиций, а не сумма длин: два перекрывающихся спана не
    объявляют покрытым то, что покрыто наполовину (`bench/eval_piibench.py`).
    """
    at = text.index(gold)
    end = at + len(gold)
    got: set[int] = set()
    for _, start, stop in spans(text):
        got |= set(range(max(at, start), min(end, stop)))
    return len(got) == end - at


def round_trips(text: str) -> tuple[bool, str]:
    """Замаскировать и вернуть: настоящий текст обязан вернуться символ в символ."""
    detected = DET.detect(text)
    if not detected:
        return True, "нечего маскировать"
    vault = Vault(":memory:", "tail-test")
    masked = redact.mask_text(text, vault, detected)
    back = redact.unmask_text(masked, vault)
    return back == text, f"masked={masked!r} back={back!r}"


