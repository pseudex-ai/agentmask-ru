"""Адрес: голова и хвост. Паспорт: свидетельство и фраза. Инвариант круга.

ЗАЧЕМ ЭТОТ ФАЙЛ. `bench/eval_piibench.py` печатает ДВЕ колонки, и разница между
ними — утёкший хвост. Пост-спринтовый замер дал ADDRESS 93.2% полноты при 77.8%
покрытия и PASSPORT 83.3% при 76.7%: значения НАХОДИЛИСЬ, а часть уходила к
модели открытым текстом внутри спана, который колонка полноты уже считала
закрытым.

Здесь стерегутся три класса, которые правятся в ЭТИХ файлах, —

  * НАЗВАНИЕ РЕГИОНА в начале адреса («Московская обл, Одинцово, Парковая 7»):
    правило «человек перед адресом» снимало его как имя, и в спан уезжало одно
    «обл»;
  * ГОРОД В КОНЦЕ адреса («ул. Садовая 23, Екатеринбург»): ключ волта читал
    этот хвост всегда, а читатель ролей — нет, и одна фраза давала КЛЮЧ С
    ГОРОДОМ и спан без него;
  * СЛОВО-ПОДСКАЗКА ДАЛЬШЕ ШЕСТНАДЦАТИ СИМВОЛОВ от паспорта — «паспортные
    данные арендатора: 4607238914» не находилось вовсе.

И ОДИН ИНВАРИАНТ, который важнее покрытия, — вектор 4. Хвост «…, кв. 87,
3 подъезд» расширить ЛЕГКО: `LOC_TOKEN_PATTERN` в `pseudex/vault.py` строил
окно восстановления как «подъезд N», то есть маркер-перед-числом, только с
твёрдым знаком и только перед «кв.», — а корпус пишет «N подъезд», «N под»,
«подьезд N» и «N этаж». Спан, включающий такой хвост, чеканил подмену, которую
восстановитель не находил: `redact.unmask_text` возвращал её же, и в инструмент
клиента уходил адрес, которого нет в волте.

ХВОСТ И ВОССТАНОВИТЕЛЬ РАСШИРЕНЫ ВМЕСТЕ, и теперь векторы 6-8 стерегут ОБЕ
половины этого одного изменения: спан обязан накрыть часть ЦЕЛИКОМ (иначе
утечка вернётся) И круг обязан сойтись (иначе вернётся фейк в инструменте).
Красный на любом из них означает, что половины разошлись, — и это ровно тот
дефект, которым эта работа началась. Замерено на PII-Bench: ADDRESS 80.1% ->
88.6% покрытия, PASSPORT 83.3% -> 90.0%, и ни одного нового расхождения круга
(132 против 134 на исходном коде — два исправлено).

    python3 test_addr_passport_tail.py
"""

