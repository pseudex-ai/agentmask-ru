# ВЕКТОР 1. РЕГИОН В НАЧАЛЕ.
#
# «Московская обл, Одинцово, Парковая 7» резалось до «обл, …»: у «Московская»
# есть разбор-существительное, остаток — настоящий адрес, и правило «человек
# перед адресом» снимало НАЗВАНИЕ РЕГИОНА. Свидетельство уже было арендовано —
# `district` («Московская обл», «Свердловская область», «Краснодарский край»), —
# и спрашивается оно от начала спана, ничего не расширяя.
def vector_1_region_head() -> None:
    for text in ("Московская обл, Одинцово, Парковая 7",
                 "Московская область, г. Химки, ул. Победы 12",
                 "Московская область г. Химки ул. Победы 23",
                 "Свердловская область, г. Первоуральск, ул. Ленина 5",
                 "Краснодарский край, Сочи, ул. Морская 3"):
        check(covered(text, text), "1a регион в начале закрыт целиком", repr(text))


