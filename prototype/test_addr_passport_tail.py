# ВЕКТОР 5. НЕГАТИВЫ — ОБЫЧНЫЙ ДЕЛОВОЙ РУССКИЙ.
#
# Два негатива здесь ловят ИМЕННО цену этой правки, и оба измерены на HEAD:
#
#   * «паспортный стол закрыт, счёт 5301456789» — окно подсказки, выросшее ради
#     «паспортные данные арендатора: 4607238914», сделало паспортом ЧУЖОЙ СЧЁТ.
#     Слово, которым число ВВЕДЕНО («счёт»), — тот же арендованный deny-список,
#     которым это число снимает `context.suppress`; ветка с широким окном
#     спрашивает его сама.
#   * «Компания Ромашка область сбыта расширяет» — слово региона без НАЗВАНИЯ
#     региона регионом не является, и `district` от начала спана молчит.
#
# «дом 5 под ключ сдан» в список НЕ входит намеренно: голый «дом 5» — адрес и
# на HEAD (маркер дома сам себя объявляет адресом), к этой правке отношения не
# имеет и в её зачёт не идёт.
def vector_5_negatives() -> None:
    for text in ("Счёт 1234 от 15.05.2025 оплачен полностью.",
                 "Заказ №A-4471 собран, вес 4517 г, трек 812345.",
                 "Артикул 2024/117, партия 445, склад Б.",
                 "Объект 3 под охрану принят",
                 "доставка 3 под дождём не приехала",
                 "Офис в Екатеринбурге работает до 18:00.",
                 "Компания Ромашка область сбыта расширяет",
                 "паспортный стол закрыт, счёт 5301456789"):
        check(not spans(text), "5a не замаскировано", repr(text))


# --------------------------------------------------------------------------
# ВЕКТОР 6. ХВОСТ — ЧАСТЬ СПАНА, А НЕ ТЕКСТ РЯДОМ С НИМ.
#
# Круг (вектор 4) сам по себе НЕ доказывает, что хвост закрыт: пока спан
# обрывался на «кв. 12», круг сходился тоже — «подьезд 1» просто оставался у
# модели открытым текстом. Поэтому здесь спрашивается и покрытие: часть обязана
# лежать ВНУТРИ спана.
#
# ЧЕТЫРЕ ФОРМЫ ОДНОГО ХВОСТА, и все четыре написаны живым корпусом: «подьезд N»
# с мягким знаком, «N подъезд» числом-перед-маркером, «N под» сокращением и
# «N этаж». Пятая форма — «корпус 5» полным словом — идёт отдельной строкой:
# маркер там не подъезд, а домовая часть.
def vector_6_tail_is_covered() -> None:
    for text, part in TAIL_IN_SPAN:
        # Точка на конце сокращения («2 под.») в спан не входит и не должна:
        # `_strip` снимает конечную пунктуацию. Судится часть БЕЗ неё.
        wanted = part.rstrip(" .,;:")
        at = text.index(wanted)
        end = at + len(wanted)
        got = spans(text)
        covered = any(kind == "LOC" and start <= at and end <= stop
                      for kind, start, stop in got)
        check(covered, "6a хвост внутри спана", f"{part!r} <- {text!r} {got}")


# --------------------------------------------------------------------------
# ВЕКТОР 7. ПАСПОРТ ФРАЗОЙ: «серия 4607 номер 238914».
#
# ДВА СПАНА НА ЧИСЛА ЗАКРЫВАЛИ НЕ ВСЁ: слова «серия» и «номер» уходили к модели
# открытым текстом внутри адреса, который колонка полноты считала найденным, —
# то есть спан накрывал 10 символов из 23. Но расширить его было НЕЛЬЗЯ, пока
# паспортная половина `vault._token_re` знала только цифровую подмену
# «00 23 237431»: `_digits_laid_like` кладёт цифры подмены в СЛОТЫ ИСХОДНОЙ
# строки, поэтому расширенный спан чеканится «серия 0023 номер 237431» — и
# такой подмены восстановитель не находил вовсе. Это тот же класс «фейк в
# инструменте», что и хвост адреса, и правятся они вместе.
def vector_7_passport_phrase() -> None:
    for text, gold in PASSPORT_PHRASES:
        at = text.index(gold)
        end = at + len(gold)
        got = spans(text)
        covered = any(kind == "PASSPORT" and start <= at and end <= stop
                      for kind, start, stop in got)
        check(covered, "7a фраза паспорта закрыта целиком",
              f"{gold!r} <- {text!r} {got}")
        ok, detail = round_trips(text)
        check(ok, "7b круг на фразе паспорта", f"{text!r} {detail}")


