# ВЕКТОР 2. ГОРОД В КОНЦЕ.
def vector_2_city_tail() -> None:
    check(covered("ул. Садовая 23, Екатеринбург", "ул. Садовая 23, Екатеринбург"),
          "2a город в конце закрыт целиком")
    for text in ("ул. Ленина 5, Казань", "Москва, ул. Ленина 14"):
        check(covered(text, text), "2b адрес с городом закрыт целиком", repr(text))
    # НЕГАТИВ: у «Пушкин» есть разбор-фамилия, поэтому хвостовым городом он не
    # становится и остаётся человеком.
    for text, person in (("ленина 14, Пушкин", "Пушкин"),
                         ("ленина 14, Смирнов", "Смирнов")):
        got = spans(text)
        want = ("NAME", text.index(person), text.index(person) + len(person))
        check(want in got, "2c человек после адреса — человек", f"{text!r} -> {got}")


