# ВЕКТОР 8. ПОДМЕНА НЕСЁТ ТУ ЖЕ ЧАСТЬ, А НЕ ОДИН МАРКЕР.
#
# ЭТО НЕ ПРО КРУГ, А ПРО ИНСТРУМЕНТ. Схема клиента просит `entrance` и `floor`
# отдельными полями. Пока `_decorate_place` подъезд не чеканил, модель в подмене
# его не видела и клала в поле пустоту; пока не чеканила этаж, в маскированной
# строке оставалось «…, этаж» — маркер без числа, и номер этажа исчезал из
# текста вовсе. Обе половины проверляются здесь на САМОЙ подмене, а не на
# восстановленном значении: восстановление возвращает настоящее из волта и
# промолчит, даже если подмена части не несла.
def vector_8_substitute_carries_the_part() -> None:
    # Маркер подмены зеркалит КЛИЕНТА и знак тоже: корпус пишет «подьезд», и
    # подмена приходит с мягким знаком. Поэтому шаблон, а не слово.
    for text, word in (("Тула, улица Октябрьская, 67, 3 этаж", "этаж"),
                       ("Москва, ул. Профсоюзная, д. 45, корп. 2, кв. 87, 3 подъезд",
                        "под[ъь]езд"),
                       ("ул. Чехова 30 корпус 5 кв 12 подьезд 1", "под[ъь]езд")):
        vault = Vault(":memory:", "tail-test")
        masked = redact.mask_text(text, vault, DET.detect(text))
        # Порядок маркера и числа подмена МИРРОРИТ у клиента, поэтому обе
        # стороны пары допустимы: «подъезд 8» и «8 подъезд».
        carries = re.search(rf"(?i){word}\s*\d|\d\s*{word}", masked) is not None
        check(carries, "8a подмена несёт часть с числом", f"{text!r} -> {masked!r}")
        check(masked != text, "8b подмена не равна оригиналу", repr(masked))


# --------------------------------------------------------------------------
# ВЕКТОР 9. ГРАНИЦА ЧИСЛА-ПЕРЕД-МАРКЕРОМ: РАЗДЕЛИТЕЛЬ, А НЕ СЛОВО УЛИЦЫ.
#
# «Победы 81 подьезд 3» — дом 81 и подъезд 3. Если бы роль подъезда забирало
# ЧИСЛО СЛЕВА без оглядки, подъездом стал бы 81, домом — 3, а спан оборвался бы
# на «подьезд»: правка теряла бы ровно тот хвост, ради которого написана.
# Различает их РАЗДЕЛИТЕЛЬ перед числом: «…, 3 подъезд» — часть, «Победы 81
# подьезд» — нет. Здесь обе стороны одной монеты.
def vector_9_number_before_marker_guard() -> None:
    from pseudex import morph_places
    roles = morph_places.split_roles("Победы 81 подьезд 3")
    check(roles.get("house") == "81" and roles.get("entrance") == "3",
          "9a дом слева не отдан подъезду", repr(roles))
    roles = morph_places.split_roles("Победы 81 подьезд")
    check(roles.get("house") == "81" and "entrance" not in roles,
          "9b без числа после маркера подъезда нет", repr(roles))
    roles = morph_places.split_roles("Москва, ул. Ленина, д. 45, кв. 87, 3 подъезд")
    check(roles.get("entrance") == "3" and roles.get("house") == "45",
          "9c после разделителя число — часть", repr(roles))
    check(not spans("дом 5 под ключ сдан") or
          spans("дом 5 под ключ сдан")[0][2] <= len("дом 5"),
          "9d «под ключ» в спан не втянуто", repr(spans("дом 5 под ключ сдан")))


