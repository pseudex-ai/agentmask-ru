# ВЕКТОР 3. ПАСПОРТ: ПОДСКАЗКА ДАЛЬШЕ ШЕСТНАДЦАТИ СИМВОЛОВ.
#
# «паспортные данные арендатора: 4607238914» — цифры слитные, слово-подсказка
# стоит за двадцатью символами, и шаблон, требовавший её вплотную, не находил
# значение вовсе. Окно приведено к тому, которым это значение судит
# `context._passport_is_evidenced`: распознаватель и сторож обязаны спрашивать
# ОДНО и то же, иначе спан либо не родится, либо родится и будет снят.
def vector_3_passport_cue_window() -> None:
    cases = (
        "для договора аренды офиса нужны паспортные данные арендатора: 4607238914",
        "для оформления в штат нужны паспортные данные. присылаю: 5301456789",
        "оформить дебетовую карту. паспортные данные для идентификации: 4518123456",
        "Покупатель предоставил паспорт 4516728934. Прошу проверить на ограничения",
    )
    for text in cases:
        gold = "".join(ch for ch in text if ch.isdigit())[-10:]
        check(any(kind == "PASSPORT" and text[start:stop].isdigit()
                  for kind, start, stop in spans(text)),
              "3a слитный номер найден по широкому окну", repr(text))
        check(covered(text, gold), "3b найденное значение закрыто целиком", repr(gold))
    # НЕГАТИВ: без слова-подсказки слитные десять цифр остаются тем, чем и были.
    check(not spans("Для оформления трудового договора направляю: 5310 486321"),
          "3c без подсказки паспорта нет")


# --------------------------------------------------------------------------
# ВЕКТОР 4. ИНВАРИАНТ КРУГА, И ОН ЖЕ — ЗАПРЕТ НА ХВОСТ.
#
# Тот, кто будет расширять спан на «…, кв. 87, 3 подъезд», получит здесь красное
# и прочтёт причину: у клиента в инструменте оказался бы адрес, которого нет в
# волте. Круг — не второй способ измерить покрытие, а условие, при котором
# покрытие вообще разрешено поднимать.
def vector_4_round_trip_is_the_gate() -> None:
    for text in UNRESTORABLE_TAILS:
        ok, detail = round_trips(text)
        check(ok, "4a маска возвращается символ в символ", f"{text!r} {detail}")
    # И на тех классах, которые этим изменением правятся, круг тоже обязан
    # держаться — расширение головы и хвоста адреса не должно его ломать.
    #
    # «Московская область, г. Химки, ул. Победы 12» СЮДА НЕ ВХОДИТ, и это
    # измерено, а не забыто: её круг был сломан и на HEAD (восстановитель
    # собирал «Московская область, г. химки, победы ул.. 12»), то есть это
    # пре-существующий дефект формы «регион + г. + улица», а не инвариант,
    # который ломает эта правка. Покрытие по ней проверяет вектор 1.
    for text in ("Московская обл, Одинцово, Парковая 7",
                 "ул. Садовая 23, Екатеринбург",
                 "для договора аренды офиса нужны паспортные данные арендатора: 4607238914"):
        ok, detail = round_trips(text)
        check(ok, "4b круг на исправленных классах", f"{text!r} {detail}")


