"""Настройки, которые шаблон обязан видеть, чтобы текст не разошёлся с кодом."""

from django.conf import settings


def private_page(path: str) -> bool:
    """Закрытая страница: кабинет, админка, вход. Ни индексации, ни счётчиков."""
    return (path.startswith("/app/")
            or path.startswith(f"/{settings.ADMIN_PATH}")
            or path.startswith("/accounts/"))


def counters_allowed(path: str) -> bool:
    """Может ли ЭТА страница нести счётчики — нашу аналитику и чужую.

    ОДНА ФУНКЦИЯ НА ДВА МЕСТА, И ЭТО НЕ ЭКОНОМИЯ СТРОК. Решение принимают
    шаблон (`analytics` ниже) и заголовок CSP (`storefront_web.middleware`), и
    две копии одного решения расходятся молча: получилась бы страница, которая
    обещает не считать, и заголовок, который разрешает. Теперь разойтись они не
    могут — оба спрашивают здесь.

    ЗАКРЫТЫЕ СТРАНИЦЫ — ПО ОДНОЙ ПРИЧИНЕ: на экране кабинета префиксы ключей и
    суммы счетов, и запись сессии сделала бы их копию, которую никто не
    заказывал. Что делают КЛИЕНТЫ, мы знаем из своих серверных событий.

    И ОТДЕЛЬНО ОТ НИХ — ДВЕ ПУБЛИЧНЫЕ СТРАНИЦЫ, НА КОТОРЫХ ЛЕЖИТ СЕКРЕТ:

      * `/activate?t=…` несёт подписанный токен, названный в `views.activate`
        «работающий логин на 24 часа». Счётчик отправляет `location.href`, то
        есть токен ушёл бы в Яндекс ДАЖЕ С ВЫКЛЮЧЕННЫМ Вебвизором. Своя
        аналитика шлёт то же самое — так что дыра была и до Метрики, просто у
        себя, а не у третьей стороны;
      * `/welcome` показывает клиенту его лицензионный ключ прямо в разметке
        (блок `data-copy`), и при включённом Вебвизоре ключ попал бы в запись.

    ЭТО НЕ ТО ЖЕ САМОЕ, ЧТО `private_page`, И СМЕШИВАТЬ ИХ НЕЛЬЗЯ. Индексация
    считается по `private_page`: `/activate` без токена ведёт на главную, и
    закрывать его от робота незачем — в `robots.txt` он уже закрыт отдельно.
    Одна граница на два решения разъехалась бы ровно там, где её никто не
    проверяет.
    """
    return not private_page(path) and not path.startswith(("/activate", "/welcome"))


def analytics(request) -> dict[str, object]:
    """Режим аналитики — в каждый шаблон.

    ТЕКСТ НА ЛЕНДИНГЕ ГЕНЕРИРУЕТСЯ ИЗ НЕГО, а не пишется рядом. На странице
    стоит сильное обещание про отсутствие счётчиков и баннера; включить счётчик
    и оставить фразу значило бы опубликовать утверждение, не совпадающее с
    кодом. Тест, сравнивающий две копии, ловит расхождение; одна копия,
    выведенная из другой, не может разойтись вовсе.
    """
    counters = counters_allowed(request.path)
    # СЧЁТЧИК МЕТРИКИ — ПО ТОЙ ЖЕ ГРАНИЦЕ, НО НЕ ПО ТОМУ ЖЕ ФЛАГУ. Граница
    # одна, а решения разные: `analytics_here` — про наш Rybbit, `metrika_here`
    # — про третью сторону, и включить их можно порознь. Разными их держит не
    # аккуратность, а CSP: он пускает `mc.yandex.ru` ровно тогда, когда Метрика
    # настроена И страница не в списке исключений.
    metrika_here = bool(settings.METRIKA_ID) and counters
    return {"analytics": settings.ANALYTICS,
            "analytics_here": settings.ANALYTICS["mode"] != "off" and counters,
            "metrika_id": settings.METRIKA_ID if metrika_here else "",
            "support_bot": settings.SUPPORT_BOT,
            "support_email": settings.SUPPORT_EMAIL,
            # ТА ЖЕ ГРАНИЦА РЕШАЕТ И ИНДЕКСАЦИЮ — но по `private_page`, а не по
            # `counters_allowed`: страницы с секретом индексировать не вредно,
            # а закрытые — вредно. Признак один на «закрытое», другой на
            # «со счётчиком», и это разные вопросы.
            "indexable": not private_page(request.path),
            # Абсолютный адрес нужен канонической ссылке и карточке для
            # мессенджеров: относительный путь в `og:url` не работает нигде.
            "site_url": settings.SITE_URL,
            # ЕДИНЫЙ ВХОД СОТРУДНИКОВ, ЕСЛИ ОН ВКЛЮЧЁН, И ПУСТО, ЕСЛИ НЕТ.
            # Шаблон входа в админку показывает кнопку ровно тогда, когда путь
            # существует: кнопка, ведущая в 404, хуже отсутствующей.
            "sso_login_url": (f"/{settings.ADMIN_PATH}/oidc/authenticate/"
                              if getattr(settings, "OIDC_ENABLED", False) else ""),
            "sso_login_redirect": (f"/{settings.ADMIN_PATH}/"
                                   if getattr(settings, "OIDC_ENABLED", False) else ""),
            # Доска — в шапке админки. Пусто, если адрес не задан: ссылка
            # в никуда на экране оператора хуже, чем её отсутствие.
            "board_url": settings.BOARD_URL}
