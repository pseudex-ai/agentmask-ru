def by_slug(slug: str) -> dict | None:
    """Человек по адресу из QR. Нет такого — None, и view отдаёт 404.

    Адреса в QR напечатаны, и «похожего» человека здесь быть не должно: опечатка
    в адресе обязана кончаться 404, а не чужой страницей с чужим телефоном.
    """
    for person in TEAM:
        if person["slug"] == slug:
            return person
    return None


def tel_href(tel: str) -> str:
    """`tel:` без пробелов, дефисов и скобок — иначе часть телефонов не наберёт."""
    return "".join(ch for ch in tel if ch.isdigit() or ch == "+")


def vcard(person: dict) -> str:
    """vCard 3.0 для кнопки «Сохранить контакт».

    ПЕРЕВОДЫ СТРОК — CRLF, И ЭТО НЕ ПРИДИРКА: RFC 6350 требует CRLF, и клиенты,
    которые принимают только LF, существуют ровно до первого строгого. Файл на
    диске (`brand/business-cards/nfc/<slug>.vcf`) собирается с LF, потому что его
    читает человек глазами в редакторе; отдаваемый — с CRLF, потому что его
    читает телефон.
    """
    return "\r\n".join([
        "BEGIN:VCARD",
        "VERSION:3.0",
        f"N:;{person['name']};;;",
        f"FN:{person['name']}",
        "ORG:Pseudex",
        f"TITLE:{person['title']}",
        f"TEL;TYPE=CELL:{tel_href(person['tel'])}",
        f"EMAIL;TYPE=WORK:{person['mail']}",
        f"URL:{SITE}",
        "NOTE:Маскирование персональных данных для LLM-агентов. 152-ФЗ, "
        "контейнер в контуре клиента.",
        "END:VCARD",
        "",
    ])
