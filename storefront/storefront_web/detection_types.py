def missing_numbered() -> list[dict]:
    """`MISSING` для шаблона, с номерами и разбивкой на два раздела."""
    return [{"n": f"{index:02d}", "kind": kind, "title": title, "text": text}
            for index, (kind, title, text) in enumerate(MISSING, start=1)]


