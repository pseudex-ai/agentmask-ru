CODES = frozenset(group["code"] for group in GROUPS)


def _check() -> None:
    """Ссылка, которая не разрешается, роняет ИМПОРТ, а не отдаёт пустой экран.

    Опечатка в подписи типа иначе тихо выкинула бы его из группы: конфигуратор
    отвечал бы «находим» про меньшее, чем находим, и увидеть это можно было бы
    только глазами на живой странице.
    """
    labels = {label for label, _example, _holds in FOUND}
    for group in GROUPS:
        unknown = set(group.get("found", ())) - labels
        if unknown:
            raise ValueError(f"группа {group['code']}: нет таких типов в FOUND: {sorted(unknown)}")
        for index in group.get("missing", ()):
            if not 1 <= index <= len(MISSING):
                raise ValueError(f"группа {group['code']}: нет пункта {index} в MISSING")
        if not group.get("found") and not group.get("missing"):
            raise ValueError(f"группа {group['code']} ни на что не ссылается")
    if len(CODES) != len(GROUPS):
        raise ValueError("коды групп повторяются")
    # И ОБРАТНАЯ СТОРОНА, БЕЗ КОТОРОЙ ПРОВЕРКА ЛОВИЛА ПОЛОВИНУ. Выше сказано,
    # что группа не может сослаться на несуществующий тип; здесь — что тип не
    # может остаться без группы. Так и было: «ОГРН / ОГРНИП» лежал в FOUND и не
    # входил ни в одну группу, то есть на конфигураторе его просто не было, а
    # модуль, заведённый против расхождения, этого не видел.
    grouped = {label for group in GROUPS for label in group.get("found", ())}
    orphan = labels - grouped
    if orphan:
        raise ValueError(f"типы вне групп конфигуратора: {sorted(orphan)}")
    covered_missing = {index for group in GROUPS for index in group.get("missing", ())}
    lost = set(range(1, len(MISSING) + 1)) - covered_missing
    if lost:
        raise ValueError(f"пункты «не находим» вне групп: {sorted(lost)}")


_check()


def groups_for_page() -> list[dict]:
    """Группы для шаблона: покрытость выводится, а не хранится вторым полем —
    иначе появилось бы место, где «покрыта» и «ссылается на FOUND» разошлись."""
    return [{"code": group["code"], "label": group["label"],
             "covered": bool(group.get("found")),
             "verdict": group["verdict"]}
            for group in GROUPS]
