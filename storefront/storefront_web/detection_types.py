# Множество кодов групп — для проверки отметок конфигуратора в `views.demand`.
CODES = frozenset(group["code"] for group in GROUPS)


def _check() -> None:
    """Ссылка, которая не разрешается, роняет ИМПОРТ, а не отдаёт пустой экран."""
    labels = set(FOUND)
    for group in GROUPS:
        unknown = set(group.get("found", ())) - labels
        if unknown:
            raise ValueError(f"группа {group['code']}: нет таких типов в FOUND: {sorted(unknown)}")
        for index in group.get("missing", ()):
            if not 1 <= index <= len(MISSING):
                raise ValueError(f"группа {group['code']}: нет пункта {index} в MISSING")
        if (not group.get("found") and not group.get("missing")
                and not group.get("core_only") and not group.get("custom")):
            raise ValueError(f"группа {group['code']} ни на что не ссылается")
    # Коды групп не повторяются.
    codes = [group["code"] for group in GROUPS]
    if len(set(codes)) != len(codes):
        raise ValueError("коды групп повторяются")
    # Каждый тип FOUND входит хотя бы в одну отрасль, либо в ядро — иначе он
    # останется невидимым на странице.
    grouped = {label for group in GROUPS for label in group.get("found", ())}
    orphan = labels - grouped - set(CORE)
    if orphan:
        raise ValueError(f"типы вне отраслей и вне ядра: {sorted(orphan)}")
    covered_missing = {index for group in GROUPS for index in group.get("missing", ())}
    lost = set(range(1, len(MISSING) + 1)) - covered_missing
    if lost:
        raise ValueError(f"пункты «не находим» вне групп: {sorted(lost)}")


_check()


def ru_types(n: int) -> str:
    """Русское склонение слова «тип»: 1 тип, 2–4 типа, 5–20 типов, 21 тип…"""
    n %= 100
    if 11 <= n <= 14:
        return "типов"
    n %= 10
    if n == 1:
        return "тип"
    if 2 <= n <= 4:
        return "типа"
    return "типов"


