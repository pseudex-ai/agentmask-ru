"""Спрос на типы данных, которых мы пока не находим.

ЗАЧЕМ ЭТО ВООБЩЕ ЕСТЬ. `templates/legal/detection.html` дважды обещал
«напишите — это меняет очередь работ», и писать было некуда: адреса для связи
нет ни на одной странице сайта. ТЗ вертикалей §1 называет это достаточной
причиной само по себе: сегодня очередь работ строится из наших догадок, а
отметка на конфигураторе — это заявка на тип данных.

СТРОКИ О ПОСЕТИТЕЛЕ ЗДЕСЬ НЕ СУЩЕСТВУЕТ, И ЭТО ГЛАВНОЕ РЕШЕНИЕ. Хранится
счётчик на (сутки, группа) и ничего больше: ни адреса, ни отпечатка, ни
идентификатора сессии. Три причины, и третья решающая:

  утекать нечему — записи о человеке нет вовсе;
  сигнал переживает флуд, а он обязан: смысл таблицы в том, чтобы по ней
    строилась очередь работ, и очередь по спамеру хуже отсутствующей;
  троттлинг, за которым стоит эта ручка, СЛАБ ПО УСТРОЙСТВУ — `CACHES` в
    настройках не задан, значит `LocMemCache` на процесс, и при N воркерах
    лимит делится на N. Проектировать надо так, чтобы обойдённый лимит не
    убивал смысл, а не так, чтобы полагаться на лимит.
"""

from django.db import models


class DemandDay(models.Model):
    """Сколько раз за сутки отметили эту группу данных.

    Ключ по (сутки, группа): UPSERT вместо вставки, поэтому таблица растёт со
    скоростью «число групп в сутки», а не «число посетителей».
    """

    day = models.DateField()
    # Код группы из `storefront_web.detection_types.GROUPS`. Не FK и не choices
    # НАМЕРЕННО: список групп — продуктовый текст, он будет меняться, и миграция
    # на каждую правку формулировки — цена без выгоды. Неизвестный код отвергает
    # ВЬЮ, до записи, поэтому мусора здесь не появляется.
    group = models.CharField(max_length=32)
    count = models.PositiveIntegerField(default=0)

    class Meta:
        unique_together = ("day", "group")
        ordering = ("-day", "group")

    def __str__(self) -> str:
        return f"{self.day} {self.group} = {self.count}"


