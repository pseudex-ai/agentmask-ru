from django.apps import AppConfig


class OpsConfig(AppConfig):
    """Операторская консоль.

    БЕЗ ЕДИНОЙ МОДЕЛИ, и это не экономия: всё, что она показывает, уже есть —
    организации, подписки и счета в наших таблицах, лизы, ёмкость и цепи на
    лицензионном сервере. Своя таблица здесь означала бы ТРЕТЬЕ место, где
    живёт то же самое, и обязанность держать его в согласии с двумя первыми.
    Поэтому у приложения нет ни `models.py`, ни миграций.
    """

    name = "ops"
    verbose_name = "Операции"
