from django.apps import AppConfig


class OpsConfig(AppConfig):
    """Операторская консоль.

    ПОЧТИ БЕЗ МОДЕЛЕЙ, и это не экономия: всё, что консоль ПОКАЗЫВАЕТ, уже
    есть — организации, подписки и счета в наших таблицах, лизы, ёмкость и цепи
    на лицензионном сервере. Своя таблица для них означала бы ТРЕТЬЕ место, где
    живёт то же самое, и обязанность держать его в согласии с двумя первыми.

    Единственное исключение — `DemandDay`: спрос с конфигуратора не существует
    больше нигде, его негде взять, и поэтому он здесь. Правило не «моделей не
    заводим», а «не заводим ВТОРУЮ КОПИЮ того, что уже где-то есть».
    """

    name = "ops"
    verbose_name = "Операции"
