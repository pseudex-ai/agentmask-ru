"""Первопартийная аналитика: что считаем, чего НЕ храним и почему.

РЕШЕНИЕ И ЕГО ОСНОВАНИЕ

Считаем сами, на своей стороне, без куки и без единой строки чужого кода на
странице. Три причины, и третья — та, ради которой это вообще стоит строить.

  * СТОРОННЯЯ АНАЛИТИКА ЛОМАЕТ ПРОДУКТ. `settings.py` в шапке запрещает
    «аналитику, которая бьёт маячком со страницы, где сидит залогиненный
    клиент». Метрика на странице кабинета — это утечка того, кто наш клиент,
    третьей стороне, и мы её же продаём как то, чего у нас нет.
  * ТРАНСГРАНИЧНАЯ ПЕРЕДАЧА. Зарубежная аналитика в 2026 — активная область
    проверок РКН, а мы продаём отсутствие трансграничной передачи.
  * ВОРОНКА ПРОХОДИТ ЧЕРЕЗ ТРИ СИСТЕМЫ — лендинг, витрину и лицензионный
    сервер. «Зашёл → отправил форму → открыл письмо → поднял контейнер → взял
    первую аренду → заплатил» видно только изнутри. Ни одна внешняя аналитика
    не может связать визит с первой арендой контейнера, потому что вторая
    половина пути живёт в нашей базе. Это не «дешевле, чем Метрика» — это то,
    чего Метрика не умеет вовсе.

ИДЕНТИФИКАТОР: СОЛЁНЫЙ ХЕШ, IP НЕ ХРАНИТСЯ НИКОГДА

`sha256(соль_суток + хост + ip + user-agent)`, соль меняется и УНИЧТОЖАЕТСЯ
каждые сутки. Приём Plausible, и он выбран не из подражания: позиция по IP в РФ
противоречива (суды говорят «не ПД», Роскомнадзор — «может быть»), а наш
СОБСТВЕННЫЙ продукт числит IP-адрес среди типов персональных данных, которые
находит. Хранить IP и одновременно продавать его как ПД нельзя. Не храним —
вопрос не возникает.

Цена решения названа честно: без сквозного идентификатора нельзя посчитать
«новый против вернувшегося» и удержание. Для лендинга B2B это не потеря —
удержание меряется подписками, а не визитами.

ХРАНЕНИЕ: POSTGRES, СЫРЫЕ СОБЫТИЯ ПЛЮС СВЁРТКИ

ClickHouse здесь был бы из пушки по воробьям. Порог, за которым он начинает
выигрывать, — сотни миллионов строк; Umami живёт на Postgres и добавляет
почасовые свёртки ровно так же. Лендинг B2B даже при 10 000 визитов в сутки —
это 3,6 млн строк в год, то есть два порядка до порога.

Сырьё держим 90 суток и удаляем, свёртки — вечно: вопрос «сколько было в
марте» переживает сырьё, а вопрос «с какой страницы пришёл вот тот визит» — нет.
"""

from django.db import models
from django.utils import timezone


class Visit(models.Model):
    """Один просмотр страницы. Сырьё, живёт 90 суток.

    ЗАПИСИ О ЧЕЛОВЕКЕ ЗДЕСЬ НЕТ. Ни адреса, ни user-agent, ни куки — только
    суточный хеш, который завтра нельзя связать с сегодняшним, потому что соль
    уничтожена.
    """

    at = models.DateTimeField(default=timezone.now, db_index=True)
    # Суточный отпечаток посетителя. 16 hex-символов от sha256: коллизия на
    # 64 битах при сотнях тысяч визитов в сутки — величина, которой нет.
    visitor = models.CharField(max_length=16, db_index=True)
    path = models.CharField(max_length=200)
    # ОТКУДА ПРИШЁЛ — ТОЛЬКО ХОСТ, НЕ ПОЛНЫЙ АДРЕС. Полный реферер несёт
    # поисковый запрос, а запрос — это то, что человек искал, и в связке с
    # остальным он опознаёт. Хост отвечает на вопрос «какой канал работает» и
    # ничего не добавляет к опознанию.
    referrer_host = models.CharField(max_length=120, blank=True)
    utm_source = models.CharField(max_length=60, blank=True)
    utm_medium = models.CharField(max_length=60, blank=True)
    utm_campaign = models.CharField(max_length=60, blank=True)
    # ИДЕНТИФИКАТОР КЛИКА ПО ОБЪЯВЛЕНИЮ ДИРЕКТА. Приходит в адресе рекламного
    # перехода и хранится ровно те же сутки, что и связь визита с организацией:
    # дальше он не нужен и не воспроизводится.
    #
    # ЗАЧЕМ ОН, ЕСЛИ ЕСТЬ UTM. Метки говорят, ОТКУДА человек пришёл, и этого
    # хватает отчёту. Для конверсии нужно больше: Метрика принимает
    # офлайн-конверсию только с одним из идентификаторов — `ClientId` (это кука,
    # а мы их не ставим), `UserId` (наш собственный, которого мы не заводим) или
    # `Yclid`. Остаётся yclid, и он же единственный, который работает без куки.
    yclid = models.CharField(max_length=64, blank=True)
    # Категории, а не строка user-agent: «мобильный Chrome» отвечает на вопрос
    # «верстать ли под телефон», а полная строка — это отпечаток.
    device = models.CharField(max_length=12, blank=True)
    browser = models.CharField(max_length=20, blank=True)
    os = models.CharField(max_length=20, blank=True)
    # Страна по IP НЕ определяется: для этого нужна база геолокации и сам IP,
    # а IP мы не держим ни мгновения дольше, чем нужно для хеша.
    is_bot = models.BooleanField(default=False, db_index=True)

    class Meta:
        ordering = ["-at"]
        indexes = [
            models.Index(fields=["at", "is_bot"]),
            models.Index(fields=["referrer_host", "at"]),
        ]


class Funnel(models.Model):
    """Шаг воронки. ЭТО ГЛАВНАЯ ТАБЛИЦА, а не Visit.

    Просмотры страниц говорят, сколько людей пришло. Воронка говорит, где они
    отваливаются, — и только она отвечает на вопрос, который стоит денег.

    Шаги намеренно пересекают три системы: витрину, почту и лицензионный
    сервер. `container_first_lease` невозможно узнать из браузера вообще — это
    факт, который случается на чужом железе и доезжает до нас арендой.
    """

    LANDING = "landing"
    SIGNUP_SUBMITTED = "signup_submitted"
    SIGNUP_REFUSED = "signup_refused"
    ACTIVATED = "activated"
    KEY_ISSUED = "key_issued"
    FIRST_LEASE = "first_lease"
    FIRST_MASK = "first_mask"
    INVOICE_ISSUED = "invoice_issued"
    PAID = "paid"
    STEPS = [
        (LANDING, "зашёл на лендинг"),
        (SIGNUP_SUBMITTED, "отправил форму"),
        (SIGNUP_REFUSED, "форма отклонена"),
        (ACTIVATED, "подтвердил почту"),
        (KEY_ISSUED, "получил ключ"),
        (FIRST_LEASE, "поднял контейнер"),
        (FIRST_MASK, "первый замаскированный запрос"),
        (INVOICE_ISSUED, "получил счёт"),
        (PAID, "заплатил"),
    ]

    at = models.DateTimeField(default=timezone.now, db_index=True)
    step = models.CharField(max_length=24, db_index=True)
    # СВЯЗКА ВИЗИТА С ОРГАНИЗАЦИЕЙ ЖИВЁТ РОВНО ОДНИ СУТКИ, потому что суточный
    # хеш назавтра не воспроизводится. Этого достаточно: путь от лендинга до
    # ключа занимает минуты, а не дни. Хвост воронки после `key_issued`
    # связывается по организации, и там хеш уже не нужен.
    visitor = models.CharField(max_length=16, blank=True, db_index=True)
    organization_id = models.CharField(max_length=32, blank=True, db_index=True)
    # Что именно: код тарифа, причина отказа, номер счёта. Никогда не почта.
    detail = models.CharField(max_length=64, blank=True)

    class Meta:
        ordering = ["-at"]
        indexes = [models.Index(fields=["step", "at"])]


class VisitDay(models.Model):
    """Свёртка по суткам. Живёт вечно, сырьё — нет.

    Считается ночью из `Visit` и отвечает на вопросы, которые задают через год:
    сколько было в марте, какой канал рос. Разрез по одному измерению за
    строку — `dimension`/`value` — вместо таблицы на каждое измерение: разрезов
    будет больше, чем предусмотрено сейчас, и добавление нового не должно
    стоить миграции.
    """

    day = models.DateField(db_index=True)
    # "total" · "path" · "referrer" · "utm_source" · "device" · "browser"
    dimension = models.CharField(max_length=16)
    value = models.CharField(max_length=200, blank=True)
    visits = models.PositiveIntegerField(default=0)
    visitors = models.PositiveIntegerField(default=0)

    class Meta:
        ordering = ["-day"]
        unique_together = [("day", "dimension", "value")]


class UsageDay(models.Model):
    """Накопительный расход клиента на конец суток — наш собственный след.

    ЗАЧЕМ ОН, ЕСЛИ СЧЁТЧИК УЖЕ ЕСТЬ У ЛИЦЕНЗИОННОГО СЕРВЕРА. `usage.requests`
    МОНОТОНЕН — он никогда не уменьшается, и это правильно для счёта. Но
    ровно поэтому по нему НЕВОЗМОЖНО увидеть, что клиент перестал работать:
    платящий клиент, у которого трафик упал до нуля месяц назад, на экране
    флота выглядит в точности как работающий, потому что его накопленное число
    так и стоит большим. А замолчавший клиент — самый сильный сигнал оттока,
    какой вообще бывает, и он приходит за месяцы до отказа платить.

    ПОСУТОЧНАЯ ИСТОРИЯ У СЕРВЕРА ЕСТЬ, НО ПО ОДНОЙ ОРГАНИЗАЦИИ ЗА ЗАПРОС, и
    экран всего флота стоил бы N обращений под локом чужого хранилища. Здесь
    же снимок ничего не стоит: почасовой цикл и так спрашивает расход каждого
    живого клиента, чтобы предупредить о перерасходе, — строка пишется из уже
    полученного ответа.

    ХРАНИТСЯ НАКОПЛЕННОЕ, А НЕ ПРИРОСТ. Прирост выводится вычитанием соседних
    суток, а обратно — нет: пропущенные сутки (наша авария, остановленный
    контейнер) превратили бы ряд приростов в ложный ноль, неотличимый от
    настоящего молчания.
    """

    organization_id = models.CharField(max_length=32, db_index=True)
    day = models.DateField(db_index=True)
    requests = models.BigIntegerField(default=0)

    class Meta:
        # Одна строка на клиента в сутки: цикл идёт каждый час и обязан
        # переписывать сегодняшнюю, а не дописывать двадцать четыре.
        unique_together = [("organization_id", "day")]
        ordering = ["-day"]


class ConversionSent(models.Model):
    """Офлайн-конверсия, отправленная в Метрику. Одна на организацию и цель.

    ЗАЧЕМ ОТДЕЛЬНАЯ ТАБЛИЦА, А НЕ ФЛАГ НА ОРГАНИЗАЦИИ. `Funnel` отвечает на
    вопрос «что случилось», эта таблица — «что мы об этом рассказали наружу».
    Совпадать они не обязаны, и разница между ними и есть то, ради чего таблица
    существует: конверсия без yclid не привязывается ни к какому визиту,
    кампания могла кончиться, Метрика могла отказать. Один флаг «отправлено»
    стёр бы разницу между «мы не отправляли» и «мы отправили, а она не
    привязалась», а это два разных действия: первое чинится у нас, второе — в
    настройках рекламы.

    УНИКАЛЬНОСТЬ ПО ПАРЕ, А НЕ ПО ВРЕМЕНИ. Повторный запуск команды обязан
    ничего не отправить второй раз: конверсия, загруженная дважды, удваивает
    ценность цели и учит Директ на завышенной цифре. Поэтому повтор — не
    «пропустить похожее», а «второй строки не существует по устройству».
    """

    organization_id = models.CharField(max_length=32, db_index=True)
    target = models.CharField(max_length=64)
    at = models.DateTimeField(default=timezone.now, db_index=True)
    # Номер загрузки в Метрике и её статус. `LINKAGE_FAILURE` — не наша ошибка,
    # но знать о ней надо: значит идентификатор не совпал ни с одним визитом.
    uploading_id = models.BigIntegerField(default=0)
    status = models.CharField(max_length=24, blank=True)

    class Meta:
        ordering = ["-at"]
        unique_together = [("organization_id", "target")]
