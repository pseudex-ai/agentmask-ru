"""Приблизительный показ инстансов для экранов — СПРАВКА, а не принуждение.

Слот/поколение/эпоха/фенсинг удалены (docs/tz-license-volume-quota.md §A):
инстанс-счёт как ЛИМИТ убран — весь трафик через один прокси его обходит, а
детектор отказов нереализуем (Chandra–Toueg), и шесть заходов доказали это на
живых клиентах. Принуждение теперь объёмное (period-квота + абсолютный потолок
запросов, §B/§C). Осталась одна справка: сколько РАЗЛИЧНЫХ инстансов
лицензионный сервер видел в окне. Это ПОКАЗ, а не потолок.

ОДИН УРОК ПЕРЕЖИЛ УДАЛЕНИЕ СЛОТОВ: число, которого сервер не назвал, — НЕ ноль.
«0 инстансов» при живых арендах читается как ответ «ничего не работает». Поэтому
молчание доезжает как `None`, а экран пишет «неизвестно», а не рисует ноль.
"""


def _instances(payload: dict) -> int | None:
    """Приблизительное число инстансов в окне, или `None`, если сервер не назвал.

    Принимаются оба имени, под которыми сервер отдаёт счётчик: `instances` и
    `occupied`. `bool` исключён явно, а список (сырые строки аренд у
    `/admin/usage`) не проходит проверку на число — молчанием он и остаётся.
    """
    for key in ("instances", "occupied"):
        value = payload.get(key)
        if isinstance(value, bool) or not isinstance(value, (int, float)):
            continue
        return int(value)
    return None


def unknown() -> dict:
    """Лицензионный сервер не ответил: число инстансов НЕИЗВЕСТНО, а не ноль."""
    return {"known": False, "instances": None}


def describe(payload: dict, now: float) -> dict:
    """Ответ `/admin/instances` → приблизительный показ для экранов.

    `now` больше не участвует в вычислении (сроков и поколений нет), но параметр
    сохранён в сигнатуре, чтобы кабинет и консоль не переписывались одномоментно
    с этим модулем.
    """
    return {"known": True, "instances": _instances(payload)}
