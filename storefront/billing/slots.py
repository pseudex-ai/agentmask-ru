"""Слоты тарифа для экранов: занятость — ЧИСЛОМ, состояние — словом.

ПОЧЕМУ ЭТО ОТДЕЛЬНЫЙ МОДУЛЬ. Один и тот же ответ `/admin/instances` читают два
экрана с разными читателями — кабинет клиента и консоль поддержки, — и до сих
пор каждый из них выводил занятость сам: кабинет длиной списка
(`{{ instances|length }}`), консоль — зелёной плашкой на всём, что не
«остывает». Обе догадки стали враньём в один день, когда сервер начал отдавать
в том же списке контейнеры, которые слот НЕ держат (`silent`, `released`).
Занятость теперь считает лицензионный сервер — то есть та же функция, что
принимает решение об отказе, — а витрина обязана её ПОКАЗАТЬ, а не вывести
заново. Третьего мнения о том же контейнере больше нет нигде.

ЧТО ЗНАЧАТ СОСТОЯНИЯ (`licensing/store.py::active_instances`):

  * `active`    — признак жизни свежее `alive_seconds`: слот занят;
  * `silent`    — аренда не отпущена, но контейнер молчит: слот УЖЕ свободен,
                  и труп больше не показан работающим;
  * `released`  — контейнер отпустил слот сам (`/v1/release`);
  * `reclaimed` — место у молчащего ЗАБРАЛИ, чтобы пустить другой контейнер
                  (`released_by='silence'`). Для клиента это не то же самое,
                  что «вы его остановили»: его движок ещё работает, но на
                  следующем продлении получит 409 (Б26ter), и сказать ему об
                  этом обязан экран, а не поддержка по телефону.

ДВА ПРАВИЛА, КОТОРЫЕ ЗДЕСЬ НЕЛЬЗЯ НАРУШАТЬ, И ОБА КУПЛЕНЫ ДОРОГО:

1. **Плашка следует `occupies`, слово — `state`.** Экраны выводили занятость из
   НАЗВАНИЯ состояния (`state == 'active'` → зелёное «ДЕРЖИТ СЛОТ»), то есть
   заводили ровно то второе мнение, ради отмены которого сервер и начал
   отдавать `occupies`. Цена этого — состояние, которого шаблон не знает,
   молча красилось в «СЛОТ СВОБОДЕН»: так `reclaimed` читался бы как «вы сами
   остановили контейнер».
2. **Число, которого сервер не назвал, — не ноль.** `occupied` по умолчанию
   нулём и `live_processes` по умолчанию нулём — это и есть оба враньё
   вердикта: «контейнеры — 0 из 1 занято» при 128 живых арендах и
   «vol-one · процессов 0» у контейнера с тридцатью двумя воркерами. Ноль
   читается как ОТВЕТ, и человек делает из него вывод. Отсутствующее поле
   доезжает до экрана как `None`, и экран пишет «неизвестно».
"""


def ago(seconds: float) -> str:
    """Срок словами: «41 с», «12 мин», «3 ч».

    ТА ЖЕ ШКАЛА, ЧТО В ОТКАЗЕ. Строку «на связи 12 мин назад» клиент сперва
    видит в отказе своего контейнера (`licensing/store.py::ago`), а следом —
    в кабинете; разные округления в двух местах читались бы как разные данные.
    Шесть строк дублируются намеренно: витрина не имеет права импортировать
    движок, и общая библиотека ради форматирования завела бы эту зависимость.
    """
    seconds = max(0.0, seconds)
    if seconds < 90:
        return f"{int(seconds)} с"
    if seconds < 5400:
        return f"{int(seconds // 60)} мин"
    return f"{int(seconds // 3600)} ч"


def _number(raw: dict, key: str) -> int | None:
    """Целое поле сервера — или `None`, если сервер его не назвал.

    `raw.get(key, 0)` превращало молчание в число, и именно так на экран
    попадали «0 занято» и «процессов 0» про работающие контейнеры. Молчание
    обязано доезжать молчанием; решает, что с ним делать, экран.
    """
    value = raw.get(key)
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        return None
    return int(value)


def _state_of(raw: dict) -> str:
    """Имя состояния — СЕРВЕРНОЕ, и незнакомое остаётся собой.

    ОТОБРАННОЕ МЕСТО — НЕ ОСТАНОВЛЕННЫЙ КОНТЕЙНЕР. Сервер закрывает строку
    молчащего инстанса пометкой `released_by='silence'`, когда отдаёт его место
    другому (`store.reclaim_silent`), — то есть в одном и том же `released`
    лежат два разных события: «клиент ушёл сам» и «мы забрали». Клиенту это
    разные новости: в первом случае делать нечего, во втором его движок ещё
    работает и встанет на следующем продлении. Если сервер называет состояние
    сам (`reclaimed`), верим ему; иначе выводим по причине освобождения.
    """
    state = str(raw.get("state", "") or "")
    if state == "released" and str(raw.get("released_by", "") or "") == "silence":
        return "reclaimed"
    return state


_STATE_WORDS = {"active": "НА СВЯЗИ", "silent": "МОЛЧИТ",
                "released": "ОСТАНОВЛЕН", "reclaimed": "МЕСТО ОТОБРАНО"}
_SLOT_WORDS = {True: "ДЕРЖИТ СЛОТ", False: "СЛОТ СВОБОДЕН",
               None: "ЗАНЯТОСТЬ НЕИЗВЕСТНА"}


def _pill(state: str, holds: bool | None) -> str:
    """Плашка: что с контейнером и что с его слотом — двумя разными словами.

    ОДНА ПЛАШКА НА ОБА ЭКРАНА. Кабинет писал про отпущенный контейнер
    «ОСТАНОВЛЕН», консоль — «ОТПУЩЕН», и это два разных ответа на один вопрос
    сервера; поддержка и клиент смотрят на один контейнер и обязаны видеть одно
    слово. Аудитории различаются ОБЪЯСНЕНИЕМ рядом, а не именем состояния.
    """
    word = _STATE_WORDS.get(state)
    if word is None:
        # Состояние, которого витрина не знает, НАЗЫВАЕТСЯ, а не подводится под
        # знакомое: подводить — значит соврать в ту сторону, в какую подвели.
        word = f"СОСТОЯНИЕ «{state}»" if state else "СОСТОЯНИЕ НЕ НАЗВАНО"
    if state == "active" and holds is True:
        # Единственный случай, где два слова слились бы в «НА СВЯЗИ — ДЕРЖИТ
        # СЛОТ»: он и так читается одним.
        return _SLOT_WORDS[True]
    return f"{word} — {_SLOT_WORDS[holds]}"


def _pill_class(state: str, holds: bool | None) -> str:
    """Цвет — по слоту, а не по состоянию. Зелёное значит «место занято и это
    нормально»; «остановлен» — серое, потому что это сделал сам клиент; всё
    остальное, включая неизвестную занятость, — жёлтое: там есть о чём
    спросить."""
    if holds is True:
        return "ok"
    if holds is None:
        return "warn"
    return "" if state == "released" else "warn"


def _row(raw: dict, now: float, alive_seconds: float) -> dict:
    """Одна строка списка контейнеров, готовая к показу.

    `holds` берётся из `occupies` СЕРВЕРА, а не выводится из названия
    состояния: занятость считает одна функция, и вывести её второй раз здесь
    значило бы завести ровно то расхождение, которое чинится. Поля, которого
    нет, — это `None`, а не `False` и не ноль.
    """
    state = _state_of(raw)
    occupies = raw.get("occupies")
    holds = None if occupies is None else bool(occupies)
    last_seen = float(raw.get("last_seen", 0.0) or 0.0)
    free_at = raw.get("free_at")
    return {
        "instance_id": str(raw.get("instance_id", "")),
        "state": state,
        "holds": holds,
        "pill": _pill(state, holds),
        "pill_class": _pill_class(state, holds),
        "seen_ago": ago(now - last_seen) if last_seen else "",
        # СКОЛЬКО ОСТАЛОСЬ ДО САМОСТОЯТЕЛЬНОГО ОСВОБОЖДЕНИЯ — только там, где
        # сервер это назвал. Пустая строка значит «сказать нечего», и экран
        # обязан написать именно это, а не подставить ноль.
        "frees_in": ago(float(free_at) - now) if free_at else "",
        # РАБОЧИЕ ПРОЦЕССЫ. Потолок тарифа считается и по ним, и отказ «тариф
        # допускает 1 контейнер — это 32 рабочих процесса, сейчас живых 32»
        # клиент до сих пор не мог сверить ни с одним своим экраном.
        "live_processes": _number(raw, "live_processes"),
        # СЕРВЕР СКАЗАЛ «СЛОТ СВОБОДЕН» — И ТУТ ЖЕ, ЧТО СЛЫШАЛ ЭТОТ КОНТЕЙНЕР
        # МИНУТУ НАЗАД. Два его же поля противоречат друг другу (так выглядели
        # 128 живых аренд, показанных свободными), и экран обязан сказать об
        # этом, а не выбрать из них удобное.
        "heard_recently": bool(holds is False and last_seen and alive_seconds
                               and now - last_seen <= alive_seconds),
        "engine_version": str(raw.get("engine_version", "") or ""),
    }


def unknown() -> dict:
    """Лицензионный сервер не ответил: занятость НЕИЗВЕСТНА, а не ноль.

    Ноль на этом месте читается как «свободно всё» — то есть как ответ, — и
    именно из такого «ответа» человек делает вывод, что контейнеров у него нет.
    Молчание обязано выглядеть молчанием.
    """
    return {"known": False, "occupied": None, "alive_label": "", "rows": [],
            "turnover_last_hour": None, "turnover_budget": None}


def describe(payload: dict, now: float) -> dict:
    """Ответ `/admin/instances` → то, что рисуют оба экрана.

    `occupied` приходит с сервера числом. Витрина и лицензионный сервер едут
    ОДНИМ платформенным релизом (`platform/vX.Y.Z`), поэтому расхождения версий
    между ними не бывает и запасного счёта здесь нет: поле, которого нет, — это
    сломанный ответ, и показать по нему число значило бы угадать. Поэтому его
    отсутствие доезжает как `None` — «сервер не назвал», — а не как ноль,
    который читается как «свободно».
    """
    listed = payload.get("instances", [])
    if not isinstance(listed, list):
        listed = []
    alive_seconds = float(payload.get("alive_seconds", 0.0) or 0.0)
    return {
        "known": True,
        "occupied": _number(payload, "occupied"),
        # «Через 10 минут молчания» — это `alive_seconds` сервера, а не
        # константа в шаблоне: число настраивается переменной окружения, и
        # зашитое в текст оно соврало бы при первой же правке.
        "alive_label": ago(alive_seconds) if alive_seconds else "",
        "turnover_last_hour": _number(payload, "turnover_last_hour"),
        "turnover_budget": _number(payload, "turnover_budget"),
        "rows": [_row(raw, now, alive_seconds)
                 for raw in listed if isinstance(raw, dict)],
    }
