"""Сверка нашего счёта с собственным логом шлюза клиента.

`docs/billing-integrity.md` объясняет, почему единица тарификации — ЗАПРОС, а не
значение и не токен: «запрос виден в логе шлюза самого клиента. Значит наш счёт
можно сверить с его собственной записью, а спор о деньгах превращается в
сравнение двух независимых источников». До сих пор это обещание существовало
только текстом — сверять было нечем и негде.

МЫ ПРИНИМАЕМ ЧИСЛО, А НЕ ЛОГ, И ЭТО НЕ УПРОЩЕНИЕ. Загрузить сюда лог шлюза
значило бы принять файл, в котором лежат тела запросов, то есть ровно те
персональные данные, ради невыхода которых за периметр всё построено;
`docs/tz-site.md` §1 запрещает витрине даже экран, где такое видно. Клиент
считает свои строки у себя (`grep -c`, счётчик своего же дашборда) и называет
одно число. Число — не персональные данные, и оно ровно то, что нужно для
сравнения двух независимых источников.

В обратную сторону выгрузка идёт свободно: посуточный ряд НАШИХ чисел клиент
уносит и раскладывает по своим суткам сам. Экспорт нашего — не импорт чужого.
"""

from dataclasses import dataclass, field

# ЧТО НЕ СЧИТАЕТСЯ ЗАПРОСОМ, дословно по `docs/billing-integrity.md`. Это первая
# и самая частая причина расхождения: клиент грепает свой лог по всем обращениям
# к сайдкару, а платит только за успешно замаскированные.
NOT_BILLABLE = (
    "заблокированный запрос (маскирование fail-closed — до модели он не дошёл)",
    "отвергнутый валидацией",
    "/spans — он только читает и токенов не создаёт",
    "/unmask, /unmask_chunk, /unmask_arguments",
    "/reveal",
    "самопроверка (/selfcheck)",
)

MATCH = "match"
UNKNOWN_BAND = "unknown_band"
WITHIN_BAND = "within_band"
THEY_COUNTED_MORE = "they_counted_more"
WE_BILLED_MORE = "we_billed_more"


@dataclass(frozen=True)
class Reconciliation:
    """Итог сверки: два числа, полоса и объяснение разницы."""

    ours: int
    theirs: int
    band: int
    difference: int
    verdict: str
    reasons: list[str] = field(default_factory=list)
    chain_clean: bool = True

    @property
    def agrees(self) -> bool:
        """Сходится ли счёт в пределах, которые мы сами и объявили.

        `within_band` — это НЕ «почти сошлось», это «сошлось ровно настолько,
        насколько обещано»: погрешность `Q + R` объявлена в
        `docs/billing-integrity.md` как несущая, и попадание в неё есть
        выполнение обещания, а не его нарушение.
        """
        return self.verdict in (MATCH, WITHIN_BAND)


def band_width(quantum_max: int, reserve_max: int, processes: int = 1) -> int:
    """`процессов × (Q + R)` — на сколько счёт МОЖЕТ разойтись с расходом.

    Потолки берутся из строки тарифа, а не из воздуха: `issue_quantum` зажимает
    квант между `quantum_min` и `quantum_max`, а резерв — между квантом и
    `reserve_max`. Верхние границы дают худший случай, а именно он тут и нужен.

    УМНОЖЕНИЕ НА ЧИСЛО ПРОЦЕССОВ — НЕСУЩЕЕ, И БЕЗ НЕГО ПОЛОСА ВРЁТ В РАЗЫ.
    `LicenseStore.billable` считает `clamp(acked, granted − Q − R, granted)` НА
    КАЖДЫЙ ПРОЦЕСС и складывает: леджер ёмкости ключуется на ключ процесса,
    потому что это единственный идентификатор, который клиент не выбирает.
    Значит и погрешность складывается. Восьмиворкерный контейнер на «Старте»
    законно расходится на 8 × 22 000, а полоса в одну штуку объявила бы это
    «мы выставили больше, смотреть надо у нас» — то есть отправила бы искать
    несуществующий дефект на нашей стороне при исправной работе.
    """
    per_process = max(0, int(quantum_max or 0)) + max(0, int(reserve_max or 0))
    return per_process * max(1, int(processes or 1))


def reconcile(ours: int, theirs: int, quantum_max: int, reserve_max: int,
              processes: int = 1, reports_missing: int = 0, chain_breaks: int = 0,
              unverified_reports: int = 0, unacked_quanta: int = 0) -> Reconciliation:
    """Сравнить наш счёт за период с числом из лога шлюза клиента.

    `ours` — то, что мы выставляем (`capacity_billable` за период), `theirs` —
    сколько успешно замаскированных запросов клиент насчитал у себя.

    ПОРЯДОК ПРИЧИН — ПО ВЕРОЯТНОСТИ, А НЕ ПО ВАЖНОСТИ, и первой стоит наша
    собственная. Разошлось — сначала спрашиваем, не посчитал ли клиент лишнего,
    потому что это самая частая причина и проверяется за минуту; и только потом
    смотрим на цепь отчётов. Обратный порядок превращает каждую сверку в
    расследование там, где хватает одной строки.
    """
    ours, theirs = max(0, int(ours)), max(0, int(theirs))
    band = band_width(quantum_max, reserve_max, processes)
    difference = theirs - ours
    chain_clean = not (reports_missing or chain_breaks or unverified_reports
                       or unacked_quanta)

    if difference == 0:
        verdict = MATCH
    elif band <= 0:
        # ПОЛОСА НЕИЗВЕСТНА — ВЕРДИКТА НЕТ. Ноль здесь означает не «расходиться
        # нельзя», а «мы не знаем, на сколько можно»: у организации нет подписки,
        # либо её тариф лицензионному серверу неизвестен, либо ни один процесс
        # ещё не брал ёмкость. Выносить на этом «мы выставили больше, смотреть
        # надо у нас» — значит отправлять человека искать дефект по отсутствию
        # данных.
        verdict = UNKNOWN_BAND
    elif abs(difference) <= band:
        verdict = WITHIN_BAND
    elif difference > 0:
        verdict = THEY_COUNTED_MORE
    else:
        verdict = WE_BILLED_MORE

    reasons: list[str] = []
    if verdict == UNKNOWN_BAND:
        reasons.append(
            "Погрешность посчитать не из чего: у организации нет подписки, либо "
            "её тариф неизвестен лицензионному серверу, либо ни один процесс ещё "
            "не брал ёмкость. Пока полоса неизвестна, вердикт о расхождении "
            "выносить нельзя — сначала надо понять, по какому тарифу её считать."
        )
    if difference > 0 and verdict != UNKNOWN_BAND:
        reasons.append(
            "У клиента больше нашего. Чаще всего в его подсчёт попало то, что "
            "запросом не считается и не тарифицируется: "
            + "; ".join(NOT_BILLABLE) + "."
        )
    if not chain_clean and verdict != UNKNOWN_BAND:
        # ЭТО НЕ ОБВИНЕНИЕ, И ФОРМУЛИРОВКА ВАЖНА. Счёт идёт по ВЫДАННОЙ ёмкости,
        # а подтверждённый отчёт только уменьшает его до фактического расхода.
        # Значит порванная цепь означает «клиент отказался от скидки за
        # неиспользованное», а не «клиент нас обманул», — и разговор с ним
        # начинается с этого, а не с подозрения.
        reasons.append(
            f"Цепь отчётов не целая: продлений без отчёта {reports_missing}, "
            f"разрывов {chain_breaks}, неподписанных отчётов {unverified_reports}, "
            f"квантов без подтверждения {unacked_quanta}. Счёт при этом идёт по "
            f"выданной ёмкости, а подтверждённый отчёт только уменьшил бы его до "
            f"фактического расхода: разница здесь — это скидка, от которой "
            f"отказались, а не приписка."
        )
    if difference < 0 and chain_clean and verdict != UNKNOWN_BAND:
        # Единственный случай, где виноваты скорее мы. При целой цепи счёт равен
        # расходу с нулевой погрешностью — так измерено на трёх масштабах.
        reasons.append(
            "Мы выставили больше, чем клиент насчитал, при ЦЕЛОЙ цепи отчётов. "
            "Так быть не должно: при доходящих отчётах счёт равен расходу. "
            "Это наша сторона — смотреть надо у нас, а не у клиента."
        )
    if verdict == WITHIN_BAND and chain_clean:
        reasons.append(
            f"Расхождение укладывается в объявленную погрешность Q + R = {band} "
            f"запросов и ничего не требует."
        )
    return Reconciliation(ours=ours, theirs=theirs, band=band,
                          difference=difference, verdict=verdict,
                          reasons=reasons, chain_clean=chain_clean)


def daily_rows(history: list[dict]) -> list[dict]:
    """Посуточный ряд для выгрузки: накопленное и прирост.

    Ровно то, что уносит клиент, чтобы разложить наши числа по своим суткам.
    Первая точка окна прироста не имеет — предшественника в выборке нет, — и
    честно отдаётся пустой, а не пожизненным итогом.
    """
    rows, previous = [], None
    for point in history:
        requests = int(point.get("requests", 0) or 0)
        rows.append({
            "day": point.get("day", ""),
            "requests_total": requests,
            "requests_delta": "" if previous is None else max(0, requests - previous),
            "values_total": int(point.get("values", 0) or 0),
            "reports": int(point.get("reports", 0) or 0),
            "instances": int(point.get("instances", 0) or 0),
        })
        previous = requests
    return rows
